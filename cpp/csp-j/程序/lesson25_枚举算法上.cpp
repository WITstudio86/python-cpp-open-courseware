#include <iostream>
#include <cmath>
using namespace std;

// ============================================================
// 演示 1：水仙花数（Narcissistic Number）
//
// 定义：一个 n 位数，其各位数字的 n 次方之和等于该数本身。
//       例如 153 = 1^3 + 5^3 + 3^3，所以 153 是三位水仙花数。
//
// 本演示找出所有三位水仙花数（100 ~ 999）。
// ============================================================

/**
 * @brief 判断一个三位数是否为水仙花数
 *
 * 算法步骤：
 *   1. 提取百位数字 a = num / 100
 *   2. 提取十位数字 b = (num / 10) % 10
 *   3. 提取个位数字 c = num % 10
 *   4. 检查 a^3 + b^3 + c^3 == num
 *
 * @param num  一个三位整数（100 ~ 999）
 * @return     true 如果是水仙花数，否则 false
 */
bool isNarcissistic(int num) {
    int a = num / 100;          // 百位：整除 100
    int b = (num / 10) % 10;    // 十位：先整除 10 再取余
    int c = num % 10;           // 个位：直接取余
    // 判断各位立方和是否等于原数
    return (a * a * a + b * b * b + c * c * c == num);
}

/**
 * @brief 演示水仙花数的枚举查找
 *
 * 枚举范围：100 ~ 999（所有三位数）
 * 对每个数调用 isNarcissistic 检查，找到则输出。
 */
void demoNarcissistic() {
    cout << "【演示1】所有三位水仙花数：" << endl;
    int count = 0;  // 计数器：统计找到了几个水仙花数
    for (int num = 100; num <= 999; num++) {
        if (isNarcissistic(num)) {
            // 输出并分解给用户看
            int a = num / 100;
            int b = (num / 10) % 10;
            int c = num % 10;
            cout << "  " << num << " = " << a << "^3 + " << b << "^3 + " << c << "^3"
                 << " = " << a * a * a << " + " << b * b * b << " + " << c * c * c << endl;
            count++;
        }
    }
    cout << "共有 " << count << " 个三位水仙花数。" << endl;
    cout << endl;
}

// ============================================================
// 演示 2：百钱百鸡问题（Hundred Fowls Problem）
//
// 经典问题：公鸡 5 钱一只，母鸡 3 钱一只，小鸡 1 钱三只。
// 用 100 钱恰好买 100 只鸡，问公鸡、母鸡、小鸡各几只？
//
// 设公鸡 x 只、母鸡 y 只、小鸡 z 只，则：
//   x + y + z = 100        （只数约束）
//   5x + 3y + z/3 = 100    （金额约束，z 必须是 3 的倍数）
// ============================================================

/**
 * @brief 百钱百鸡 - 朴素三层循环版本
 *
 * 直接枚举 x（公鸡0~100）、y（母鸡0~100）、z（小鸡0~100），
 * 检查两个方程是否同时满足。
 *
 * 时间复杂度：O(n^3)，这里 n ≈ 100，约 100 万次循环。
 * 虽然 100^3 = 1,000,000 在现代计算机上很快，
 * 但当范围更大时三层循环会急剧膨胀，需要优化。
 */
void demoHundredChickensNaive() {
    cout << "【演示2-a】百钱百鸡 —— 朴素三层循环：" << endl;
    int solutionCount = 0; // 解的个数
    for (int x = 0; x <= 100; x++) {           // 枚举公鸡数量
        for (int y = 0; y <= 100; y++) {       // 枚举母鸡数量
            for (int z = 0; z <= 100; z++) {   // 枚举小鸡数量
                // 检查两个约束条件
                if (x + y + z == 100 &&                 // 共 100 只
                    5 * x + 3 * y + z / 3 == 100 &&     // 共 100 钱
                    z % 3 == 0) {                       // 小鸡数必须是3的倍数
                    cout << "  解" << (++solutionCount) << ": 公鸡 "
                         << x << "只, 母鸡 " << y << "只, 小鸡 " << z << "只" << endl;
                }
            }
        }
    }
    cout << "  共 " << solutionCount << " 组解。" << endl;
    cout << endl;
}

/**
 * @brief 百钱百鸡 - 优化两层循环版本
 *
 * 优化思路：
 *   1. 由 x + y + z = 100 可得 z = 100 - x - y，无需再枚举 z。
 *   2. 公鸡最多买 100/5 = 20 只，母鸡最多买 100/3 ≈ 33 只。
 *      缩小 x 和 y 的枚举范围。
 *
 * 时间复杂度：O(n^2)，约 20 × 33 ≈ 660 次循环 —— 比朴素版本快了上千倍。
 */
void demoHundredChickensOptimized() {
    cout << "【演示2-b】百钱百鸡 —— 优化两层循环：" << endl;
    cout << "  优化1: 小鸡 z = 100 - x - y（省掉一层循环）" << endl;
    cout << "  优化2: 公鸡最多20只，母鸡最多33只（缩小范围）" << endl;
    cout << endl;

    int solutionCount = 0;
    // 公鸡最多 100/5 = 20 只
    for (int x = 0; x <= 20; x++) {
        // 母鸡最多 100/3 ≈ 33 只
        for (int y = 0; y <= 33; y++) {
            int z = 100 - x - y;  // 小鸡数量由只数约束直接算出
            // 只需检查金额约束和小鸡数量的整除条件
            if (z >= 0 &&                          // z 必须非负
                z % 3 == 0 &&                      // 小鸡数必须是3的倍数
                5 * x + 3 * y + z / 3 == 100) {    // 金额约束
                cout << "  解" << (++solutionCount) << ": 公鸡 "
                     << x << "只, 母鸡 " << y << "只, 小鸡 " << z << "只" << endl;
            }
        }
    }
    cout << "  共 " << solutionCount << " 组解。" << endl;
    cout << endl;
}

// ============================================================
// 演示 3：数字统计（Digit Counting）
//
// 问题描述：统计从 1 到 N 的所有整数中，数字 x（0~9）出现的总次数。
// 例如 N=12, x=1：数字 1 出现在 1、10、11、12 中，
//   共出现 5 次（1×1, 10×1, 11×2, 12×1）。
//
// 方法：枚举每个数，逐位拆解并计数。
// ============================================================

/**
 * @brief 统计一个整数 num 中数字 digit 出现的次数
 *
 * 算法：不断对 num 取个位（%10），判断是否等于 digit，
 *       然后去掉个位（/10），直到 num 变为 0。
 *
 * @param num    要检查的整数
 * @param digit  要统计的数字（0~9）
 * @return       digit 在 num 中出现的次数
 */
int countDigitInNumber(int num, int digit) {
    int count = 0;          // 该数中 digit 出现的次数
    while (num > 0) {
        if (num % 10 == digit) {  // 当前个位是 digit 吗？
            count++;
        }
        num /= 10;                // 去掉个位，处理下一位
    }
    return count;
}

/**
 * @brief 统计 1 ~ N 中数字 digit 出现的总次数
 *
 * 算法：枚举 1 到 N 的每个整数 i，
 *       对每个 i 调用 countDigitInNumber 统计 digit 出现次数并累加。
 *
 * 时间复杂度：O(N * log₁₀N)，对 N 较大的场景（如 N > 10^6）需用数位 DP 优化，
 *             但 CSP-J 初赛中枚举法通常足够。
 *
 * @param N      上限（包含 N）
 * @param digit  要统计的数字（0~9）
 * @return       1~N 中 digit 出现的总次数
 */
int countDigitRange(int N, int digit) {
    int total = 0;               // 总出现次数
    for (int i = 1; i <= N; i++) {
        total += countDigitInNumber(i, digit);
    }
    return total;
}

/**
 * @brief 演示数字统计
 */
void demoDigitCount() {
    cout << "【演示3】数字统计（1 ~ N 中数字 x 出现的次数）：" << endl;

    // 示例 1：小范围
    int N1 = 12, x1 = 1;
    int result1 = countDigitRange(N1, x1);
    cout << "  示例1: N=" << N1 << ", 数字=" << x1
         << " → 出现 " << result1 << " 次" << endl;
    // 手动验证：1, 10, 11(两次), 12 → 共5次
    cout << "    验证: 1→1次, 10→1次, 11→2次, 12→1次 = 5次" << endl;

    // 示例 2：统计 1~100 中数字 0 出现的次数
    int N2 = 100, x2 = 0;
    int result2 = countDigitRange(N2, x2);
    cout << "  示例2: N=" << N2 << ", 数字=" << x2
         << " → 出现 " << result2 << " 次" << endl;
    // 10,20,...,90,100 → 11次

    // 示例 3：可交互式（使用固定示例）
    int N3 = 1000, x3 = 9;
    int result3 = countDigitRange(N3, x3);
    cout << "  示例3: N=" << N3 << ", 数字=" << x3
         << " → 出现 " << result3 << " 次" << endl;

    cout << endl;
}

