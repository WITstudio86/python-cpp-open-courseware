/*
 * =============================================
 * C++趣味学习 —— 第15课：多岔路口——else if
 * 知识点：多分支选择、条件顺序
 * 趣味项目：🎪 成绩等级评定系统
 * 阶段：第三单元——选择与决策
 * =============================================
 */

#include <iostream>
using namespace std;

int main() {

    // ==========================================
    // 示例1：成绩等级评定系统
    // 功能：根据分数输出对应的等级评语
    // 重点：条件从高到低排列，否则判断会出错！
    // ==========================================
    cout << "========== 示例1：成绩等级评定系统 ==========" << endl;
    {
        int score = 85;  // 可以修改这个分数测试不同结果

        cout << "你的考试分数是：" << score << " 分" << endl;
        cout << "评定结果：";

        // ✅ 正确写法：从高到低排列条件
        //    如果顺序反了（比如>=60放最前面），95分也会被判为D！
        //    原因：只要满足>=60就执行，后面的>=90永远不会被检查
        if (score >= 90) {
            cout << "A（优秀）🎉 太厉害了！继续保持！" << endl;
        } else if (score >= 80) {
            cout << "B（良好）💪 不错！再冲一冲就能拿A！" << endl;
        } else if (score >= 70) {
            cout << "C（中等）📚 还有进步空间，加油！" << endl;
        } else if (score >= 60) {
            cout << "D（及格）✏️ 刚过线，下次争取更好！" << endl;
        } else {
            cout << "E（需要努力）📖 别灰心，找到弱点多练习！" << endl;
        }
    }
    cout << endl;
    cout << endl;

    // ==========================================
    // 示例2：根据月份判断季节
    // 功能：输入1-12的数字，输出对应的季节
    // 重点：使用逻辑运算符 && 和 || 精确限定范围
    // ==========================================
    cout << "========== 示例2：季节判断器 ==========" << endl;
    {
        int month = 7;  // 可以修改这个月份测试不同结果

        cout << "当前月份：" << month << " 月" << endl;

        // 方法：使用 && 逻辑与，让条件精确落在范围内
        // 3-5月是春天，6-8月是夏天，9-11月是秋天，12-2月是冬天
        if (month >= 3 && month <= 5) {
            cout << "🌸 现在是【春天】—— 春暖花开，万物复苏！" << endl;
        } else if (month >= 6 && month <= 8) {
            cout << "☀️ 现在是【夏天】—— 烈日炎炎，吃西瓜咯！" << endl;
        } else if (month >= 9 && month <= 11) {
            cout << "🍁 现在是【秋天】—— 秋高气爽，丰收的季节！" << endl;
        } else if (month == 12 || month == 1 || month == 2) {
            // 注意：冬天横跨12月到次年2月，用 || 逻辑或连接
            cout << "❄️ 现在是【冬天】—— 雪花飘飘，堆雪人啦！" << endl;
        } else {
            cout << "⚠️ 月份输入错误！请输入1-12之间的数字。" << endl;
        }
    }
    cout << endl;
    cout << endl;

    // ==========================================
    // 示例3：简易计算器
    // 功能：输入两个数和运算符，输出计算结果
    // 重点：多个else if判断不同运算符，并特殊处理除数为0的情况
    // ==========================================
    cout << "========== 示例3：简易计算器 ==========" << endl;
    {
        // 预设测试数据（实际应用中可以用cin让用户输入）
        double num1 = 15;
        double num2 = 4;
        char op = '/';  // 可以改为 '+', '-', '*', '/' 测试

        cout << "计算算式：" << num1 << " " << op << " " << num2 << endl;
        cout << "计算结果：";

        if (op == '+') {
            cout << num1 << " + " << num2 << " = " << num1 + num2 << endl;
        } else if (op == '-') {
            cout << num1 << " - " << num2 << " = " << num1 - num2 << endl;
        } else if (op == '*') {
            cout << num1 << " * " << num2 << " = " << num1 * num2 << endl;
        } else if (op == '/') {
            // 重点：除法要检查除数是否为0！
            // 在数学中，除以0是没有意义的
            if (num2 == 0) {
                cout << "❌ 错误：除数不能为0！" << endl;
            } else {
                cout << num1 << " / " << num2 << " = " << num1 / num2 << endl;
            }
        } else {
            cout << "❌ 错误：不支持的运算符 '" << op << "'！" << endl;
            cout << "   请使用 +、-、*、/ 中的一个。" << endl;
        }
    }
    cout << endl;
    cout << endl;

    // ==========================================
    // 示例4：条件顺序的重要性 —— 错误演示
    // 这段代码演示了"条件顺序写反"会带来的问题
    // ==========================================
    cout << "========== 示例4：条件顺序错误演示 ==========" << endl;
    {
        int score = 95;

        cout << "你的分数是：" << score << endl;
        cout << endl;

        // ❌ 错误写法 —— 条件从低到高排列
        cout << "--- 错误写法（从低到高）---" << endl;
        if (score >= 60) {
            cout << "等级：D（及格）" << endl;
        } else if (score >= 70) {
            cout << "等级：C（中等）" << endl;
        } else if (score >= 80) {
            cout << "等级：B（良好）" << endl;
        } else if (score >= 90) {
            cout << "等级：A（优秀）" << endl;
        } else {
            cout << "等级：E（需要努力）" << endl;
        }
        cout << "⚠️ 看！95分被错误地判定为\"及格\"！" << endl;
        cout << "   因为 >=60 的条件第一个被满足，后面全被跳过了！" << endl;

        cout << endl;

        // ✅ 正确写法 —— 条件从高到低排列
        cout << "--- 正确写法（从高到低）---" << endl;
        if (score >= 90) {
            cout << "等级：A（优秀）" << endl;
        } else if (score >= 80) {
            cout << "等级：B（良好）" << endl;
        } else if (score >= 70) {
            cout << "等级：C（中等）" << endl;
        } else if (score >= 60) {
            cout << "等级：D（及格）" << endl;
        } else {
            cout << "等级：E（需要努力）" << endl;
        }
        cout << "✅ 这次对了！95分正确判定为\"优秀\"！" << endl;
    }
    cout << endl;
    cout << endl;

    // ==========================================
    // 练习1答案：成绩等级评定程序（A-E制）
    // 要求：90-100→A，80-89→B，70-79→C，60-69→D，60以下→E
    // ==========================================
    cout << "========== 练习1答案：A-E成绩等级 ==========" << endl;
    {
        int score = 88;
        cout << "分数：" << score << " → 等级：";

        if (score >= 90 && score <= 100) {
            cout << "A" << endl;
        } else if (score >= 80) {
            // 注意：能走到这里说明 score < 90 已经在上面的条件被排除了
            cout << "B" << endl;
        } else if (score >= 70) {
            cout << "C" << endl;
        } else if (score >= 60) {
            cout << "D" << endl;
        } else if (score >= 0) {
            cout << "E" << endl;
        } else {
            cout << "分数无效！" << endl;
        }
    }
    cout << endl;
    cout << endl;

    // ==========================================
    // 练习2答案：季节判断器
    // 要求：输入月份，输出季节
    // ==========================================
    cout << "========== 练习2答案：季节判断器 ==========" << endl;
    {
        int month = 10;
        cout << "月份：" << month << " → 季节：";

        if (month < 1 || month > 12) {
            cout << "输入错误！请输入1-12。" << endl;
        } else if (month >= 3 && month <= 5) {
            cout << "春季 🌸" << endl;
        } else if (month >= 6 && month <= 8) {
            cout << "夏季 ☀️" << endl;
        } else if (month >= 9 && month <= 11) {
            cout << "秋季 🍁" << endl;
        } else {
            // 剩下的是12、1、2月
            cout << "冬季 ❄️" << endl;
        }
    }
    cout << endl;
    cout << endl;

    // ==========================================
    // 练习3分析：条件顺序问题
    // 问题代码：if (score >= 60) ... else if (score >= 90) ...
    // 分析：因为 >=60 写在前面，而 >=60 包含 >=90 的所有分数，
    //       所以 >=90 的条件永远不会被执行到！
    // 修正：把范围小的条件（>=90）放在前面，范围大的（>=60）放在后面
    // ==========================================
    cout << "========== 练习3分析：条件顺序问题 ==========" << endl;
    cout << "问题代码：" << endl;
    cout << "  if (score >= 60) cout << \"及格\";" << endl;
    cout << "  else if (score >= 90) cout << \"优秀\";" << endl;
    cout << endl;
    cout << "错误原因：" << endl;
    cout << "  score >= 60 的\"范围\"包含了 >=90 的所有分数，" << endl;
    cout << "  所以后面的 >=90 条件永远不会被检查到！" << endl;
    cout << endl;
    cout << "正确写法：把 >=90 放在前面，>=60 放在后面。" << endl;
    cout << endl;
    cout << endl;

    // ==========================================
    // 挑战任务：万能简易计算器（交互版）
    // 功能：用户输入两个数和运算符，计算结果
    // 注意：除数为0的特殊处理
    // ==========================================
    cout << "========== 挑战任务：万能简易计算器 ==========" << endl;
    {
        double a, b;
        char op;

        cout << "🎪 欢迎使用万能简易计算器！" << endl;
        cout << "支持运算：加法(+)、减法(-)、乘法(*)、除法(/)" << endl;
        cout << endl;

        cout << "请输入第一个数字：";
        cin >> a;
        cout << "请输入运算符（+ - * /）：";
        cin >> op;
        cout << "请输入第二个数字：";
        cin >> b;

        cout << endl;
        cout << "===== 计算结果 =====" << endl;
        cout << a << " " << op << " " << b << " = ";

        if (op == '+') {
            cout << a + b << endl;
        } else if (op == '-') {
            cout << a - b << endl;
        } else if (op == '*') {
            cout << a * b << endl;
        } else if (op == '/') {
            if (b == 0) {
                cout << "❌ 错误：除数不能为0！在数学里，除以0是没有意义的哦！" << endl;
            } else {
                cout << a / b << endl;
            }
        } else {
            cout << "❌ 不支持的运算符 '" << op << "'！请输入 +、-、* 或 /。" << endl;
        }

        cout << endl;
        cout << "感谢使用计算器，再见！👋" << endl;
    }
    cout << endl;

    // ==========================================
    // 程序结束
    // ==========================================
    cout << "========== 第15课学习完毕 ==========" << endl;
    cout << "核心要点：" << endl;
    cout << "  1. if-else if-else 可以处理多个分支" << endl;
    cout << "  2. 条件要从\"最特殊\"到\"最一般\"排列" << endl;
    cout << "  3. 一旦某个条件成立，后面的条件不再检查" << endl;
    cout << "  4. 最后的else是\"兜底\"，处理所有剩余情况" << endl;

    return 0;
}

/*
 * =============================================
 * 本课知识点总结：
 *
 * 1. 多分支结构语法：
 *    if (条件1) {
 *        // 条件1成立
 *    } else if (条件2) {
 *        // 条件1不成立，条件2成立
 *    } else {
 *        // 所有条件都不成立（兜底）
 *    }
 *
 * 2. 条件顺序黄金法则：
 *    从"最特殊"到"最一般"排列
 *    ↓ 范围最小，条件最严格
 *    ↓ 范围较大
 *    ↓ 范围最大/兜底
 *
 * 3. 常见错误：
 *    - 条件顺序反了，导致后面的条件永远不会执行
 *    - 忘记最后的else做兜底处理
 *    - 在除法中没有检查除数是否为0
 *
 * 4. 与逻辑运算符配合：
 *    && (逻辑与)：两个条件都成立才行
 *    || (逻辑或)：两个条件有一个成立就行
 *
 * =============================================
 */
