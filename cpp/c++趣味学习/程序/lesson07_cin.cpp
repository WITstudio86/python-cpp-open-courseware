/*
 * ==========================================
 *  第07课：电脑的问答机——cin输入
 *  知识点：cin输入、交互式程序、用户输入处理
 *  C++趣味学习系列
 * ==========================================
 *
 *  程序说明：
 *  cin = 电脑的"耳朵"，用来接收键盘输入。
 *  本程序展示如何编写交互式程序，让电脑和用户"对话"！
 *  包含多个实用示例和智能问答机器人的完整实现。
 *
 *  运行提示：
 *  运行这个程序时，当看到提示信息后，
 *  在键盘上输入你的回答，然后按回车键。
 */

#include <iostream>
#include <string>
using namespace std;

int main() {
    // =====================================
    // 示例1：最简单的cin用法
    // =====================================
    cout << "========== 示例1：cin基本用法 ==========" << endl;
    cout << "cin是电脑的'耳朵'，用来接收键盘输入。" << endl;
    cout << "箭头 >> 指向变量，表示数据流入变量。" << endl;
    cout << endl;

    string name1;
    cout << "请输入你的名字：";
    cin >> name1;  // 程序会停下来等你输入！
    cout << "你好，" << name1 << "！欢迎来到C++世界！" << endl;
    cout << endl;

    // =====================================
    // 示例2：输入不同类型的数据
    // =====================================
    cout << "========== 示例2：不同类型输入 ==========" << endl;

    int age2;
    cout << "请输入你的年龄：";
    cin >> age2;  // cin知道要读整数
    cout << "你今年" << age2 << "岁。" << endl;

    double height;
    cout << "请输入你的身高（米）：";
    cin >> height;  // cin知道要读小数
    cout << "你的身高是" << height << "米。" << endl;

    cout << "你的名字（再输入一次）：";
    cin >> name1;  // 字符串（但不能有空格）
    cout << "好的，" << name1 << "！" << endl;
    cout << endl;

    // =====================================
    // 示例3：简易加法计算器
    // =====================================
    cout << "========== 示例3：简易计算器 ==========" << endl;

    int num1, num2;
    cout << "===== 加法计算器 =====" << endl;
    cout << "请输入第一个数字：";
    cin >> num1;
    cout << "请输入第二个数字：";
    cin >> num2;

    int sum = num1 + num2;
    cout << num1 << " + " << num2 << " = " << sum << endl;
    cout << endl;

    // =====================================
    // 示例4：链式输入
    // =====================================
    cout << "========== 示例4：链式输入 ==========" << endl;
    cout << "可以一次输入两个数（用空格分开）：" << endl;

    int a, b;
    cout << "请输入两个数字：";
    cin >> a >> b;  // 链式输入！可以在一行输入，空格分隔
    cout << "a = " << a << ", b = " << b << endl;
    cout << "a + b = " << a + b << endl;
    cout << "a × b = " << a * b << endl;
    cout << endl;

    // =====================================
    // 示例5：猜数字游戏（简单版）
    // =====================================
    cout << "========== 示例5：猜数字游戏 ==========" << endl;

    int secretNumber = 7;  // 秘密数字（以后可以改成随机数）
    int guess;

    cout << "我心里想了一个1到10之间的数字..." << endl;
    cout << "你猜是多少？请输入：";
    cin >> guess;

    cout << "你猜的是" << guess << "，正确答案是" << secretNumber << "。" << endl;
    if (guess == secretNumber) {
        cout << "🎉 恭喜你，猜对了！你太厉害了！" << endl;
    } else {
        cout << "😅 很遗憾，猜错了。答案是" << secretNumber << "哦！" << endl;
        if (guess < secretNumber) {
            cout << "   提示：你猜的偏小了。" << endl;
        } else {
            cout << "   提示：你猜的偏大了。" << endl;
        }
    }
    cout << endl;

    // =====================================
    // 示例6：餐厅点餐机
    // =====================================
    cout << "========== 示例6：餐厅点餐机 ==========" << endl;

    string foodName;
    int quantity;
    const int unitPrice = 15;  // 每份15元（const表示不可改变）

    cout << "===== 欢迎光临！ =====" << endl;
    cout << "今日菜品价格：" << unitPrice << "元/份" << endl;
    cout << endl;
    cout << "请输入你想点的菜品：";
    cin >> foodName;
    cout << "请输入数量：";
    cin >> quantity;

    int totalPrice = unitPrice * quantity;
    cout << endl;
    cout << "===== 您的订单 =====" << endl;
    cout << "  菜品：" << foodName << endl;
    cout << "  单价：" << unitPrice << "元" << endl;
    cout << "  数量：" << quantity << "份" << endl;
    cout << "  总价：" << totalPrice << "元" << endl;
    cout << "  谢谢惠顾！" << endl;
    cout << endl;

    // =====================================
    // 练习2参考答案：年龄计算器
    // =====================================
    cout << "========== 练习2答案：年龄计算器 ==========" << endl;

    int birthYear;
    cout << "请输入你的出生年份：";
    cin >> birthYear;

    int calculatedAge = 2026 - birthYear;
    cout << "现在是2026年，你出生在" << birthYear << "年。" << endl;
    cout << "你今年大约" << calculatedAge << "岁。" << endl;
    if (calculatedAge >= 7 && calculatedAge <= 15) {
        cout << "正是学习编程的黄金年龄！" << endl;
    }
    cout << endl;

    // =====================================
    // 挑战任务：智能问答机器人
    // =====================================
    cout << "========== 挑战任务：智能问答机器人 ==========" << endl;

    // 声明变量来存储用户的回答
    string userName;
    int userAge;
    string hobby;
    string favoriteFood;
    string dream;

    // 机器人登场
    cout << "🤖 ================================ 🤖" << endl;
    cout << "         智能问答机器人——小Q" << endl;
    cout << "🤖 ================================ 🤖" << endl;
    cout << endl;
    cout << "小Q：你好！我是小Q，很高兴认识你！" << endl;
    cout << endl;

    // 问题1：名字
    cout << "小Q：请问你叫什么名字？" << endl;
    cout << "回答：";
    cin >> userName;

    // 问题2：年龄
    cout << "小Q：" << userName << "，真是个好听的名字！你今年几岁啦？" << endl;
    cout << "回答：";
    cin >> userAge;

    // 问题3：爱好
    cout << "小Q：" << userAge << "岁正是充满活力的年纪！你的爱好是什么？" << endl;
    cout << "回答：";
    cin >> hobby;

    // 问题4：喜欢的食物
    cout << "小Q：哇，" << hobby << "听起来很有趣！你最喜欢吃什么？" << endl;
    cout << "回答：";
    cin >> favoriteFood;

    // 问题5：梦想
    cout << "小Q：最后一个问题——你的梦想是什么？" << endl;
    cout << "回答：";
    cin >> dream;

    // 输出总结
    cout << endl;
    cout << "🌟 ================================ 🌟" << endl;
    cout << "            你的个人档案" << endl;
    cout << "🌟 ================================ 🌟" << endl;
    cout << endl;
    cout << "  姓名：" << userName << endl;
    cout << "  年龄：" << userAge << "岁" << endl;
    cout << "  爱好：" << hobby << endl;
    cout << "  最喜欢的食物：" << favoriteFood << endl;
    cout << "  梦想：" << dream << endl;
    cout << endl;
    cout << "🌟 ================================ 🌟" << endl;
    cout << endl;
    cout << "小Q：太棒了！记住你的梦想——" << dream << "！" << endl;
    cout << "小Q：相信你一定可以实现！我们下次再见！👋" << endl;
    cout << endl;

    // =====================================
    // 程序结束
    // =====================================
    cout << "========== 程序结束 ==========" << endl;
    cout << "今天学会了cin输入，现在程序可以和你对话了！" << endl;
    cout << "你还能想到什么有趣的交互式程序呢？" << endl;

    return 0;
}

/*
 * ==========================================
 *  本课核心内容总结：
 *
 *  1. cin = 电脑的"耳朵"，接收键盘输入
 *  2. cin >> 变量 —— 把用户输入存进变量
 *  3. cout << 和 cin >> 箭头方向相反
 *     - cout << : 数据流向屏幕
 *     - cin >>  : 数据从键盘流入
 *  4. cin >> 可以读取不同类型：int, double, string 等
 *  5. cin 遇到空格会停止读取（字符串）
 *  6. 链式输入：cin >> a >> b;
 *
 *  cout 和 cin 对比：
 *  ┌──────────┬──────────────┬──────────────┐
 *  │          │    cout      │     cin      │
 *  ├──────────┼──────────────┼──────────────┤
 *  │  全称    │ char output  │ char input   │
 *  │  方向    │ 电脑 → 屏幕  │ 键盘 → 电脑  │
 *  │  运算符  │     <<       │      >>      │
 *  │  比喻    │  嘴巴(说话)  │  耳朵(听话)  │
 *  │  后面跟  │  输出内容    │  存储变量    │
 *  └──────────┴──────────────┴──────────────┘
 *
 *  口诀：
 *  cout说话cin听话，箭头方向反着画；
 *  cin后面跟变量，用户输入全靠它！
 * ==========================================
 */
