/*
 * ==========================================
 *  第05课：让电脑说话——cout输出
 *  知识点：cout输出、endl换行、转义字符、链式输出
 *  C++趣味学习系列
 * ==========================================
 *
 *  程序说明：
 *  深入探索cout的各种用法！
 *  从基本输出到漂亮的格式化显示，
 *  让电脑成为你的"发言人"。
 */

#include <iostream>
#include <string>
using namespace std;

int main() {
    // =====================================
    // 示例1：cout的基本用法
    // =====================================
    cout << "========== 示例1：cout基本用法 ==========" << endl;
    cout << "cout是电脑的'嘴巴'，通过<<把内容送到屏幕上。" << endl;
    cout << endl;

    // 输出文字（字符串必须加引号）
    cout << "你好，我是你的电脑！" << endl;

    // 输出数字（数字不需要加引号）
    cout << "我最喜欢的数字是：" << 7 << endl;

    // 输出计算结果
    cout << "10 + 20 = " << 10 + 20 << endl;
    cout << "7 × 8 = " << 7 * 8 << endl;
    cout << "100 - 45 = " << 100 - 45 << endl;
    cout << "100 ÷ 4 = " << 100 / 4 << endl;
    cout << "17 ÷ 5 的余数 = " << 17 % 5 << endl;
    cout << endl;

    // =====================================
    // 示例2：链式输出
    // =====================================
    cout << "========== 示例2：链式输出 ==========" << endl;
    cout << "链式输出就像串糖葫芦，用<<把内容一串串起来！" << endl;

    // 链式输出一句话（混合文字和数字）
    string name = "小明";
    int age = 10;
    cout << "我叫" << name << "，今年" << age << "岁，"
         << "我喜欢" << "编程" << "！" << endl;

    // 更多链式输出
    cout << "我有" << 8 << "块糖，分给" << 3 << "个小朋友，"
         << "每人" << 8 / 3 << "块，还剩" << 8 % 3 << "块。" << endl;
    cout << endl;

    // =====================================
    // 示例3：endl 和 \n 的用法
    // =====================================
    cout << "========== 示例3：endl 和 \\n ==========" << endl;

    // 使用 endl 换行
    cout << "第一行（用endl）" << endl;
    cout << "第二行（用endl）" << endl;

    // 使用 \n 换行（在字符串内部）
    cout << "第三行（用\\n）\n第四行（用\\n）\n";

    // endl 和 \n 的对比
    cout << endl;
    cout << "对比：下面两行效果相同" << endl;
    cout << "A: 你好" << endl << "世界" << endl;
    cout << "B: 你好\\n世界\\n" << endl;
    // 注意：B方式实际输出为：你好\n世界\n（因为这里是在cout中）
    // 为了正确演示，我们这样写：
    cout << "B: 你好\n世界\n" << endl;
    cout << endl;

    // =====================================
    // 示例4：转义字符大全
    // =====================================
    cout << "========== 示例4：转义字符 ==========" << endl;
    cout << "转义字符：用反斜杠\\给字母'施魔法'" << endl;
    cout << endl;

    // \n 换行
    cout << "\\n = 换行：你好\\n世界 → " << endl;
    cout << "你好\n世界" << endl;

    // \t 制表符（Tab，用于对齐）
    cout << "\\t = Tab对齐：" << endl;
    cout << "姓名\t年龄\t成绩" << endl;
    cout << "小明\t10\t98" << endl;
    cout << "小红\t9\t95" << endl;
    cout << "小刚\t11\t88" << endl;

    // \\ 输出反斜杠本身
    cout << "\\\\ = 输出反斜杠：路径是 C:\\\\Users\\\\小明" << endl;

    // \" 输出双引号
    cout << "\\\" = 输出双引号：她说\\\"你好！\\\" → ";
    cout << "她说\"你好！\"" << endl;

    // \' 输出单引号
    cout << "\\' = 输出单引号：It\\'s → It's" << endl;
    cout << endl;

    // =====================================
    // 示例5：制作漂亮的格式化输出
    // =====================================
    cout << "========== 示例5：漂亮输出 ==========" << endl;
    cout << endl;

    // 用装饰线画出标题框
    cout << "********************************" << endl;
    cout << "*                              *" << endl;
    cout << "*     🌟 自我介绍卡片 🌟     *" << endl;
    cout << "*                              *" << endl;
    cout << "********************************" << endl;
    cout << endl;
    cout << "  姓名：\t小明" << endl;
    cout << "  年龄：\t10岁" << endl;
    cout << "  爱好：\t编程、踢足球、画画" << endl;
    cout << "  梦想：\t成为程序员！🚀" << endl;
    cout << endl;
    cout << "********************************" << endl;
    cout << endl;

    // 用等号做边框制作菜单
    cout << "========== 今日菜单 ==========" << endl;
    cout << "  1. 🍕 披萨 —— 25元" << endl;
    cout << "  2. 🍔 汉堡 —— 18元" << endl;
    cout << "  3. 🍜 面条 —— 12元" << endl;
    cout << "  4. 🍦 冰淇淋 —— 8元" << endl;
    cout << "==============================" << endl;
    cout << endl;

    // =====================================
    // 示例6：算术运算演示
    // =====================================
    cout << "========== 示例6：算术运算 ==========" << endl;
    cout << "C++中的算术运算符：" << endl;
    cout << "  +  加法：  10 + 5 = " << 10 + 5 << endl;
    cout << "  -  减法：  10 - 5 = " << 10 - 5 << endl;
    cout << "  *  乘法：  10 * 5 = " << 10 * 5 << endl;
    cout << "  /  除法：  10 / 5 = " << 10 / 5 << endl;
    cout << "  %  取余：  10 % 3 = " << 10 % 3 << endl;
    cout << endl;

    // 注意：整数除法会舍去小数部分
    cout << "注意：整数除法 7 / 2 = " << 7 / 2 << "（结果是3，不是3.5！）" << endl;
    cout << "因为两个整数相除，结果也是整数。" << endl;
    cout << endl;

    // =====================================
    // 练习2参考答案：课程表
    // =====================================
    cout << "========== 练习2答案：课程表 ==========" << endl;
    cout << "======================" << endl;
    cout << "   📚 我的课程表 📚" << endl;
    cout << "======================" << endl;
    cout << "星期\t上午\t下午" << endl;
    cout << "周一\t语文\t数学" << endl;
    cout << "周二\t英语\t科学" << endl;
    cout << "周三\t数学\t编程" << endl;
    cout << "======================" << endl;
    cout << endl;

    // =====================================
    // 练习3参考答案：算术小能手
    // =====================================
    cout << "========== 练习3答案：算术运算 ==========" << endl;
    cout << "12 + 35 = " << 12 + 35 << endl;
    cout << "99 - 28 = " << 99 - 28 << endl;
    cout << "8 × 7 = " << 8 * 7 << endl;
    cout << "144 ÷ 12 = " << 144 / 12 << endl;
    cout << "17 ÷ 5 的余数 = " << 17 % 5 << endl;
    cout << endl;

    // =====================================
    // 挑战任务：完整自我介绍卡片
    // =====================================
    cout << "========== 挑战任务：自我介绍卡片 ==========" << endl;
    cout << endl;
    cout << "********************************" << endl;
    cout << "                              " << endl;
    cout << "     🌟 自我介绍卡片 🌟     " << endl;
    cout << "                              " << endl;
    cout << "********************************" << endl;
    cout << endl;
    cout << "  姓名：\t小明" << endl;
    cout << "  年龄：\t10岁" << endl;
    cout << "  年级：\t四年级" << endl;
    cout << "  爱好：\t编程、踢足球、画画" << endl;
    cout << "  最喜欢的食物：\t🍕 披萨" << endl;
    cout << "  梦想：\t成为一名游戏开发者 🎮" << endl;
    cout << endl;
    cout << "********************************" << endl;
    cout << endl;

    // 链式输出的完整句子
    cout << "大家好！我是" << "小明" << "，今年" << 10 << "岁，"
         << "我的梦想是" << "成为一名游戏开发者！" << endl;
    cout << "很高兴认识大家，让我们一起学编程吧！" << endl;
    cout << endl;

    // =====================================
    // 程序结束
    // =====================================
    cout << "========== 程序结束 ==========" << endl;
    cout << "今天深入学习了cout的各种用法，你能让电脑说什么呢？" << endl;

    return 0;
}

/*
 * ==========================================
 *  本课核心内容总结：
 *
 *  1. cout = 电脑的"嘴巴"，通过 << 输出内容
 *  2. 链式输出：多个 << 串起来输出
 *  3. endl = 换行 + 刷新
 *  4. \n = 在字符串中换行
 *  5. \t = Tab制表符，\ = 反斜杠，\" = 双引号
 *  6. cout << 算式：可以直接输出计算结果
 *
 *  口诀：
 *  cout张嘴说句话，双尖括号来传达；
 *  endl换行\n也一样，链式输出顶呱呱！
 * ==========================================
 */
