// ===== 积木块1：头文件（工具箱） =====
#include <iostream>
#include <cmath>       // 数学工具箱，提供 sqrt() 等函数

// ===== 积木块2：使用标准命名空间 =====
using namespace std;

// ===== 积木块3：main函数（程序入口） =====
int main() {

    // =====================================
    // 示例1：认识程序的基本结构
    // =====================================
    cout << "========== 示例1：程序的基本结构 ==========" << endl;
    cout << "任何C++程序都由这几部分组成：" << endl;
    cout << "  1. #include —— 引入工具箱" << endl;
    cout << "  2. using namespace std —— 使用标准命名空间" << endl;
    cout << "  3. int main() —— 程序入口" << endl;
    cout << "  4. { } 中的语句 —— 具体要做的事" << endl;
    cout << "  5. return 0 —— 程序结束" << endl;
    cout << endl;

    // =====================================
    // 示例2：使用多个头文件
    //   因为引入了 <cmath>，所以可以使用 sqrt 函数
    //   如果没有 #include <cmath>，sqrt 就不能用啦！
    // =====================================
    cout << "========== 示例2：使用cmath数学工具箱 ==========" << endl;
    cout << "4的平方根是：" << sqrt(4) << endl;
    cout << "9的平方根是：" << sqrt(9) << endl;
    cout << "16的平方根是：" << sqrt(16) << endl;
    cout << "25的平方根是：" << sqrt(25) << endl;
    cout << "100的平方根是：" << sqrt(100) << endl;
    cout << endl;

    // =====================================
    // 示例3：每条语句都要以分号结尾
    //   注意：下面每一行末尾都有分号 ;
    //   分号 = 句号，告诉编译器"这句话结束了"
    //   如果忘了写分号，编译就会报错！
    // =====================================
    cout << "========== 示例3：分号的重要性 ==========" << endl;
    cout << "第一句：每条语句后面都要有分号；" << endl;
    cout << "第二句：就像写作文要有句号一样；" << endl;
    cout << "第三句：初学者最容易在这里犯错！" << endl;
    cout << endl;

    // =====================================
    // 示例4：程序的"骨架"展示
    // =====================================
    cout << "========== 示例4：程序骨架口诀 ==========" << endl;
    cout << "头文件是工具箱，main函数是进门；" << endl;
    cout << "花括号里写指令，句句分号记在心！" << endl;
    cout << endl;

    // =====================================
    // 练习2参考答案：找茬游戏修正版
    // =====================================
    cout << "========== 练习2答案：找茬修正 ==========" << endl;
    cout << "原来有3处缺少分号：" << endl;
    cout << "  1. using namespace std 后面" << endl;
    cout << "  2. 第一条 cout 语句后面" << endl;
    cout << "  3. return 0 后面" << endl;
    cout << "现在全部修正好啦！" << endl;
    cout << endl;

    // =====================================
    // 挑战任务参考答案：多功能程序
    // =====================================
    cout << "========== 挑战任务：多功能程序 ==========" << endl;
    cout << "===== 我的程序 =====" << endl;
    cout << "大家好！" << endl;
    cout << "100的平方根是：" << sqrt(100) << endl;
    cout << "256的平方根是：" << sqrt(256) << endl;
    cout << "1024的平方根是：" << sqrt(1024) << endl;
    cout << "程序到此结束，再见！" << endl;
    cout << endl;

    // =====================================
    // 程序结束
    // =====================================
    cout << "========== 程序结束 ==========" << endl;
    cout << "今天学习了程序的五大积木块，你记住了吗？" << endl;

    return 0;  // 积木块5：返回值，告诉系统"程序正常结束"
}

/*
 * 程序结构总结：
 *
 * ┌── 积木块1：头文件 ──────────┐
 * │ #include <iostream>        │
 * │ #include <cmath>           │
 * └────────────────────────────┘
 * ┌── 积木块2：命名空间 ────────┐
 * │ using namespace std;       │
 * └────────────────────────────┘
 * ┌── 积木块3：main函数入口 ────┐
 * │ int main() {               │
 * │                            │
 * │   ┌── 积木块4：语句 ──────┐ │
 * │   │ cout << "...";       │ │
 * │   │ ...                  │ │
 * │   └──────────────────────┘ │
 * │                            │
 * │   return 0; ← 积木块5     │
 * │ }                          │
 * └────────────────────────────┘
 */
