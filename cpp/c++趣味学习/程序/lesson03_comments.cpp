/*
 * ==========================================
 *  第03课：电脑的记忆——注释与代码规范
 *  知识点：单行注释、多行注释、缩进、命名规则
 *  C++趣味学习系列
 * ==========================================
 *
 *  程序说明：
 *  这个程序演示了C++中注释的使用方法、
 *  代码缩进的重要性和好的命名习惯。
 */

#include <iostream>
#include <string>    // 字符串工具箱，用于 string 类型
using namespace std;

int main() {
    // =====================================
    // 示例1：单行注释的用法
    // =====================================
    cout << "========== 示例1：单行注释 ==========" << endl;

    // 双斜杠后面的内容都是注释，编译器会忽略
    cout << "你看不到上面的注释，但你能看到这句话！" << endl;

    int score = 100;  // 行尾注释：说明这个变量的用途
    cout << "满分是：" << score << "分" << endl;
    cout << endl;

    // =====================================
    // 示例2：多行注释的用法
    // =====================================
    cout << "========== 示例2：多行注释 ==========" << endl;

    /*
     * 这是一个多行注释。
     * 可以写很多很多行。
     * 编译器会跳过 /* 到 */
    /* 之间的所有内容。
     * 非常适合写大段的说明文字！
     */

    /* 多行注释也可以只占一行，但一般用于多行 */
    cout << "多行注释通常用于写长说明。" << endl;
    cout << endl;

    // =====================================
    // 示例3：代码缩进的重要性
    // =====================================
    cout << "========== 示例3：代码缩进演示 ==========" << endl;

    // 缩进让代码有层次感，就像写作文分段一样
    cout << "第一层缩进（没有额外空格）" << endl;
    // 下面是模拟嵌套的代码块
    {   // 进入新的代码块 → 加一级缩进
        cout << "    第二层缩进（多了4个空格）" << endl;
        {   // 再进入一层 → 再加一级缩进
            cout << "        第三层缩进（多了8个空格）" << endl;
        }   // 退出 → 减少一级缩进
        cout << "    回到第二层" << endl;
    }   // 再退出 → 再减少一级缩进
    cout << "回到第一层" << endl;
    cout << endl;

    // =====================================
    // 示例4：好的命名 vs 坏的命名
    // =====================================
    cout << "========== 示例4：命名规范 ==========" << endl;

    // ❌ 不好的命名：看名字不知道是什么
    // 这段代码被注释掉了，因为只是演示
    /*
    int a = 12;
    double b = 36.5;
    int c = 150;
    */

    // ✅ 好的命名：一看就明白
    int myAge = 12;              // 我的年龄（驼峰式命名）
    double bodyTemperature = 36.5;  // 体温（驼峰式命名）
    int my_height = 150;         // 我的身高（下划线命名）

    cout << "年龄：" << myAge << "岁" << endl;
    cout << "体温：" << bodyTemperature << "度" << endl;
    cout << "身高：" << my_height << "厘米" << endl;
    cout << endl;

    // =====================================
    // 示例5：命名规则要点
    // =====================================
    cout << "========== 示例5：命名规则 ==========" << endl;
    cout << "命名规则：" << endl;
    cout << "  1. 只能使用字母、数字和下划线" << endl;
    cout << "  2. 第一个字符不能是数字" << endl;
    cout << "  3. 不能使用C++关键字（如int、return）" << endl;
    cout << "  4. 区分大小写（age 和 Age 是不同的）" << endl;
    cout << endl;

    // =====================================
    // 练习2参考答案：给代码"化妆"（加入缩进）
    // =====================================
    cout << "========== 练习2答案：缩进美化 ==========" << endl;
    cout << "原始代码没有缩进，加了缩进之后层次分明：" << endl;
    cout << "  第一层" << endl;
    cout << "    → 第二层（花括号内多4个空格）" << endl;
    cout << "      → 第三层（再嵌套又多4个空格）" << endl;
    cout << endl;

    // =====================================
    // 挑战任务参考答案：完整注释的自我介绍
    // =====================================
    cout << "========== 挑战任务：自我介绍 ==========" << endl;

    // ---- 个人信息 ----
    string myName = "小明";                 // 姓名
    int myAgeValue = 10;                   // 年龄（用myAgeValue避免与上面myAge冲突）
    string favoriteQuote = "好好学习，天天向上";  // 最喜欢的一句话

    // ---- 成绩信息 ----
    int math = 98;       // 数学成绩
    int english = 95;    // 英语成绩
    int science = 93;    // 科学成绩

    // ---- 计算平均分 ----
    // 注意：除以3.0而不是3，是为了得到小数结果
    double average = (math + english + science) / 3.0;

    // ---- 输出结果 ----
    cout << "========== 自我介绍 ==========" << endl;
    cout << "大家好！" << endl;
    cout << "我叫" << myName << "，今年" << myAgeValue << "岁。" << endl;
    cout << "我最喜欢的一句话是：「" << favoriteQuote << "」" << endl;
    cout << endl;
    cout << "========== 我的成绩 ==========" << endl;
    cout << "数学：" << math << "分" << endl;
    cout << "英语：" << english << "分" << endl;
    cout << "科学：" << science << "分" << endl;
    cout << "平均分：" << average << "分" << endl;
    cout << endl;

    // =====================================
    // 程序结束
    // =====================================
    cout << "========== 程序结束 ==========" << endl;
    cout << "今天学习了注释和代码规范，你的代码变漂亮了吗？" << endl;

    return 0;  // return 0 表示程序正常结束
}

/*
 * ==========================================
 *  本课核心内容总结：
 *
 *  1. 单行注释：// 后面的内容都是注释
 *  2. 多行注释：斜杠星号 到 星号斜杠 之间的内容都是注释
 *  3. 缩进：每进入花括号就多缩进4个空格
 *  4. 命名：用有意义的英文词或拼音，见名知意
 *  5. 好习惯：注释 + 缩进 + 好名字 = 漂亮代码！
 *
 *  口诀：
 *  双斜杠写单行，星号斜杠包多行；
 *  缩进对齐层次清，好名字让代码自己会说话！
 * ==========================================
 */
