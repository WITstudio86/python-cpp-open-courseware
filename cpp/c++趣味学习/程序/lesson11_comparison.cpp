/*
 * =============================================
 * C++趣味学习 —— 第11课：关系对对碰——比较运算符
 * 知识点：>、<、>=、<=、==、!=
 * 趣味项目：⚖️ 数字比大小擂台
 * =============================================
 */

#include <iostream>
using namespace std;

int main() {
    // =============================================
    // 示例1：比较两个数字——比大小擂台
    // 六种比较运算符逐一演示
    // =============================================
    cout << "========== 示例1：数字比大小擂台 ==========" << endl;
    {
        int a = 8, b = 5;

        cout << "红方选手：" << a << "  VS  蓝方选手：" << b << endl;
        cout << endl;
        cout << a << " >  " << b << " 吗？ " << (a > b)  << " (1=对, 0=错)" << endl;
        cout << a << " <  " << b << " 吗？ " << (a < b)  << " (1=对, 0=错)" << endl;
        cout << a << " >= " << b << " 吗？ " << (a >= b) << " (1=对, 0=错)" << endl;
        cout << a << " <= " << b << " 吗？ " << (a <= b) << " (1=对, 0=错)" << endl;
        cout << a << " == " << b << " 吗？ " << (a == b) << " (1=对, 0=错)" << endl;
        cout << a << " != " << b << " 吗？ " << (a != b) << " (1=对, 0=错)" << endl;
    }
    cout << endl;

    // =============================================
    // 示例2：= 和 == 的区别陷阱（重要！）
    // = 是赋值，== 是比较
    // 这是初学者最容易犯的错！
    // =============================================
    cout << "========== 示例2：= 和 == 的区别 ==========" << endl;
    {
        int score = 60;  // = 是赋值：把60放进score里

        cout << "你的分数是：" << score << endl;
        cout << endl;

        // 正确写法：使用 == 做比较
        cout << "----- 正确：用 == 判断是否满分 -----" << endl;
        if (score == 100) {
            cout << "满分！太厉害了！🏆" << endl;
        } else {
            cout << "还不是满分，继续加油！💪" << endl;
        }

        // 演示：怎么记住 = 和 == 的区别
        cout << endl;
        cout << "----- 记忆技巧 -----" << endl;
        cout << "一个等号 =  → 赋值（把东西放进去）" << endl;
        cout << "两个等号 == → 比较（问相等吗？）" << endl;

        // 错误示范（注释掉，否则会改变score的值）
        // if (score = 100) {  // ⚠️ 这是赋值！score会变成100！
        //     cout << "这行永远会执行" << endl;
        // }

        cout << "当前score的值仍然是：" << score << "（没有被错误代码改变）" << endl;
    }
    cout << endl;

    // =============================================
    // 示例3：比较运算符综合应用——成绩评级
    // 使用多种比较运算符做成绩分析
    // =============================================
    cout << "========== 示例3：成绩综合分析 ==========" << endl;
    {
        int math = 95;      // 数学
        int english = 88;   // 英语
        int chinese = 82;   // 语文

        cout << "各科成绩：" << endl;
        cout << "  数学：" << math << " 分" << endl;
        cout << "  英语：" << english << " 分" << endl;
        cout << "  语文：" << chinese << " 分" << endl;
        cout << endl;

        // 判断分数高低
        cout << "----- 比大小 -----" << endl;
        cout << "数学 > 英语？ " << (math > english ? "对✓" : "错✗") << endl;
        cout << "英语 > 语文？ " << (english > chinese ? "对✓" : "错✗") << endl;
        cout << "数学 > 语文？ " << (math > chinese ? "对✓" : "错✗") << endl;
        cout << endl;

        // 判断是否有满分
        cout << "----- 满分检查 -----" << endl;
        cout << "数学 == 100？ " << (math == 100 ? "是满分！🏆" : "不是满分") << endl;
        cout << "英语 == 100？ " << (english == 100 ? "是满分！🏆" : "不是满分") << endl;
        cout << "语文 == 100？ " << (chinese == 100 ? "是满分！🏆" : "不是满分") << endl;
        cout << endl;

        // 判断是否同分
        cout << "----- 同分检查 -----" << endl;
        cout << "数学 == 英语？ " << (math == english ? "同分！" : "不同分") << endl;
        cout << "语文 != 数学？ " << (chinese != math ? "不一样！" : "一样") << endl;

        // 使用 >= 判断是否及格
        cout << endl;
        cout << "----- 及格检查（>= 60）-----" << endl;
        cout << "数学 >= 60？ " << (math >= 60 ? "及格✓" : "不及格✗") << endl;
        cout << "英语 >= 60？ " << (english >= 60 ? "及格✓" : "不及格✗") << endl;
        cout << "语文 >= 60？ " << (chinese >= 60 ? "及格✓" : "不及格✗") << endl;
    }
    cout << endl;

    // =============================================
    // 练习1 参考答案：火眼金睛判对错
    // =============================================
    cout << "========== 练习1答案：火眼金睛判对错 ==========" << endl;
    {
        cout << "① 8 > 5      → " << (8 > 5 ? "true(1)" : "false(0)") << endl;
        cout << "② 3 == 4     → " << (3 == 4 ? "true(1)" : "false(0)") << endl;
        cout << "③ 7 <= 7     → " << (7 <= 7 ? "true(1)" : "false(0)") << endl;
        cout << "④ 10 != 9    → " << (10 != 9 ? "true(1)" : "false(0)") << endl;
        cout << "⑤ 15 >= 20   → " << (15 >= 20 ? "true(1)" : "false(0)") << endl;
        cout << "⑥ 6 < 8      → " << (6 < 8 ? "true(1)" : "false(0)") << endl;
        cout << "⑦ 100 == 100 → " << (100 == 100 ? "true(1)" : "false(0)") << endl;
        cout << "⑧ 50 != 50   → " << (50 != 50 ? "true(1)" : "false(0)") << endl;
    }
    cout << endl;

    // =============================================
    // 练习3 参考答案：输入两数比大小
    // =============================================
    cout << "========== 练习3答案：两数比大小 ==========" << endl;
    {
        int num1, num2;
        cout << "请输入第一个整数：";
        cin >> num1;
        cout << "请输入第二个整数：";
        cin >> num2;
        cout << endl;

        cout << "===== 比较结果 =====" << endl;
        if (num1 > num2) {
            cout << num1 << " > " << num2 << "（第一个数更大）" << endl;
        } else if (num1 < num2) {
            cout << num1 << " < " << num2 << "（第二个数更大）" << endl;
        } else {
            cout << num1 << " == " << num2 << "（两数相等！）" << endl;
        }
    }
    cout << endl;

    // =============================================
    // 挑战任务 参考答案：数字比大小擂台——找最大值
    // 输入三个整数，找出最大值
    // =============================================
    cout << "========== 挑战任务：数字比大小擂台 ==========" << endl;
    {
        int a, b, c;
        int max;

        cout << "三位选手登场！请输入他们的分数：" << endl;
        cout << "🔴 红方选手分数：";
        cin >> a;
        cout << "🔵 蓝方选手分数：";
        cin >> b;
        cout << "🟢 绿方选手分数：";
        cin >> c;

        cout << endl;
        cout << "===== 比赛开始！=====" << endl;
        cout << "红方：" << a << "  VS  蓝方：" << b << endl;

        // 先比较a和b，找出较大的
        if (a > b) {
            max = a;
            cout << "第一回合：红方获胜！(" << a << " > " << b << ")" << endl;
        } else if (b > a) {
            max = b;
            cout << "第一回合：蓝方获胜！(" << b << " > " << a << ")" << endl;
        } else {
            max = a;  // 相等时随便取一个
            cout << "第一回合：平局！(" << a << " == " << b << ")" << endl;
        }

        // 再和c比较
        cout << endl;
        cout << "擂主：" << max << "  VS  挑战者绿方：" << c << endl;
        if (c > max) {
            max = c;
            cout << "第二回合：绿方获胜！(" << c << " > " << max << ")" << endl;
        } else if (c < max) {
            cout << "第二回合：擂主守住了！(" << max << " > " << c << ")" << endl;
        } else {
            cout << "第二回合：平局！(" << max << " == " << c << ")" << endl;
        }

        cout << endl;
        cout << "===== 🏆 最终结果 =====" << endl;

        // 判断是否有完全平局
        if (a == b && b == c) {
            cout << "三位选手全部打平！大家都是" << a << "分！" << endl;
            cout << "这场比赛没有输家，都是冠军！🏆🏆🏆" << endl;
        } else {
            cout << "冠军得分：" << max << " 分！🏆" << endl;
            // 输出谁得了最高分
            cout << "冠军是——";
            if (max == a) cout << "红方选手！🔴" << endl;
            if (max == b) cout << "蓝方选手！🔵" << endl;
            if (max == c) cout << "绿方选手！🟢" << endl;
        }
    }
    cout << endl;

    // =============================================
    // 程序结束
    // =============================================
    cout << "========== 程序结束 ==========" << endl;
    cout << "恭喜！你已经掌握了六种比较运算符！" << endl;
    cout << "记住：= 是赋值，== 是比较，千万别搞混哦！" << endl;

    return 0;
}
