void exerciseAnswers() {
    cout << "\n═══════════════════════════════════════════" << endl;
    cout << "📝 课堂练习答案验证" << endl;
    cout << "═══════════════════════════════════════════" << endl;

    // 练习 1：猜输出
    cout << "\n--- 练习 1：猜输出 ---" << endl;
    int a_test = 5;  // 模拟全局 a
    cout << "在 main 中，a = " << a_test << endl;
    {
        int a_test = 10;  // 局部遮盖
        cout << "在内层块中，a = " << a_test << " ← 局部变量遮盖了外层的 a" << endl;
    }
    cout << "回到外层，a = " << a_test << " ← 外层的 a 没有被改变" << endl;

    // 练习 2：生命周期验证
    cout << "\n--- 练习 2：生命周期验证 ---" << endl;
    cout << "变量 secret 定义在内层 {} 中，" << endl;
    cout << "离开 {} 后 secret 就消失了，" << endl;
    cout << "所以外层的 cout << secret 会编译报错！" << endl;

    // 练习 3：作用域判断
    cout << "\n--- 练习 3：作用域判断 ---" << endl;
    cout << "① ✅ saveMoney() 内的 piggyBank 在作用域内" << endl;
    cout << "② ✅ money 是全局变量，任何地方都能访问" << endl;
    cout << "③ ✅ money 是全局变量，main() 里也能用" << endl;
    cout << "④ ❌ piggyBank 是 saveMoney() 的局部变量，main() 看不到它" << endl;
}


