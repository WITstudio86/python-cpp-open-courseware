/*
 * ============================================================================
 * Lesson 39: 变量的小天地——作用域
 * 🏠 家的地图——变量的"房间"分布
 * ============================================================================
 *
 * 本程序通过"家"的比喻，展示 C++ 中变量的作用域规则：
 *
 * 【核心概念】
 * 1. 局部变量：定义在函数/代码块内部，只在"自己的房间"里有效
 * 2. 全局变量：定义在所有函数外面，整个"家"的任何角落都能访问
 * 3. 名字遮盖（Name Shadowing）：局部变量与全局变量同名时，局部优先
 * 4. 代码块作用域：if / for / while 的 { } 也构成独立的作用域
 * 5. 生命周期：进入作用域时变量"出生"，离开作用域时变量"消失"
 *
 * 【家的地图】（各程序的变量分布）
 *
 *         ┌──────────────────────────────────────────┐
 *         │          🏠 第39号 · 阳光花园              │
 *         │                                          │
 *         │   【花园（全局区域）】                      │
 *         │   - gardenName = "阳光花园"               │
 *         │   - houseNumber = 39                     │
 *         │   - totalGuests = 0                      │
 *         │                                          │
 *         │   ┌─────────┐  ┌─────────┐  ┌─────────┐ │
 *         │   │  客厅    │  │  厨房    │  │  卧室    │ │
 *         │   │ ─────── │  │ ─────── │  │ ─────── │ │
 *         │   │ sofa    │  │ stove   │  │ bed     │ │
 *         │   │ guests  │  │ guests  │  │ guests  │ │
 *         │   │ (局部)  │  │ (局部)  │  │ (局部)  │ │
 *         │   │         │  │ light!  │  │         │ │
 *         │   │         │  │ (遮盖)  │  │         │ │
 *         │   └─────────┘  └─────────┘  └─────────┘ │
 *         │                                          │
 *         │   【院子（main 函数）】                     │
 *         │   - 能看到花园（全局变量）                   │
 *         │   - 看不到各房间里的东西（局部变量）          │
 *         └──────────────────────────────────────────┘
 *
 * 编译运行：
 *   g++ -std=c++11 lesson39_scope.cpp -o lesson39_scope
 *   ./lesson39_scope
 * ============================================================================
 */

#include <iostream>
using namespace std;

// ==================== 全局变量·花园区域 ====================
// 这些变量定义在所有函数外面，整个程序的每个角落都能看到它们。
// 它们就像房子外面花园里的公告牌，每个房间的人都能看到。

string gardenName = "阳光花园";    // 花园的名字
int    houseNumber = 39;           // 门牌号
int    totalGuests = 0;            // 来访总人数（会被各房间累加）

// ==================== 函数声明 ====================
void livingRoom();   // 客厅
void kitchen();      // 厨房
void bedroom();      // 卧室
void shadowDemo();   // 遮盖演示
void blockScopeDemo(); // 代码块作用域演示


// ====================================================================
// 程序一：局部变量与全局变量的基本用法
// ====================================================================

void livingRoom() {
    // sofa 是客厅的"私有物品"——局部变量
    // 只有客厅里的人（livingRoom 函数内的代码）能看到和使用它
    string sofa = "蓝色沙发";
    int guests = 5;   // 客厅来了 5 位客人

    cout << "┌─────────────────────┐" << endl;
    cout << "│  🛋️  客厅             │" << endl;
    cout << "├─────────────────────┤" << endl;
    cout << "│  家具：" << sofa << "        │" << endl;
    cout << "│  访客：" << guests << " 人            │" << endl;
    cout << "│  花园名：" << gardenName;       // ✅ 能看到全局变量
    if (gardenName.length() < 9) cout << "    │" << endl;
    else cout << "│" << endl;
    cout << "│  门牌号：" << houseNumber << " 号          │" << endl;
    // cout << bed;  // ❌ 编译错误！客厅看不到卧室的床
    totalGuests += guests;  // ✅ 修改全局变量
    cout << "└─────────────────────┘" << endl;
}

void kitchen() {
    string stove = "燃气灶";  // 厨房的私有物品——局部变量
    int guests = 3;           // 厨房来了 3 位客人（每个房间的 guests 互不影响！）

    cout << "┌─────────────────────┐" << endl;
    cout << "│  🍳  厨房             │" << endl;
    cout << "├─────────────────────┤" << endl;
    cout << "│  厨具：" << stove << "        │" << endl;
    cout << "│  访客：" << guests << " 人            │" << endl;
    cout << "│  花园名：" << gardenName << "│" << endl;
    // cout << sofa;  // ❌ 编译错误！厨房看不到客厅的沙发
    totalGuests += guests;  // ✅ 修改全局变量
    cout << "└─────────────────────┘" << endl;
}

void bedroom() {
    string bed = "双人床";   // 卧室的私有物品——局部变量
    int guests = 2;          // 卧室来了 2 位客人

    cout << "┌─────────────────────┐" << endl;
    cout << "│  🛏️  卧室             │" << endl;
    cout << "├─────────────────────┤" << endl;
    cout << "│  家具：" << bed << "        │" << endl;
    cout << "│  访客：" << guests << " 人            │" << endl;
    cout << "│  花园名：" << gardenName << "│" << endl;
    // cout << sofa;  // ❌ 编译错误！卧室看不到客厅的沙发
    totalGuests += guests;  // ✅ 修改全局变量
    cout << "└─────────────────────┘" << endl;
}

// ====================================================================
// 程序二：名字遮盖（Name Shadowing）演示
// "灯光的故事"——不同房间的灯 vs 屋外的路灯
// ====================================================================

int light = 1;  // 全局变量：屋外的路灯，编号为 1

void shadowDemo() {
    cout << "\n═══════════════════════════════════════════" << endl;
    cout << "💡 名字遮盖实验 —— 灯光的故事" << endl;
    cout << "═══════════════════════════════════════════" << endl;

    // 在主程序中（院子），看到的是全局的路灯
    cout << "\n📍 站在院子里向外看：" << endl;
    cout << "   light = " << light << "（路灯，编号①）" << endl;

    // 走进厨房——厨房有自己的灯！
    {
        int light = 2;  // 局部变量：厨房的灯，编号为 2
        // 注意：这里的局部 light "遮盖"了全局 light！
        cout << "\n📍 走进厨房后：" << endl;
        cout << "   light = " << light << "（厨房的灯，编号②）⚠️ 遮盖了路灯！" << endl;
        cout << "   虽然路灯 light 还存在，但在厨房里只能看到厨房的灯。" << endl;
    }  // 离开厨房——厨房的灯 light(2) 消失，路灯 light(1) 重新可见

    // 走出厨房，回到院子
    cout << "\n📍 走出厨房，回到院子：" << endl;
    cout << "   light = " << light << "（又是路灯了，编号①）" << endl;
    cout << "   厨房的灯已经灭了（生命周期结束），路灯重新亮起。" << endl;

    // 验证：全局 light 的值从未被厨房改变过
    cout << "\n✅ 全局变量 light 始终是 " << light << "，从未被修改过。" << endl;
}

// ====================================================================
// 程序三：代码块作用域演示
// 房间里的"小隔间"——if / for / while 的 { } 也是作用域！
// ====================================================================

void blockScopeDemo() {
    cout << "\n═══════════════════════════════════════════" << endl;
    cout << "📦 代码块作用域实验 —— 房间里的纸箱子" << endl;
    cout << "═══════════════════════════════════════════" << endl;

    string owner = "小明";  // main 函数作用域内的局部变量

    // --- 演示 1：if 语句的代码块 ---
    cout << "\n📌 实验一：if 语句的代码块" << endl;
    if (true) {
        string note = "这个纸条放在 if 代码块的纸箱里";  // 只在 if {} 内有效
        int boxNumber = 1;
        cout << "   进 if 块 → 第 " << boxNumber << " 号纸箱里的纸条：" << note << endl;
        cout << "   进 if 块 → 还能看到 owner：" << owner << " ✅（owner 在外层）" << endl;
        // 内层可以"向外看"——看到外层的变量
    }  // note 和 boxNumber 在这里消失！
    // cout << note;  // ❌ 编译错误！note 已经不存在了
    cout << "   出 if 块 → owner 还在：" << owner << " ✅" << endl;
    // cout << "   出 if 块 → 纸条还在吗？" << note;  // ❌ 这行不能编译

    // --- 演示 2：for 循环的代码块 ---
    cout << "\n📌 实验二：for 循环的代码块" << endl;
    for (int i = 1; i <= 3; i++) {
        string loopMsg = "第 " + to_string(i) + " 次循环";
        cout << "   " << loopMsg << " → i 在循环体内有效" << endl;
        // 每次循环迭代结束，loopMsg 的生命周期就结束了
        // 下一次循环开始时，一个新的 loopMsg 被创建
    }  // i 在这里消失！
    // cout << i;  // ❌ 编译错误！i 只在 for 代码块内存在

    // --- 演示 3：嵌套作用域 ---
    cout << "\n📌 实验三：嵌套作用域" << endl;
    cout << "   外层：" << endl;
    int outerValue = 100;
    {
        int innerValue = 200;
        cout << "      中层：outerValue = " << outerValue << " ✅" << endl;
        cout << "      中层：innerValue = " << innerValue << " ✅" << endl;
        {
            int deepValue = 300;
            cout << "         内层：outerValue = " << outerValue << " ✅" << endl;
            cout << "         内层：innerValue = " << innerValue << " ✅" << endl;
            cout << "         内层：deepValue = " << deepValue << " ✅" << endl;
        }  // deepValue 消失
        // cout << deepValue;  // ❌ deepValue 已消失
        cout << "      回到中层：innerValue 还在 = " << innerValue << " ✅" << endl;
    }  // innerValue 消失
    cout << "   回到外层：outerValue = " << outerValue << " ✅" << endl;
    // cout << innerValue;  // ❌ innerValue 已消失

    cout << "\n💡 规则：外层看不到内层，内层能看到外层！" << endl;
}

