// ================================================================
// 例题1：删数问题
// 题目描述：
//   给定一个高精度正整数 N（长度不超过240位），去掉其中任意 K 个数字后，
//   剩下的数字按原左右次序组成一个新的正整数。
//   找出一种方案使得剩下的数字组成的新数最小。
//
// 贪心策略分析：
//   要使得删除后剩下的数字最小，高位数字应该尽可能小。
//   因此，从高位到低位扫描，找到第一个满足 s[i] > s[i+1] 的位置 i，
//   删除 s[i]，因为删除后，较小的 s[i+1] 会顶替到高位，使整体数值变小。
//   重复 K 次即可。
//
//   特殊情况：如果数字串是单调递增的（如 "12345"），找不到 s[i] > s[i+1]，
//   说明每一位都比后面小，此时删除最后一位（最大的一位）是最优的。
//
//   时间复杂度：O(n × k)，其中 n 是数字串长度，k 是删除次数。
//   空间复杂度：O(1)，在原字符串上操作。
// ================================================================
string deleteDigits(string s, int k) {
    // 边界处理：如果删除次数大于等于数字长度，结果为 "0"
    if (k >= (int)s.size()) {
        return "0";
    }

    // 重复 k 次删除操作
    for (int t = 0; t < k; t++) {
        // pos 记录本轮要删除的位置
        // 默认删除最后一位（处理单调递增的情况）
        int pos = s.size() - 1;

        // 从高位到低位扫描，找第一个「当前位 > 下一位」的位置
        // 例如："178543" 中，8 > 5，所以删除位置2的 '8'
        for (int i = 0; i < (int)s.size() - 1; i++) {
            if (s[i] > s[i + 1]) {
                pos = i;
                break;  // 找到第一个就停止，贪心选择
            }
        }

        // 删除 pos 位置的字符
        s.erase(pos, 1);
    }

    // 去除前导零
    // 例如："0013" → "13"，但注意要保留至少一个 "0"
    // （比如结果本身就是 0 的情况）
    while (s.size() > 1 && s[0] == '0') {
        s.erase(0, 1);
    }

    return s;
}

// ================================================================
// 例题1 的展示函数：演示删数问题的逐步过程
// 让学生直观看到每一步删除了哪个数字
// ================================================================
void solveDeleteDigits() {
    cout << "══════════════════════════════════════" << endl;
    cout << "  例题1：删数问题" << endl;
    cout << "══════════════════════════════════════" << endl;
    cout << "给定一个数字串，删除K个数字使结果最小" << endl;
    cout << "贪心策略：每次删除第一个「比下一位大」的数字" << endl;
    cout << "--------------------------------------" << endl;

    // ===== 测试用例1 =====
    {
        string s = "178543";
        int k = 4;
        cout << "\n【测试1】数字: " << s << ", 删除: " << k << " 个" << endl;
        cout << "删除过程：" << endl;

        string cur = s;
        for (int t = 0; t < k; t++) {
            int pos = cur.size() - 1;
            for (int i = 0; i < (int)cur.size() - 1; i++) {
                if (cur[i] > cur[i + 1]) {
                    pos = i;
                    break;
                }
            }
            cout << "  第" << (t + 1) << "步：找到 " << cur[pos]
                 << " > " << cur[pos + 1] << "（位置 " << pos << "），删除 '"
                 << cur[pos] << "' → ";
            cur.erase(pos, 1);
            cout << cur << endl;
        }

        // 去前导零
        while (cur.size() > 1 && cur[0] == '0') {
            cur.erase(0, 1);
        }
        cout << "最终结果：" << cur << endl;
    }

    // ===== 测试用例2：单调递增 =====
    {
        string s = "12345";
        int k = 2;
        cout << "\n【测试2】数字: " << s << "（单调递增）, 删除: " << k << " 个" << endl;

        string cur = s;
        for (int t = 0; t < k; t++) {
            int pos = cur.size() - 1;
            for (int i = 0; i < (int)cur.size() - 1; i++) {
                if (cur[i] > cur[i + 1]) {
                    pos = i;
                    break;
                }
            }
            cout << "  第" << (t + 1) << "步：单调递增，删除最后一位 '"
                 << cur[pos] << "' → ";
            cur.erase(pos, 1);
            cout << cur << endl;
        }
        cout << "最终结果：" << cur << endl;
    }

    // ===== 测试用例3：含前导零 =====
    {
        string s = "100200";
        int k = 2;
        cout << "\n【测试3】数字: " << s << ", 删除: " << k << " 个" << endl;
        string result = deleteDigits(s, k);
        cout << "最终结果：" << result << "（自动去除前导零）" << endl;
    }

    // ===== 测试用例4：边界情况 =====
    {
        string s = "54321";
        int k = 5;
        cout << "\n【测试4】数字: " << s << ", 删除: " << k
             << " 个（全部删除）" << endl;
        string result = deleteDigits(s, k);
        cout << "最终结果：" << result << endl;
    }

    cout << endl;
}

