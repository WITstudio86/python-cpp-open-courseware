// 例题2：均分纸牌
// 题目描述：
//   有 N 堆纸牌排成一行，编号为 1, 2, ..., N。
//   每堆上有若干张纸牌，总张数必为 N 的倍数。
//   每次移动：从任意一堆取若干张纸牌，移动到相邻的堆上。
//   第1堆只能移到第2堆，第N堆只能移到第N-1堆。
//   求最少移动次数使每堆纸牌数相等。
//
// 贪心策略分析：
//   1. 计算所有纸牌的平均值 avg = sum / N。
//   2. 从左到右逐堆处理：
//      - 如果第 i 堆的牌数不等于 avg，计算差额 diff = cards[i] - avg。
//      - 由于第 i-1 堆已经处理完毕（已变为 avg），无法再调整，
//        因此第 i 堆的差额只能通过第 i+1 堆来调整。
//      - 将 diff 加到 cards[i+1] 上，同时记一次移动。
//      - 无论 diff 是正（给出去）还是负（借进来），都算一次操作。
//   3. 处理到最后一堆时，由于总数是 N 的倍数，最后一堆会自动变为 avg。
//
//   「每次转移无论牌数多少只算一次移动」是本题的关键设定。
//   移动次数 = 所有「cards[i] != avg」的堆的数量。
//
//   时间复杂度：O(n)，只需两次遍历。
//   空间复杂度：O(1)，在原数组上操作。
// ================================================================
int minMovesToEvenCards(int cards[], int n) {
    // 第一步：计算总牌数和平均值
    int sum = 0;
    for (int i = 0; i < n; i++) {
        sum += cards[i];
    }
    int avg = sum / n;  // 题目保证 sum 是 n 的倍数

    // 第二步：从左到右贪心调整
    int moves = 0;
    for (int i = 0; i < n - 1; i++) {
        // 如果当前堆不等于平均值，需要通过下一堆来调整
        if (cards[i] != avg) {
            // 计算当前堆与平均值的差额
            // diff > 0：当前堆多了，把多余的给下一堆
            // diff < 0：当前堆少了，从下一堆借
            int diff = cards[i] - avg;

            // 将差额转移给下一堆
            cards[i + 1] += diff;

            // 当前堆变为平均值（这一步在代码中不是必须的，
            // 因为我们不会再访问 cards[i]，但逻辑上是这样）
            // cards[i] = avg;  // 可省略，后续不再使用

            // 无论差额多少，都只算一次移动
            moves++;
        }
    }

    return moves;
}

// ================================================================
// 例题2 的展示函数：演示均分纸牌的逐步过程
// 让学生直观看到每一步的转移操作
// ================================================================
void solveEvenCards() {
    cout << "══════════════════════════════════════" << endl;
    cout << "  例题2：均分纸牌" << endl;
    cout << "══════════════════════════════════════" << endl;
    cout << "N堆纸牌排成一行，每次移动1张到相邻堆" << endl;
    cout << "贪心策略：从左到右，差额转移给下一堆" << endl;
    cout << "--------------------------------------" << endl;

    // ===== 测试用例1：经典样例 =====
    {
        int n = 4;
        // 数组用于演示过程（因为函数会修改原数组，所以额外声明）
        int demo[] = {9, 8, 17, 6};
        int sum = 0;
        for (int i = 0; i < n; i++) sum += demo[i];
        int avg = sum / n;

        cout << "\n【测试1】N = " << n << ", 纸牌数: [9, 8, 17, 6]" << endl;
        cout << "总牌数 = " << sum << ", 平均值 = " << avg << endl;
        cout << "调整过程：" << endl;

        int moves = 0;
        for (int i = 0; i < n - 1; i++) {
            // 打印当前状态
            cout << "  [";
            for (int j = 0; j < n; j++) {
                if (j > 0) cout << ", ";
                cout << demo[j];
            }
            cout << "]  ";

            if (demo[i] != avg) {
                int diff = demo[i] - avg;
                demo[i] = avg;             // 当前堆变为平均值
                demo[i + 1] += diff;       // 差额转移到下一堆
                moves++;
                if (diff > 0) {
                    cout << "第" << (i + 1) << "堆多" << diff
                         << "张 → 移给第" << (i + 2) << "堆";
                } else {
                    cout << "第" << (i + 1) << "堆少" << -diff
                         << "张 → 从第" << (i + 2) << "堆借";
                }
                cout << "（移动" << moves << "次）" << endl;
            } else {
                cout << "第" << (i + 1) << "堆已等于平均值，无需调整" << endl;
            }
        }
        // 最终状态
        cout << "  [";
        for (int j = 0; j < n; j++) {
            if (j > 0) cout << ", ";
            cout << demo[j];
        }
        cout << "]  全部等于平均值！" << endl;

        cout << "最少移动次数：" << moves << endl;
    }

    // ===== 测试用例2：已经平均 =====
    {
        int n = 3;
        int cards[] = {5, 5, 5};
        cout << "\n【测试2】N = " << n << ", 纸牌数: [5, 5, 5]（已经平均）" << endl;
        int result = minMovesToEvenCards(cards, n);
        cout << "最少移动次数：" << result << "（无需任何移动）" << endl;
    }

    // ===== 测试用例3：大量差额 =====
    {
        int n = 5;
        int demo[] = {1, 1, 1, 1, 21};
        int sum = 0;
        for (int i = 0; i < n; i++) sum += demo[i];
        int avg = sum / n;

        cout << "\n【测试3】N = " << n << ", 纸牌数: [1, 1, 1, 1, 21]" << endl;
        cout << "总牌数 = " << sum << ", 平均值 = " << avg << endl;

        int moves = 0;
        for (int i = 0; i < n - 1; i++) {
            cout << "  [";
            for (int j = 0; j < n; j++) {
                if (j > 0) cout << ", ";
                cout << demo[j];
            }
            cout << "]  ";

            if (demo[i] != avg) {
                int diff = demo[i] - avg;
                demo[i] = avg;             // 当前堆变为平均值
                demo[i + 1] += diff;       // 差额转移到下一堆
                moves++;
                if (diff > 0) {
                    cout << "多" << diff << " → 移给下一堆";
                } else {
                    cout << "少" << -diff << " → 从下一堆借";
                }
                cout << "（移动" << moves << "次）" << endl;
            } else {
                cout << "已等于平均值" << endl;
            }
        }
        cout << "  [";
        for (int j = 0; j < n; j++) {
            if (j > 0) cout << ", ";
            cout << demo[j];
        }
        cout << "]  完成！" << endl;
        cout << "最少移动次数：" << moves << endl;
    }

    cout << endl;
}

