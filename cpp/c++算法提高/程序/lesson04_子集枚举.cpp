// ================================================================
// 位运算知识演示
// 在开始枚举之前，先帮助学生理解位运算
// ================================================================
void demoBitOperations() {
    cout << "══════════════════════════════════════" << endl;
    cout << "  位运算基础知识" << endl;
    cout << "══════════════════════════════════════" << endl;

    int a = 5;   // 二进制: 0101
    int b = 12;  // 二进制: 1100

    cout << "a = " << a << " (二进制: ";
    for (int i = 3; i >= 0; i--) cout << ((a >> i) & 1);
    cout << ")" << endl;

    cout << "b = " << b << " (二进制: ";
    for (int i = 3; i >= 0; i--) cout << ((b >> i) & 1);
    cout << ")" << endl;

    cout << endl;
    cout << "a & b  (按位与)  = " << (a & b) << "    ";
    cout << "(只有对应位都为1才为1)" << endl;

    cout << "a | b  (按位或)  = " << (a | b) << "   ";
    cout << "(对应位有一个为1则为1)" << endl;

    cout << "1 << 3 (左移)    = " << (1 << 3) << "    ";
    cout << "(= 2^3 = 8)" << endl;

    cout << "a >> 1 (右移)    = " << (a >> 1) << "     ";
    cout << "(5/2 = 2)" << endl;
    cout << endl;

    // 演示 mask & (1<<i) 检查第i位
    cout << "【重点演示】mask & (1 << i) 检查第i位：" << endl;
    int mask = 13;  // 二进制 1101
    cout << "mask = " << mask << " (二进制: 1101)" << endl;
    for (int i = 0; i < 4; i++) {
        cout << "  第" << i << "位: mask & (1<<" << i << ") = "
             << mask << " & " << (1 << i) << " = "
             << (mask & (1 << i));
        if (mask & (1 << i))
            cout << " ≠ 0 → 第" << i << "位是1（选中！）";
        else
            cout << " = 0 → 第" << i << "位是0（未选）";
        cout << endl;
    }
    cout << endl;
}

// ================================================================
// 二进制枚举所有子集（核心演示）
// 遍历 mask 从 0 到 2^n-1，逐一输出子集
// ================================================================
void enumerateAllSubsets(int arr[], int n) {
    cout << "══════════════════════════════════════" << endl;
    cout << "  二进制枚举子集演示" << endl;
    cout << "══════════════════════════════════════" << endl;
    cout << "集合: {";
    for (int i = 0; i < n; i++) {
        cout << arr[i];
        if (i < n - 1) cout << ", ";
    }
    cout << "}  (" << n << "个元素，共2^" << n << " = " << (1<<n) << "个子集)" << endl;
    cout << "--------------------------------------" << endl;

    int total = 1 << n;  // 2^n

    // 遍历所有可能的 mask（选取方案）
    for (int mask = 0; mask < total; mask++) {
        // 输出 mask 的二进制表示
        cout << "mask=" << setw(2) << mask << " (";
        for (int i = n - 1; i >= 0; i--) {
            cout << ((mask >> i) & 1);
        }
        cout << ") → { ";

        int sum = 0;
        bool first = true;

        // 检查每一位
        for (int i = 0; i < n; i++) {
            if (mask & (1 << i)) {  // 第i位为1，选中第i个元素
                if (!first) cout << ", ";
                cout << arr[i];
                first = false;
                sum += arr[i];
            }
        }

        if (first) cout << "(空集)";
        cout << " }  和 = " << sum << endl;
    }
    cout << endl;
}

// ================================================================
// 例题1：集合选数
// 题目：给定N个正整数，求所有子集的元素和，去重排序输出
//
// 枚举思路：
//   - 用二进制枚举所有 2^N 个子集
//   - 对每个子集计算元素和
//   - 用 set 自动去重和排序
// ================================================================
void solveSubsetSum() {
    cout << "══════════════════════════════════════" << endl;
    cout << "  例题1：集合选数——所有子集和" << endl;
    cout << "══════════════════════════════════════" << endl;

    int N;
    cout << "请输入元素个数 N（建议 ≤ 15）: ";
    cin >> N;

    int arr[20];
    cout << "请输入 " << N << " 个正整数: ";
    for (int i = 0; i < N; i++) {
        cin >> arr[i];
    }

    set<int> sums;         // 用 set 自动去重和排序
    int total = 1 << N;    // 2^N 个子集

    // 打印进度提示
    cout << "正在枚举 2^" << N << " = " << total << " 个子集..." << endl;

    for (int mask = 0; mask < total; mask++) {
        int sum = 0;
        for (int i = 0; i < N; i++) {
            if (mask & (1 << i)) {  // 第i个元素被选中
                sum += arr[i];
            }
        }
        sums.insert(sum);
    }

    cout << "--------------------------------------" << endl;
    cout << "所有不同的子集和（共 " << sums.size() << " 种）：" << endl;
    int cnt = 0;
    for (int s : sums) {
        cout << s << " ";
        cnt++;
        if (cnt % 10 == 0) cout << endl;  // 每10个换行
    }
    cout << endl << endl;
}

// ================================================================
// 例题2：砝码称重
// 题目：砝码1g,2g,3g,5g,10g,20g各一个，放同一边，能称出多少种重量
//
// 枚举思路：
//   - 6种砝码，2^6 = 64 种选取方案
//   - 每种方案对应一种重量（所选砝码重量之和）
//   - 用 set 自动去重
//
// 注意：这题假设砝码只能放同一边。
//       如果允许放两边（天平问题），需要更复杂的处理。
// ================================================================
void solveBalanceWeight() {
    cout << "══════════════════════════════════════" << endl;
    cout << "  例题2：砝码称重" << endl;
    cout << "══════════════════════════════════════" << endl;
    cout << "砝码: 1g, 2g, 3g, 5g, 10g, 20g 各一个" << endl;
    cout << "砝码放同一边，问能称出多少种重量？" << endl;
    cout << "--------------------------------------" << endl;

    int weights[] = {1, 2, 3, 5, 10, 20};
    int n = 6;                    // 6种砝码
    int total = 1 << n;            // 2^6 = 64

    set<int> result;

    for (int mask = 0; mask < total; mask++) {
        int sum = 0;
        // 检查每种砝码是否被选中
        for (int i = 0; i < n; i++) {
            if (mask & (1 << i)) {
                sum += weights[i];
            }
        }
        result.insert(sum);
    }

    cout << "理论子集总数：64 种选取方案" << endl;
    cout << "不同的称重量：共 " << result.size() << " 种" << endl;
    cout << endl;
    cout << "所有可称重量（升序）：" << endl;

    int cnt = 0;
    for (int w : result) {
        cout << setw(3) << w << "g";
        cnt++;
        if (cnt % 10 == 0) cout << endl;
        else cout << " ";
    }
    cout << endl;

    // 验证：所有砝码之和 = 1+2+3+5+10+20 = 41
    int maxWeight = 0;
    for (int i = 0; i < n; i++) maxWeight += weights[i];
    cout << endl;
    cout << "最重：将全部砝码放上 = " << maxWeight << "g" << endl;
    cout << "（0g 表示不放任何砝码）" << endl;
    cout << endl;
}

// ================================================================
// 附加演示：子集枚举在"部分和问题"中的应用
// 问题：给定一组数和目标值S，判断是否存在子集其和为S
// 这是经典"subset sum"问题的暴力枚举解法
// ================================================================
void demoSubsetSumTarget() {
    cout << "══════════════════════════════════════" << endl;
    cout << "  附加演示：部分和问题" << endl;
    cout << "══════════════════════════════════════" << endl;

    int arr[] = {3, 5, 7, 9, 11};
    int n = 5;
    int target = 20;

    cout << "集合: {3, 5, 7, 9, 11}" << endl;
    cout << "目标值: " << target << endl;
    cout << "寻找和等于 " << target << " 的子集..." << endl;
    cout << "--------------------------------------" << endl;

    int total = 1 << n;
    bool found = false;

    for (int mask = 0; mask < total; mask++) {
        int sum = 0;
        // 计算当前子集的和
        for (int i = 0; i < n; i++) {
            if (mask & (1 << i)) sum += arr[i];
        }

        if (sum == target) {
            found = true;
            cout << "找到解：{ ";
            for (int i = 0; i < n; i++) {
                if (mask & (1 << i)) cout << arr[i] << " ";
            }
            cout << "} = " << target << endl;
        }
    }

    if (!found) cout << "无解" << endl;
    cout << endl;
}

