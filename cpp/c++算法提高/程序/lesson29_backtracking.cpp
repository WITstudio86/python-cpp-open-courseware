// ================================================================
// 例题1：八皇后问题
// ================================================================
// 问题描述：
//   在 8×8 的国际象棋棋盘上放置 8 个皇后，使得任意两个皇后
//   都不能在同一行、同一列或同一对角线上。
//
// 数据结构说明：
//   pos[i] = 第 i 行皇后所在的列编号（0 ~ 7）
//   这样设计天然保证了"每行只有一个皇后"
//
// 冲突检查逻辑：
//   - 同列冲突：pos[i] == col（两个皇后在同一列）
//   - 对角线冲突：abs(row - i) == abs(col - pos[i])
//     解释：在棋盘上，如果两个位置的行差等于列差，
//     说明它们在一条45度或135度的对角线上
//
// 回溯搜索流程：
//   从第0行开始，逐行放置皇后
//   对于每一行，尝试所有8列位置
//   → 如果某一列合法，就放置皇后并递归到下一行
//   → 如果8列都不合法，回溯到上一行重新选择
// ================================================================

const int N = 8;                    // 棋盘大小（8×8）
int pos[N];                         // pos[行] = 列，记录皇后位置
int queenSolutionCount = 0;         // 八皇后解的数量计数器
bool queenFirstPrinted = false;     // 是否已经输出了第一个解

// 检查在第 row 行第 col 列放置皇后是否安全
// 需要和前面已经放置的 row 个皇后逐一比较
bool isSafe(int row, int col) {
    for (int i = 0; i < row; i++) {
        // 检查1：是否在同一列？
        if (pos[i] == col) {
            return false;           // 同列冲突，不安全
        }
        // 检查2：是否在同一个对角线上？
        // 如果 |row - i| == |col - pos[i]|，说明在对角线上
        if (abs(row - i) == abs(col - pos[i])) {
            return false;           // 对角线冲突，不安全
        }
    }
    return true;                    // 通过所有检查，安全
}

// 回溯搜索函数：尝试在第 row 行放置皇后
// 参数 row：当前正在处理的行号（0 ~ N-1）
// 当 row == N 时，说明前 N 行都已经成功放置，找到一个解
void solveEightQueens(int row) {
    // 【终止条件】所有行都放好了皇后，找到一个解
    if (row == N) {
        queenSolutionCount++;

        // 如果是第一个解，打印棋盘布局
        if (!queenFirstPrinted) {
            queenFirstPrinted = true;
            cout << "┌─────────────────────────────────────┐" << endl;
            cout << "│       八皇后问题 —— 第一个解        │" << endl;
            cout << "├─────────────────────────────────────┤" << endl;
            cout << "│  棋盘布局 (Q=皇后, .=空格)          │" << endl;
            cout << "│                                     │" << endl;
            for (int i = 0; i < N; i++) {
                cout << "│  ";
                for (int j = 0; j < N; j++) {
                    if (pos[i] == j) {
                        cout << " Q ";   // 该位置有皇后
                    } else {
                        cout << " · ";   // 该位置为空
                    }
                }
                // 输出该行皇后的列号
                cout << "  ← 第" << i + 1 << "行皇后在第" << pos[i] + 1 << "列";
                cout << endl;
            }
            cout << "└─────────────────────────────────────┘" << endl;
            cout << endl;
        }
        return;
    }

    // 【回溯搜索】在第 row 行尝试所有可能的列位置
    for (int col = 0; col < N; col++) {
        // 【剪枝】只有在安全的位置才继续搜索
        if (isSafe(row, col)) {
            pos[row] = col;                 // ② 试探：放置皇后
            solveEightQueens(row + 1);      // ③ 递归：处理下一行
            // ④ 撤销：pos[row] 会在下一轮循环中被覆盖，无需显式清除
        }
    }
}

// 八皇后问题的入口函数
void solveEightQueensProblem() {
    cout << "╔══════════════════════════════════════════════╗" << endl;
    cout << "║     例题1：八皇后问题（回溯法）               ║" << endl;
    cout << "║     8×8 棋盘，放8个皇后，互不攻击             ║" << endl;
    cout << "╚══════════════════════════════════════════════╝" << endl;
    cout << endl;

    // 初始化
    queenSolutionCount = 0;
    queenFirstPrinted = false;

    // 从第 0 行开始搜索
    solveEightQueens(0);

    // 输出统计结果
    cout << "══════════════════════════════════════" << endl;
    cout << "  八皇后问题总共有 " << queenSolutionCount << " 种不同的解法。" << endl;
    cout << "══════════════════════════════════════" << endl;
    cout << endl;
}


// ================================================================
// 例题2：组合输出（回溯法）
// ================================================================
// 问题描述：
//   从 1 到 n 的整数中选出 r 个数，输出所有可能的组合。
//   组合不考虑顺序（{1,2,3} 和 {3,2,1} 是同一组合），
//   按字典序从小到大输出。
//
// 回溯思路：
//   使用 dfs(start, depth) 回溯框架：
//   - start：从哪个数开始选（保证递增，避免重复）
//   - depth：已经选了几个数（当 depth == r 时输出）
//
// 剪枝策略：
//   如果剩余可选的数字数量 < 还需要的数量，提前返回
//   即：n - start + 1 < r - depth 时剪枝
//
// 为什么 start 参数能避免重复？
//   例如从1~5选3个，选择1后，下一个只能从2开始选，
//   这样就保证了组合中的数字是递增的，不会出现 {3,1,2} 这样的重复。
// ================================================================

int n_comb, r_comb;                 // n: 总数, r: 要选的数量
int comb[25];                       // 存储当前组合的数组
int combCount = 0;                  // 组合数量计数器

// 回溯搜索函数：生成组合
// 参数 start：下一个候选数字从 start 开始（保证递增）
// 参数 depth：当前已经选择了几个数字
void dfsCombine(int start, int depth) {
    // 【终止条件】已经选够了 r 个数，输出当前组合
    if (depth == r_comb) {
        combCount++;
        cout << "  ";
        for (int i = 0; i < r_comb; i++) {
            cout << comb[i];
            if (i < r_comb - 1) cout << " ";
        }
        cout << endl;
        return;
    }

    // 【回溯搜索】从 start 开始尝试每一个候选数字
    for (int i = start; i <= n_comb; i++) {
        // 【剪枝优化】如果剩余可选的数字不够凑齐 r 个
        // 剩余可选个数 = n_comb - i + 1
        // 还需要选个数 = r_comb - depth
        if (n_comb - i + 1 < r_comb - depth) {
            break;  // 剪枝：剩下的数不够了，直接退出循环
        }

        comb[depth] = i;                    // ② 试探：选择数字 i
        dfsCombine(i + 1, depth + 1);       // ③ 递归：从 i+1 开始选下一个数
        // ④ 撤销：comb[depth] 会在下一轮循环被覆盖，无需显式清除
    }
}

// 组合输出的入口函数
void solveCombination() {
    // 测试参数：从 1~5 中选 3 个
    n_comb = 5;
    r_comb = 3;

    cout << "╔══════════════════════════════════════════════╗" << endl;
    cout << "║     例题2：组合输出（回溯法）                 ║" << endl;
    cout << "║     从 1~" << n_comb << " 中选 " << r_comb << " 个数的所有组合              ║" << endl;
    cout << "╚══════════════════════════════════════════════╝" << endl;
    cout << endl;

    // 理论上组合数：C(5,3) = 5!/(3!*2!) = 10
    int theoryCount = 1;
    for (int i = 1; i <= r_comb; i++) {
        theoryCount = theoryCount * (n_comb - r_comb + i) / i;
    }
    cout << "  理论组合数：C(" << n_comb << "," << r_comb << ") = " << theoryCount << endl;
    cout << "  ───────────────────────────────────────" << endl;

    combCount = 0;
    dfsCombine(1, 0);                       // 从数字 1 开始选

    cout << "  ───────────────────────────────────────" << endl;
    cout << "  实际输出 " << combCount << " 种组合（与理论值一致：";
    cout << (combCount == theoryCount ? "✓" : "✗ 不一致！") << "）" << endl;
    cout << endl;
}


