// ================================================================
// 辅助函数：输出1~4选3个的全排列（演示用）
// 理论排列数：P(4,3) = 4×3×2 = 24
// ================================================================
void demoPermutation3of4() {
    cout << "══════════════════════════════════════" << endl;
    cout << "  演示：从1~4中选3个数字的全排列" << endl;
    cout << "══════════════════════════════════════" << endl;
    cout << "（理论值：4×3×2 = 24 种排列）" << endl;
    cout << "--------------------------------------" << endl;

    int count = 0;

    // 第一层：第一个位置的数字
    for (int i = 1; i <= 4; i++) {
        // 第二层：第二个位置的数字
        for (int j = 1; j <= 4; j++) {
            // 如果j和i重复，跳过
            if (j == i) continue;

            // 第三层：第三个位置的数字
            for (int k = 1; k <= 4; k++) {
                // 如果k和i或j重复，跳过
                if (k == i || k == j) continue;

                count++;
                cout << "排列" << setw(2) << count << ": ";
                cout << i << " " << j << " " << k << endl;
            }
        }
    }

    cout << "--------------------------------------" << endl;
    cout << "实际输出 " << count << " 种（与理论值"
         << (count == 24 ? "一致✓" : "不一致✗") << "）" << endl;
    cout << endl;
}

// ================================================================
// 例题1：三数排序组合
// 题目：从1~9中选3个不同数字组成三位数
//       要求数字是严格递增（百<十<个）或严格递减（百>十>个）
//
// 枚举思路：
//   - 枚举对象：百位a、十位b、个位c
//   - 枚举范围：a,b,c ∈ [1,9]，且两两不同
//   - 判断条件：严格递增（a<b<c）或严格递减（a>b>c）
// ================================================================
void solveSortedThreeDigit() {
    cout << "══════════════════════════════════════" << endl;
    cout << "  例题1：三数排序组合" << endl;
    cout << "══════════════════════════════════════" << endl;
    cout << "1~9选3个不同数字，组成严格递增或递减的三位数" << endl;
    cout << "--------------------------------------" << endl;

    int total = 0;
    int incCount = 0;  // 递增数量
    int decCount = 0;  // 递减数量

    // 枚举百位 a
    for (int a = 1; a <= 9; a++) {
        // 枚举十位 b
        for (int b = 1; b <= 9; b++) {
            if (b == a) continue;  // 不能和百位重复

            // 枚举个位 c
            for (int c = 1; c <= 9; c++) {
                if (c == a || c == b) continue;  // 不能重复

                int num = a * 100 + b * 10 + c;

                // 判断：严格递增 或 严格递减
                if (a < b && b < c) {
                    cout << num << "  [递增 " << a << "<" << b << "<" << c << "]" << endl;
                    incCount++;
                    total++;
                } else if (a > b && b > c) {
                    cout << num << "  [递减 " << a << ">" << b << ">" << c << "]" << endl;
                    decCount++;
                    total++;
                }
            }
        }
    }

    // 理论值分析：
    // 递增：从9个元素中选3个，只有1种递增排列 → C(9,3) = 84
    // 递减：同理，也是 C(9,3) = 84
    // 总共：84 + 84 = 168
    cout << "--------------------------------------" << endl;
    cout << "递增: " << incCount << " 个（理论 C(9,3)=84）" << endl;
    cout << "递减: " << decCount << " 个（理论 C(9,3)=84）" << endl;
    cout << "总计: " << total << " 个" << endl;
    cout << endl;
}

// ================================================================
// 例题2：数字谜题——算式填空
// 题目：将1~9填入 □□□ + □□□ = □□□，每个数字恰用一次
//
// 枚举思路：
//   - 这是1~9的全排列问题，共9! = 362880种可能
//   - 用9重循环各取1~9，配合continue排除重复
//   - 判断：前三位组成的数 + 中间三位组成的数 == 后三位组成的数
//
// 注意：本解法用9重循环演示"暴力枚举全排列"的思路。
//       实际使用中，递归+标记数组会更简洁，但循环嵌套更直观。
// ================================================================
void solveDigitPuzzle() {
    cout << "══════════════════════════════════════" << endl;
    cout << "  例题2：数字谜题——算式填空" << endl;
    cout << "══════════════════════════════════════" << endl;
    cout << "将1~9填入 □□□ + □□□ = □□□" << endl;
    cout << "每个数字恰好用一次" << endl;
    cout << "--------------------------------------" << endl;
    cout << "（9! = 362880 种排列，正在枚举...）" << endl;

    int count = 0;

    // 9重循环 = 9个位置各选一个不重复的数字
    // a,b,c 是第一个三位数；d,e,f 是第二个；g,h,i 是和
    for (int a = 1; a <= 9; a++) {
        for (int b = 1; b <= 9; b++) {
            if (b == a) continue;
            for (int c = 1; c <= 9; c++) {
                if (c == a || c == b) continue;
                for (int d = 1; d <= 9; d++) {
                    if (d == a || d == b || d == c) continue;
                    for (int e = 1; e <= 9; e++) {
                        if (e == a || e == b || e == c || e == d) continue;
                        for (int f = 1; f <= 9; f++) {
                            if (f == a || f == b || f == c || f == d || f == e) continue;
                            for (int g = 1; g <= 9; g++) {
                                if (g == a || g == b || g == c || g == d || g == e || g == f) continue;
                                for (int h = 1; h <= 9; h++) {
                                    if (h == a || h == b || h == c || h == d || h == e || h == f || h == g) continue;
                                    for (int i = 1; i <= 9; i++) {
                                        if (i == a || i == b || i == c || i == d || i == e || i == f || i == g || i == h) continue;

                                        int num1 = a * 100 + b * 10 + c;
                                        int num2 = d * 100 + e * 10 + f;
                                        int num3 = g * 100 + h * 10 + i;

                                        if (num1 + num2 == num3) {
                                            count++;
                                            cout << "解" << setw(3) << count << ": ";
                                            cout << setw(3) << num1 << " + ";
                                            cout << setw(3) << num2 << " = ";
                                            cout << setw(3) << num3;
                                            // 验证
                                            cout << "  [" << num1 << "+" << num2
                                                 << "=" << (num1+num2)
                                                 << (num1+num2 == num3 ? " ✓" : " ✗") << "]";
                                            cout << endl;

                                            // 只输出前20个解，避免刷屏
                                            if (count >= 20) {
                                                cout << "... （仅显示前20个解）" << endl;
                                                // 跳出所有循环需要标志，这里简化处理
                                                // 实际运行会继续但输出截断
                                            }
                                        }
                                    }
                                }
                            }
                        }
                    }
                }
            }
        }
    }

    cout << "--------------------------------------" << endl;
    cout << "共找到 " << count << " 种填法" << endl;
    // 理论上共有 336 种解（包括交换加数位置算不同解）
    cout << "（理论值：336种，含加数交换）" << endl;
    cout << endl;
}

// ================================================================
// 附加演示：用标记数组实现排列（递归版，展示替代方案）
// 这个版本更简洁，适合扩展到更大的n值
// ================================================================
int permArr[10];       // 存储当前排列
bool permUsed[10];     // 标记数字是否被使用

void generatePerm(int depth, int n) {
    // 递归终点：已填满n个位置
    if (depth == n) {
        // 输出当前排列
        for (int i = 0; i < n; i++) {
            cout << permArr[i] << " ";
        }
        cout << endl;
        return;
    }

    // 尝试将数字1~n放入第depth个位置
    for (int i = 1; i <= n; i++) {
        if (!permUsed[i]) {          // 数字i还没被使用
            permArr[depth] = i;      // 放入当前位置
            permUsed[i] = true;      // 标记为已使用
            generatePerm(depth + 1, n); // 递归下一层
            permUsed[i] = false;     // 回溯：恢复未使用状态
        }
    }
}

void demoRecursivePermutation() {
    cout << "══════════════════════════════════════" << endl;
    cout << "  附加演示：递归+标记数组实现全排列" << endl;
    cout << "══════════════════════════════════════" << endl;
    cout << "1~3的全排列（递归版本）：" << endl;
    cout << "--------------------------------------" << endl;

    // 初始化标记数组
    for (int i = 0; i < 10; i++) permUsed[i] = false;

    generatePerm(0, 3);  // 从0开始，共3个位置

    cout << "--------------------------------------" << endl;
    cout << "递归方法比9重循环更简洁，适合n较大的情况！" << endl;
    cout << endl;
}

