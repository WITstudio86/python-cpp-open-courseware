#include <iostream>
#include <iomanip>
using namespace std;

// ================================================================
// 例题1：蜗牛爬井
// 题目：井深H米，白天爬A米，晚上滑B米（A>B），几天出井？
//
// 模拟思路：
//   - 状态变量：当前位置 pos（从井底往上算到井口的距离）
//   - 循环：while (pos > 0)，每天迭代
//   - 白天先爬，如果白天就出井了直接 break
//   - 晚上再下滑（只有没出井才下滑）
//
// 数学分析（验证用）：
//   实际上，最后一天爬A米出井，前面每天净爬(A-B)米
//   天数 = ceil((H-A) / (A-B)) + 1（但模拟法更直观）
// ================================================================
void solveSnailClimb() {
    cout << "══════════════════════════════════════" << endl;
    cout << "  例题1：蜗牛爬井" << endl;
    cout << "══════════════════════════════════════" << endl;

    long long H, A, B;
    cout << "请输入井深 H（米）: ";
    cin >> H;
    cout << "请输入白天爬升距离 A（米）: ";
    cin >> A;
    cout << "请输入夜间下滑距离 B（米，B < A）: ";
    cin >> B;

    // 参数校验
    if (A <= B) {
        cout << "错误：白天爬升必须大于夜间下滑（A > B）！" << endl;
        return;
    }

    long long pos = H;   // 当前位置 = 距离井口的深度（米）
    int day = 0;          // 天数计数器
    bool debug = false;

    cout << "\n是否显示逐日模拟过程？(1=是, 0=否): ";
    cin >> debug;

    if (debug) {
        cout << "\n--- 逐日模拟过程 ---" << endl;
        cout << "初始位置：井底，距离井口 " << H << " 米" << endl;
    }

    // 模拟每一天
    while (pos > 0) {
        day++;

        // 白天爬升
        pos -= A;
        if (debug) cout << "第 " << setw(3) << day << " 天：白天爬 " << A
                        << " 米 → 距离井口 " << max(0LL, pos) << " 米";

        // 如果已经出井，结束
        if (pos <= 0) {
            if (debug) cout << " 【出井！】" << endl;
            break;
        }

        // 晚上下滑（只有没出井才下滑）
        pos += B;
        if (debug) cout << "，晚上滑 " << B << " 米 → 距离井口 " << pos
                        << " 米" << endl;
    }

    cout << "\n--------------------------------------" << endl;
    cout << "结果：蜗牛在第 " << day << " 天成功爬出井口！" << endl;

    // 数学验证
    // 最后一天爬A米，前面天数需要净爬 (H-A) 米，每天净爬 (A-B) 米
    // 前面需要的天数 = ceil((H-A) / (A-B))
    long long netPerDay = A - B;
    long long preDays = (H - A + netPerDay - 1) / netPerDay;
    if (preDays < 0) preDays = 0;
    long long mathDays = preDays + 1;
    if (A >= H) mathDays = 1;

    cout << "数学验证：" << endl;
    cout << "  每天净爬升 = " << netPerDay << " 米" << endl;
    cout << "  前面需要 " << preDays << " 天，最后1天冲刺" << endl;
    cout << "  公式计算天数 = " << mathDays
         << "（与模拟结果" << (mathDays == day ? "一致 ✓" : "不一致 ✗") << "）"
         << endl;
    cout << endl;
}

// ================================================================
// 例题2：猴子吃桃
// 题目：猴子每天吃一半多一个，第N天剩1个，第一天原有多少？
//
// 模拟思路（逆向）：
//   - 从第N天开始倒推
//   - 递推公式：前一天的桃子 = (当天桃子 + 1) × 2
//   - 因为：当天桃子 = 前一天桃子/2 - 1
//          → 前一天桃子 = (当天桃子 + 1) × 2
// ================================================================
void solveMonkeyPeach() {
    cout << "══════════════════════════════════════" << endl;
    cout << "  例题2：猴子吃桃" << endl;
    cout << "══════════════════════════════════════" << endl;
    cout << "猴子每天吃前一天剩下的一半多一个" << endl;
    cout << "问：第N天早上剩1个，第一天摘了多少？" << endl;
    cout << "--------------------------------------" << endl;

    int N;
    cout << "请输入天数 N（第N天早上剩1个）: ";
    cin >> N;

    if (N < 2) {
        cout << "N < 2 无意义，请重新运行。" << endl;
        return;
    }

    long long peach = 1;  // 第N天早上剩1个（使用 long long 防止溢出）

    // 打印初始状态
    cout << "\n逆向递推过程：" << endl;
    cout << "第 " << setw(2) << N << " 天早上: 剩 " << peach << " 个" << endl;

    // 逆推：从第N天推到第1天
    for (int day = N; day > 1; day--) {
        // 逆向递推公式：
        // 设前一天有 x 个，则当天剩 x - (x/2 + 1) = x/2 - 1
        // 所以 x = (当天剩 + 1) × 2
        peach = (peach + 1) * 2;

        cout << "第 " << setw(2) << (day - 1) << " 天早上: 剩 " << peach << " 个";
        if (day - 1 == 1) cout << " ← 这就是第一天的总数！";
        cout << endl;
    }

    cout << "--------------------------------------" << endl;
    cout << "结果：第一天猴子共摘了 " << peach << " 个桃子！" << endl;
    cout << endl;

    // 正向验证
    cout << "正向验证（从第1天到第N天）：" << endl;
    long long verify = peach;
    for (int day = 1; day < N; day++) {
        long long eat = verify / 2 + 1;              // 吃掉的
        verify = verify - eat;                        // 剩下的
        cout << "  第 " << day << " 天：有" << setw(8) << (verify + eat)
             << "个 → 吃" << setw(8) << eat
             << "个 → 剩" << setw(8) << verify << "个" << endl;
    }
    cout << "  第 " << N << " 天早上：剩 " << verify << " 个";
    if (verify == 1)
        cout << "（正确！✓）" << endl;
    else
        cout << "（不对！应该是1个）" << endl;
    cout << endl;
}

// ================================================================
// 附加演示：while vs for 的区别
// ================================================================
void demoWhileVsFor() {
    cout << "══════════════════════════════════════" << endl;
    cout << "  附加演示：while 循环 vs for 循环" << endl;
    cout << "══════════════════════════════════════" << endl;

    // 示例：数到第一个能被17整除的数
    cout << "【while 循环】找到第一个能被17整除的100以上的数：" << endl;
    int n = 100;
    while (n % 17 != 0) {
        n++;
    }
    cout << n << "（" << n << " = 17 × " << n / 17 << "）" << endl;

    // while 适合"不知道要循环多少次"的场景
    cout << "\n【对比总结】" << endl;
    cout << "  while：条件循环 → \"直到...为止\"" << endl;
    cout << "  for：  计数循环 → \"做N次\"" << endl;
    cout << endl;
}

