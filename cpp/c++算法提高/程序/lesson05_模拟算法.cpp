// 附加演示：模拟一个简单的人口增长过程
// 人口每年增长10%，问多少年翻倍？
// ================================================================
void demoPopulation() {
    cout << "══════════════════════════════════════" << endl;
    cout << "  附加演示：人口增长模拟" << endl;
    cout << "══════════════════════════════════════" << endl;
    cout << "每年增长10%，问多少年翻倍？" << endl;

    double population = 1000.0;
    double target = 2000.0;
    int years = 0;

    cout << "年份  |  人口" << endl;
    cout << "------+----------" << endl;
    cout << "0     |  " << fixed << setprecision(0) << population << endl;

    while (population < target) {
        years++;
        population *= 1.10;  // 增长10%
        cout << setw(4) << years << "   |  " << setw(8)
             << setprecision(0) << population << endl;
    }

    cout << "--------------------------------------" << endl;
    cout << "结果：需要 " << years << " 年翻倍" << endl;
    cout << "（数学精确解：log(2)/log(1.10) ≈ 7.27 年，即第8年翻倍）" << endl;
    cout << endl;
}

