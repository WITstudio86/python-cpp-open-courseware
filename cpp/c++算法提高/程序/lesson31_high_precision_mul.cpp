#include <iostream>
#include <string>
#include <vector>
#include <algorithm>
using namespace std;

/**
 * 高精度乘法：计算两个大正整数的乘积
 *
 * 算法步骤：
 *   1. 将两个字符串倒序存入数组 a[] 和 b[]（个位在索引 0）
 *   2. 双层循环：c[i+j] += a[i] * b[j]
 *   3. 统一处理进位：c[i+1] += c[i] / 10; c[i] %= 10
 *   4. 去除前导零，拼接结果字符串
 *
 * @param num1  第一个大整数（字符串形式）
 * @param num2  第二个大整数（字符串形式）
 * @return      乘积的字符串表示
 */
string high_precision_multiply(const string &num1, const string &num2) {
    // 特殊情况：任何一个数为 0，结果就是 0
    if (num1 == "0" || num2 == "0") return "0";

    int len1 = num1.size();
    int len2 = num2.size();

    // 倒序存储：索引 0 存个位，索引 1 存十位，以此类推
    // 例如 "123" → a[0]=3, a[1]=2, a[2]=1
    vector<int> a(len1), b(len2);
    for (int i = 0; i < len1; i++) {
        a[i] = num1[len1 - 1 - i] - '0';  // 字符转数字
    }
    for (int i = 0; i < len2; i++) {
        b[i] = num2[len2 - 1 - i] - '0';
    }

    // 结果数组：两个数相乘，结果最多有 len1 + len2 位
    // 例如：999 × 999 = 998001，3位×3位 = 6位
    vector<int> c(len1 + len2, 0);

    // ============================================================
    // 第一步：逐位相乘并累加到对应位置
    // 核心公式：c[i+j] += a[i] * b[j]
    //
    // 原理（以 123 × 456 为例）：
    //   竖式中，123 的个位 3 乘以 456 的十位 5，得到 150
    //   这个 150 中的 5 实际上在百位（个位×十位 → 百位）
    //   即 c[0+1] += a[0]*b[1] → c[1] += 3*5 = 15
    // ============================================================
    for (int i = 0; i < len1; i++) {
        for (int j = 0; j < len2; j++) {
            c[i + j] += a[i] * b[j];
        }
    }

    // ============================================================
    // 第二步：统一处理进位
    // 从低位到高位依次处理：如果当前位 ≥ 10，则进位到高一位
    // 注意：循环到 len1+len2-1，因为最高位也可能产生进位
    // ============================================================
    for (int i = 0; i < len1 + len2; i++) {
        if (c[i] >= 10) {
            c[i + 1] += c[i] / 10;  // 进位部分加到高一位
            c[i] %= 10;              // 保留个位
        }
    }

    // ============================================================
    // 第三步：去除前导零
    // 结果数组的最后一个非零位置就是最高有效位
    // 从末尾向前找，跳过所有值为 0 的高位
    // ============================================================
    int pos = len1 + len2 - 1;
    while (pos > 0 && c[pos] == 0) {
        pos--;
    }

    // ============================================================
    // 第四步：将结果数组转换为字符串（从高位到低位）
    // ============================================================
    string result;
    for (int i = pos; i >= 0; i--) {
        result += char(c[i] + '0');  // 数字转字符
    }
    return result;
}

/**
 * 高精度加法：计算两个大正整数的和
 *
 * 算法步骤：
 *   1. 将两个字符串倒序存入数组（个位在索引 0）
 *   2. 从低位到高位逐位相加，同时处理进位
 *   3. 去除前导零，拼接结果字符串
 *
 * @param num1  第一个大整数（字符串形式）
 * @param num2  第二个大整数（字符串形式）
 * @return      和的字符串表示
 */
string high_precision_add(const string &num1, const string &num2) {
    int len1 = num1.size();
    int len2 = num2.size();
    int maxLen = max(len1, len2);

    // 倒序存储：统一到 maxLen 长度，不足的高位补 0
    vector<int> a(maxLen, 0), b(maxLen, 0);
    for (int i = 0; i < len1; i++) {
        a[i] = num1[len1 - 1 - i] - '0';
    }
    for (int i = 0; i < len2; i++) {
        b[i] = num2[len2 - 1 - i] - '0';
    }

    // 结果数组，可能比 maxLen 多 1 位（处理最高位进位）
    vector<int> c(maxLen + 1, 0);

    // 逐位相加，同时处理进位
    for (int i = 0; i < maxLen; i++) {
        c[i] += a[i] + b[i];
        if (c[i] >= 10) {
            c[i + 1] += c[i] / 10;
            c[i] %= 10;
        }
    }

    // 去除前导零
    int pos = maxLen;
    while (pos > 0 && c[pos] == 0) {
        pos--;
    }

    // 拼接结果（从高位到低位）
    string result;
    for (int i = pos; i >= 0; i--) {
        result += char(c[i] + '0');
    }
    return result;
}

/**
 * 阶乘之和：计算 S = 1! + 2! + 3! + ... + n!
 *
 * 算法思路：
 *   利用递推关系 fact(i) = fact(i-1) × i
 *   每次用高精度乘法计算当前阶乘，再用高精度加法累加到总和
 *   这样避免了每次重新计算阶乘，效率更高
 *
 * @param n  阶乘的最大项（n ≤ 50）
 * @return   阶乘之和的字符串表示
 */
string factorial_sum(int n) {
    if (n <= 0) return "0";

    string factorial = "1";   // 当前阶乘值，初始为 1! = 1
    string sum = "0";          // 累加和，初始为 0

    for (int i = 1; i <= n; i++) {
        // 计算 i! = (i-1)! × i
        // 将整数 i 转换为字符串参与高精度乘法
        string i_str = to_string(i);
        factorial = high_precision_multiply(factorial, i_str);

        // 累加到总和
        sum = high_precision_add(sum, factorial);
    }

    return sum;
}

