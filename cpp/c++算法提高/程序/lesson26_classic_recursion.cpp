    cout << endl;
    cout << "┌──────────────────────────────────────────────────────────┐" << endl;
    cout << "│  第一部分：汉诺塔问题（Hanoi Tower）                       │" << endl;
    cout << "└──────────────────────────────────────────────────────────┘" << endl;
    cout << endl;

    int n = 3;
    cout << "【测试】n = " << n << " 个盘子的汉诺塔移动步骤：" << endl;
    cout << "------------------------------------------------------------" << endl;
    cout << "说明：A = 起始柱  |  C = 目标柱  |  B = 辅助柱" << endl;
    cout << "目标：将 " << n << " 个盘子从 A 柱移动到 C 柱" << endl;
    cout << "------------------------------------------------------------" << endl;

    // 调用汉诺塔递归函数，打印每一步移动
    hanoi(n, 'A', 'C', 'B');

    // 计算并显示总移动次数
    int moves = hanoi_moves(n);
    cout << "------------------------------------------------------------" << endl;
    cout << "总移动次数：T(" << n << ") = 2^" << n << " - 1 = " << moves << " 步" << endl;
    cout << "理论验证：2^" << n << " - 1 = " << (1 << n) - 1 << " ✓" << endl;

    // ========================================================================
    // 第二部分：扩展示例 —— n=4 时只显示理论次数
    // ========================================================================
    cout << endl;
    cout << "【扩展】n = 4 时的理论分析：" << endl;
    cout << "  T(4) = 2^4 - 1 = " << hanoi_moves(4) << " 步" << endl;
    cout << "  递推关系：T(4) = 2 * T(3) + 1 = 2 * " << moves << " + 1 = "
         << 2 * moves + 1 << " 步" << endl;
    cout << "  可见随着 n 增大，移动次数呈指数增长！" << endl;

    // ========================================================================
    // 第三部分：最大公约数（辗转相除法）演示
    // ========================================================================
    cout << endl;
    cout << "┌──────────────────────────────────────────────────────────┐" << endl;
    cout << "│  第二部分：最大公约数（辗转相除法 / 欧几里得算法）         │" << endl;
    cout << "└──────────────────────────────────────────────────────────┘" << endl;
    cout << endl;

    int a = 48, b = 18;
    cout << "【测试】计算 gcd(" << a << ", " << b << ") 的详细过程：" << endl;
    cout << "------------------------------------------------------------" << endl;
    cout << "辗转相除法原理：gcd(a, b) = gcd(b, a % b)" << endl;
    cout << "不断用较小数除较大数取余，直到余数为 0" << endl;
    cout << "------------------------------------------------------------" << endl;
    cout << endl;
    cout << "递归调用过程（缩进表示递归深度）：" << endl;
    cout << endl;

    // 调用带步骤输出的 GCD 函数
    int result = gcd_with_steps(a, b, 0);

    cout << endl;
    cout << "------------------------------------------------------------" << endl;
    cout << "结果：gcd(" << a << ", " << b << ") = " << result << endl;

    // 验证结果
    cout << "验证：" << a << " ÷ " << result << " = " << a / result
         << "（整除），" << b << " ÷ " << result << " = " << b / result
         << "（整除）✓" << endl;

    // ========================================================================
    // 第四部分：更多 GCD 测试样例
    // ========================================================================
    cout << endl;
    cout << "【更多测试样例】" << endl;
    cout << "------------------------------------------------------------" << endl;

    // 测试样例数组
    int test_pairs[][2] = {
        {56, 42},
        {100, 25},
        {17, 13},    // 互质的情况
        {64, 48},
        {270, 192}
    };
    int num_tests = sizeof(test_pairs) / sizeof(test_pairs[0]);

    for (int i = 0; i < num_tests; i++) {
        int x = test_pairs[i][0];
        int y = test_pairs[i][1];
        int g = gcd(x, y);
        cout << "  gcd(" << x << ", " << y << ") = " << g;
        // 对互质情况加注释
        if (g == 1) {
            cout << "  （" << x << " 和 " << y << " 互质）";
        }
        cout << endl;
    }

    // ========================================================================
    // 总结
    // ========================================================================
    cout << endl;
    cout << "============================================================" << endl;
    cout << "  课程总结" << endl;
    cout << "============================================================" << endl;
    cout << "  1. 汉诺塔递归核心：把 n 个盘子的问题分解为移动 n-1 个盘子" << endl;
    cout << "     的子问题，体现了「分而治之」的思想。" << endl;
    cout << "  2. 汉诺塔时间复杂度为 O(2^n)，是指数级增长，n=64 时" << endl;
    cout << "     即使每秒移动一次也需要约 5849 亿年！" << endl;
    cout << "  3. 辗转相除法递归核心：gcd(a,b) = gcd(b, a%b)，" << endl;
    cout << "     每次递归问题规模急剧缩小，时间复杂度为 O(log n)。" << endl;
    cout << "  4. 编写递归函数的关键：明确基准条件、确保每次递归" << endl;
    cout << "     都向基准条件靠近、相信递归会正确完成子任务。" << endl;
    cout << "============================================================" << endl;

    return 0;
