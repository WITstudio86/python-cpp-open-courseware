/*
 * ============================================================================
 * 第28课：快速幂 —— 高效的指数运算
 * ============================================================================
 *
 * 【课程目标】
 *   学习快速幂算法，掌握如何高效地计算 a^b mod m，以及如何将快速幂思想
 *   推广到矩阵运算中，解决斐波那契数列等经典问题。
 *
 * 【知识点】
 *   1. 朴素幂运算的问题：计算 a^b 需要 O(b) 次乘法，b 很大时效率极低
 *   2. 快速幂核心思想：利用指数的二进制拆分，将 b 次乘法降为 O(log b) 次
 *   3. 递归快速幂：基于分治思想 "折半——乘方——合并"
 *   4. 迭代快速幂：基于二进制位 "逐位判断——累积——翻倍"
 *   5. 矩阵快速幂：将快速幂思想用于矩阵乘法，加速线性递推
 *   6. 应用：大数取模运算、斐波那契数列第 n 项、图论路径计数等
 *
 * 【算法复杂度】
 *   - 快速幂：   时间复杂度 O(log b)，空间复杂度 O(log b) 递归 / O(1) 迭代
 *   - 矩阵快速幂：时间复杂度 O(k³ log n)，其中 k 为矩阵阶数
 *
 * 【适用场景】
 *   当指数 b 非常大（如 b = 10^9 甚至 10^18）时，朴素算法完全不可行，
 *   而快速幂只需几十次乘法即可完成计算。
 *
 * 【学情提示】
 *   本课面向中小学生，要求已掌握循环、函数、数组基础，了解取模运算。
 *   建议先理解「折半」思想（分治），再引入二进制视角（迭代）。
 *   矩阵快速幂作为拓展内容，适合学有余力的同学。
 *
 * ============================================================================
 */

#include <iostream>
#include <vector>
using namespace std;

// 取模常量，用于防止结果溢出
const long long MOD = 1000000007LL;

// ============================================================================
// 第一部分：递归快速幂
// ============================================================================

/*
 * fastPowerRecursive —— 递归实现快速幂
 *
 * 参数：
 *   a   : 底数（base）
 *   b   : 指数（exponent），要求 b >= 0
 *   mod : 模数，防止溢出
 *
 * 返回值： (a^b) % mod
 *
 * 【算法思路（分治）】
 *   把 a^b 拆成两半：
 *     - 如果 b 是偶数：a^b = a^(b/2) * a^(b/2)
 *     - 如果 b 是奇数：a^b = a^(b/2) * a^(b/2) * a
 *   先递归算出 half = a^(b/2)，然后：
 *     - b 为偶数时：result = half * half
 *     - b 为奇数时：result = half * half * a
 *   每一步都取模，防止数字过大溢出。
 *
 * 【递归终止条件】
 *   b == 0 时，任何数的 0 次幂都等于 1（包括 0^0，这里约定返回 1）。
 *
 * 【举例】
 *   计算 2^10：
 *     fastPowerRecursive(2, 10)
 *       → half = fastPowerRecursive(2, 5) = 32
 *       → half 是奇数时多乘一个 a，此处 2^5 = 2^2 * 2^2 * 2 = 16 * 2 = 32 ✓
 *       → 2^10 = 32 * 32 = 1024 ✓
 *   总共只递归了约 log₂(10) ≈ 4 层！
 */
long long fastPowerRecursive(long long a, long long b, long long mod) {
    // 递归终止条件：任何数的 0 次幂等于 1
    if (b == 0) {
        return 1;
    }

    // 分治：先计算 a^(b/2)
    long long half = fastPowerRecursive(a, b / 2, mod);

    // 合并：a^b = half^2（当 b 为偶数时）
    long long result = (half * half) % mod;

    // 如果 b 是奇数，还需要再乘一个 a
    if (b % 2 == 1) {
        result = (result * (a % mod)) % mod;
    }

    return result;
}

// ============================================================================
// 第二部分：迭代快速幂
// ============================================================================

/*
 * fastPowerIterative —— 迭代（循环）实现快速幂
 *
 * 参数：
 *   a   : 底数
 *   b   : 指数，要求 b >= 0
 *   mod : 模数
 *
 * 返回值： (a^b) % mod
 *
 * 【算法思路（二进制拆分）】
 *   把指数 b 写成二进制形式。例如 b = 13，二进制是 1101：
 *     a^13 = a^(8+4+0+1) = a^8 * a^4 * a^0 * a^1
 *   其中 a^0 不参与乘积。
 *
 *   我们维护两个变量：
 *     - base : 代表 a^(2^i)，每轮平方一次（对应二进制位左移）
 *     - result: 累积结果，当 b 的当前最低位是 1 时才乘入
 *
 *   每次循环把 b 右移一位（除以 2），检查最低位。
 *
 * 【举例（迭代过程）】
 *   计算 3^13 mod 100：
 *     初始：base = 3, b = 13(二进制1101), result = 1
 *     第1轮：b 最低位是 1 → result = (1 * 3) % 100 = 3
 *            base = (3 * 3) % 100 = 9, b >>= 1 → b = 6
 *     第2轮：b 最低位是 0 → 不更新 result
 *            base = (9 * 9) % 100 = 81, b >>= 1 → b = 3
 *     第3轮：b 最低位是 1 → result = (3 * 81) % 100 = 43
 *            base = (81 * 81) % 100 = 61, b >>= 1 → b = 1
 *     第4轮：b 最低位是 1 → result = (43 * 61) % 100 = 23
 *            base = (61 * 61) % 100 = 21, b >>= 1 → b = 0
 *     循环结束，返回 23。验证：3^13 = 1594323，1594323 % 100 = 23 ✓
 *
 * 【迭代 vs 递归】
 *   迭代版本更省内存（没有递归调用栈），推荐在竞赛中使用。
 */
long long fastPowerIterative(long long a, long long b, long long mod) {
    // 先把底数取模，避免 a 本身过大
    a = a % mod;
    long long result = 1;

    // 当指数 b 还没变成 0 时，继续循环
    while (b > 0) {
        // 判断 b 的二进制最低位是否为 1（即 b 是否为奇数）
        if (b & 1) {  // 等价于 if (b % 2 == 1)
            result = (result * a) % mod;
        }

        // 底数平方，对应二进制位左移
        a = (a * a) % mod;

        // 指数右移一位（相当于 b = b / 2）
        b >>= 1;
    }

    return result;
}

