// 第三部分：矩阵快速幂（用于求解斐波那契数列）
// ============================================================================

/*
 * 矩阵结构体 —— 定义一个 2×2 的矩阵
 *
 * 斐波那契数列与矩阵的关系：
 *   [ F(n+1) ]   =   [ 1  1 ]^n   ×   [ F(1) ]
 *   [ F(n)   ]       [ 1  0 ]         [ F(0) ]
 *
 *   即：
 *   [ F(n+1) ]   =   [ 1  1 ]^n   ×   [ 1 ]
 *   [ F(n)   ]       [ 1  0 ]         [ 0 ]
 *
 *   其中 F(0) = 0, F(1) = 1
 *   所以 F(n) = matrixPower( [[1,1],[1,0]], n ) 的 [0][1]（或 [1][0]）位置的值。
 *
 *   更简洁的递推：把 n 次幂作用在向量 [F(1), F(0)] = [1, 0] 上，
 *   得到 [F(n+1), F(n)]，取第二个分量即可。
 */
struct Matrix {
    long long m[2][2];  // 2×2 矩阵的四个元素

    // 构造函数：初始化为零矩阵
    Matrix() {
        m[0][0] = m[0][1] = m[1][0] = m[1][1] = 0;
    }
};

/*
 * matrixMultiply —— 两个 2×2 矩阵相乘
 *
 * 参数：
 *   A, B : 两个 2×2 矩阵
 *   mod  : 模数
 *
 * 返回值： C = A × B（取模后）
 *
 * 【矩阵乘法公式（2×2）】
 *   C[0][0] = A[0][0]*B[0][0] + A[0][1]*B[1][0]
 *   C[0][1] = A[0][0]*B[0][1] + A[0][1]*B[1][1]
 *   C[1][0] = A[1][0]*B[0][0] + A[1][1]*B[1][0]
 *   C[1][1] = A[1][0]*B[0][1] + A[1][1]*B[1][1]
 *
 *   每一步乘法后立即取模，防止溢出。
 */
Matrix matrixMultiply(const Matrix &A, const Matrix &B, long long mod) {
    Matrix C;
    C.m[0][0] = (A.m[0][0] * B.m[0][0] + A.m[0][1] * B.m[1][0]) % mod;
    C.m[0][1] = (A.m[0][0] * B.m[0][1] + A.m[0][1] * B.m[1][1]) % mod;
    C.m[1][0] = (A.m[1][0] * B.m[0][0] + A.m[1][1] * B.m[1][0]) % mod;
    C.m[1][1] = (A.m[1][0] * B.m[0][1] + A.m[1][1] * B.m[1][1]) % mod;
    return C;
}

/*
 * matrixPower —— 矩阵快速幂
 *
 * 参数：
 *   base : 底矩阵（2×2）
 *   exp  : 指数（幂次）
 *   mod  : 模数
 *
 * 返回值： base^exp（取模后）
 *
 * 【算法思路】
 *   与整数快速幂完全相同！只是把「乘法」替换为「矩阵乘法」，
 *   把「单位元 1」替换为「单位矩阵 I（对角线为 1，其余为 0）」。
 *
 *   迭代过程：
 *     result = I（单位矩阵）
 *     while (exp > 0):
 *         if (exp 最低位是 1): result = result × base
 *         base = base × base
 *         exp >>= 1
 */
Matrix matrixPower(Matrix base, long long exp, long long mod) {
    // 初始化结果为单位矩阵 I（相当于整数快速幂中的 result = 1）
    Matrix result;
    result.m[0][0] = 1;  // 单位矩阵：左上角为 1
    result.m[1][1] = 1;  // 单位矩阵：右下角为 1
    // 其余位置已经是 0，不需要额外设置

    while (exp > 0) {
        // 如果当前指数的最低位是 1，将当前底矩阵乘入结果
        if (exp & 1) {
            result = matrixMultiply(result, base, mod);
        }
        // 底矩阵自乘（平方），对应指数右移一位
        base = matrixMultiply(base, base, mod);
        exp >>= 1;
    }

    return result;
}

/*
 * fibonacciMatrix —— 使用矩阵快速幂求斐波那契数列第 n 项
 *
 * 参数：
 *   n : 要求第几项（n >= 0），即 F(0)=0, F(1)=1, F(2)=1, F(3)=2, ...
 *
 * 返回值： 斐波那契数列的第 n 项 F(n)
 *
 * 【推导过程】
 *   斐波那契递推公式：F(n) = F(n-1) + F(n-2)
 *   写成矩阵形式：
 *     [ F(n+1) ]   [ 1  1 ]   [ F(n)   ]
 *     [ F(n)   ] = [ 1  0 ] × [ F(n-1) ]
 *
 *   不断展开：
 *     [ F(n+1) ]   [ 1  1 ]^n   [ F(1) ]   [ 1  1 ]^n   [ 1 ]
 *     [ F(n)   ] = [ 1  0 ]   × [ F(0) ] = [ 1  0 ]   × [ 0 ]
 *
 *   所以 F(n) = 转移矩阵的 n 次幂 的 [1][0] 位置（或 [0][1]）的值。
 *   但注意：当 n=0 时，转移矩阵^0 = I，I[1][0] = 0 = F(0) ✓
 *           当 n=1 时，转移矩阵^1 = [[1,1],[1,0]]，[1][0] = 1 = F(1) ✓
 *
 *   因此直接用转移矩阵的 n 次幂结果取 [1][0] 即可得到 F(n)。
 */
long long fibonacciMatrix(long long n) {
    // 处理 n=0 的特殊情况
    if (n == 0) {
        return 0;
    }
    // 处理 n=1 的特殊情况
    if (n == 1) {
        return 1;
    }

    // 构造斐波那契转移矩阵 T = [[1, 1], [1, 0]]
    Matrix T;
    T.m[0][0] = 1;
    T.m[0][1] = 1;
    T.m[1][0] = 1;
    T.m[1][1] = 0;

    // 计算 T 的 n 次幂（注意这里是 n 次幂，不是 n-1）
    // 因为我们将 T^n 作用在 [F(1), F(0)]^T = [1, 0]^T 上
    Matrix Tn = matrixPower(T, n, MOD);

    // 结果 = Tn × [F(1), F(0)]^T 的第二个分量
    //      = Tn[1][0] * F(1) + Tn[1][1] * F(0)
    //      = Tn[1][0] * 1 + Tn[1][1] * 0
    //      = Tn[1][0]
    return Tn.m[1][0];
}

