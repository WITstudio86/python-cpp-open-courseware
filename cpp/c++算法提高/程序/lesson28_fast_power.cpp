int main() {
    cout << "================================================" << endl;
    cout << "  第28课：快速幂 —— 高效的指数运算" << endl;
    cout << "================================================" << endl;
    cout << endl;

    // ---------- 测试1：递归快速幂 ----------
    cout << "【测试1】递归快速幂：计算 2^10 mod " << MOD << endl;
    {
        long long a = 2, b = 10;
        long long ans_rec = fastPowerRecursive(a, b, MOD);
        cout << "  递归结果：2^10 mod " << MOD << " = " << ans_rec << endl;
        cout << "  验证：2^10 = " << (1LL << 10) << "（实际值）" << endl;
        cout << endl;
    }

    // ---------- 测试2：迭代快速幂 ----------
    cout << "【测试2】迭代快速幂：计算 3^13 mod " << MOD << endl;
    {
        long long a = 3, b = 13;
        long long ans_iter = fastPowerIterative(a, b, MOD);
        cout << "  迭代结果：3^13 mod " << MOD << " = " << ans_iter << endl;
        // 3^13 = 1594323, 1594323 % MOD = 1594323
        cout << "  验证：3^13 = 1594323（不取模时）" << endl;
        cout << endl;
    }

    // ---------- 测试3：大指数场景（递归 vs 迭代对比） ----------
    cout << "【测试3】大指数对比：计算 7^123456789 mod " << MOD << endl;
    {
        long long a = 7;
        long long b = 123456789LL;
        long long ans_rec = fastPowerRecursive(a, b, MOD);
        long long ans_iter = fastPowerIterative(a, b, MOD);
        cout << "  递归结果：" << ans_rec << endl;
        cout << "  迭代结果：" << ans_iter << endl;
        cout << "  两种方法结果一致：" << (ans_rec == ans_iter ? "是 ✓" : "否 ✗") << endl;
        cout << "  （指数高达 123456789，但仅需约 log₂(b) ≈ 27 次乘法！）" << endl;
        cout << endl;
    }

    // ---------- 测试4：递归与迭代多种底数指数对比 ----------
    cout << "【测试4】多种输入对比（递归 vs 迭代）" << endl;
    {
        // 测试数组：{底数, 指数}
        long long tests[][2] = {
            {5, 0},       // 任何数的 0 次幂 = 1
            {2, 5},       // 2^5 = 32
            {10, 3},      // 10^3 = 1000
            {7, 7},       // 7^7 = 823543
            {100, 5},     // 100^5 = 10^10
            {123456, 10}, // 较大底数
        };
        int testCount = sizeof(tests) / sizeof(tests[0]);

        for (int i = 0; i < testCount; i++) {
            long long a = tests[i][0];
            long long b = tests[i][1];
            long long r1 = fastPowerRecursive(a, b, MOD);
            long long r2 = fastPowerIterative(a, b, MOD);
            cout << "  " << a << "^" << b << " mod " << MOD << " → 递归: " << r1
                 << " | 迭代: " << r2
                 << " | " << (r1 == r2 ? "一致 ✓" : "不一致 ✗") << endl;
        }
        cout << endl;
    }

    // ---------- 测试5：矩阵快速幂求斐波那契数列 ----------
    cout << "【测试5】矩阵快速幂 —— 斐波那契数列" << endl;
    cout << "  斐波那契定义：F(0)=0, F(1)=1, F(n)=F(n-1)+F(n-2)" << endl;
    cout << endl;

    // 计算并输出前20项，验证矩阵快速幂的正确性
    cout << "  --- 前20项（递归法验证） ---" << endl;
    {
        // 先用简单的递推法计算出前20项作为"标准答案"
        long long fib[21];
        fib[0] = 0;
        fib[1] = 1;
        for (int i = 2; i <= 20; i++) {
            fib[i] = fib[i - 1] + fib[i - 2];
        }

        bool allCorrect = true;
        for (int i = 0; i <= 20; i++) {
            long long matrixResult = fibonacciMatrix(i);
            if (matrixResult != fib[i]) {
                cout << "    第 " << i << " 项不一致！递推：" << fib[i]
                     << "，矩阵：" << matrixResult << endl;
                allCorrect = false;
            }
        }

        if (allCorrect) {
            cout << "    前20项全部验证通过 ✓" << endl;
        }

        // 打印前20项的具体值
        cout << "    ";
        for (int i = 0; i <= 20; i++) {
            cout << fib[i];
            if (i < 20) cout << ", ";
        }
        cout << endl;
        cout << endl;
    }

    // 计算第10、第20、第50项
    cout << "  --- 指定项查询 ---" << endl;
    {
        long long queries[] = {10, 20, 50};
        for (int i = 0; i < 3; i++) {
            long long n = queries[i];
            long long result = fibonacciMatrix(n);
            cout << "  斐波那契第 " << n << " 项 F(" << n << ") = " << result << endl;
        }
        cout << endl;
    }

    // 额外：验证一个更大的 n
    cout << "  --- 大 n 测试 ---" << endl;
    {
        long long n = 100;
        long long result = fibonacciMatrix(n);
        cout << "  斐波那契第 " << n << " 项 F(" << n << ") = " << result << endl;
        cout << "  （用矩阵快速幂依然瞬间算出，时间复杂度仅 O(log n)！）" << endl;
        cout << endl;
    }

    // ---------- 总结 ----------
    cout << "================================================" << endl;
    cout << "  课程总结" << endl;
    cout << "================================================" << endl;
    cout << "  1. 快速幂将 O(b) 的朴素算法优化到 O(log b)。" << endl;
    cout << "  2. 递归版直观易懂，适合理解「折半」思想。" << endl;
    cout << "  3. 迭代版空间 O(1)，适合竞赛和高性能场景。" << endl;
    cout << "  4. 矩阵快速幂是快速幂的自然推广，解决线性递推。" << endl;
    cout << "  5. 斐波那契数列可用 2×2 矩阵在 O(log n) 内求解。" << endl;
    cout << "================================================" << endl;

    return 0;
}
