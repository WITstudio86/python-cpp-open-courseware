void demoLeapYear() {
    cout << "══════════════════════════════════════" << endl;
    cout << "  闰年判断演示" << endl;
    cout << "══════════════════════════════════════" << endl;

    int testYears[] = {1900, 2000, 2004, 2023, 2024, 2100, 2400};
    int n = 7;

    cout << "年份    | 可被4整除 | 可被100整除 | 可被400整除 | 闰年？| 2月天数" << endl;
    cout << "--------+----------+------------+------------+-------+--------" << endl;

    for (int i = 0; i < n; i++) {
        int y = testYears[i];
        cout << setw(6) << y << " | "
             << setw(8) << (y % 4 == 0 ? "是" : "否") << " | "
             << setw(10) << (y % 100 == 0 ? "是" : "否") << " | "
             << setw(10) << (y % 400 == 0 ? "是" : "否") << " | "
             << setw(5) << (isLeap(y) ? "是" : "否") << " | "
             << setw(6) << getMonthDays(y, 2) << "天"
             << endl;
    }
    cout << endl;

    // 打印一个示例日历
    cout << "示例日历（2024年10月）：" << endl;
    printCalendar(2024, 10);
    cout << endl;
}

