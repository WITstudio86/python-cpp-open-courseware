#include <iostream>
#include <iomanip>
using namespace std;

// ================================================================
// 月份天数表（平年）
// 索引1~12对应1~12月，monthDays[0]不使用
// ================================================================
int monthDays[13] = {0, 31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31};

// 星期名称（中文）
string weekNames[] = {"一", "二", "三", "四", "五", "六", "日"};

// ================================================================
// 判断闰年
// 规则：能被400整除 → 闰年
//       能被4整除但不能被100整除 → 闰年
//       其余 → 平年
//
// 示例：2000是闰年，1900不是，2004是闰年，2023不是
// ================================================================
bool isLeap(int year) {
    return (year % 400 == 0) || (year % 4 == 0 && year % 100 != 0);
}

// ================================================================
// 获取某年某月的天数
// 只有2月需要根据闰年判断，其他月份固定
// ================================================================
int getMonthDays(int year, int month) {
    if (month == 2 && isLeap(year))
        return 29;          // 闰年2月29天
    return monthDays[month]; // 其他月份查表
}

// ================================================================
// 计算从公元1年1月1日到指定日期(y-m-d)的总天数
// （这个方法可以用于任意两个日期的比较）
//
// 计算步骤：
//   1. 累加从1年到(y-1)年的所有整年天数
//   2. 累加当年1月到(m-1)月的所有整月天数
//   3. 加上当月的天数 d
// ================================================================
long long totalDaysFrom1(int y, int m, int d) {
    long long days = 0;

    // 步骤1：累加整年
    for (int i = 1; i < y; i++) {
        days += isLeap(i) ? 366 : 365;
    }

    // 步骤2：累加整月
    for (int i = 1; i < m; i++) {
        days += getMonthDays(y, i);
    }

    // 步骤3：加当月天数
    days += d;

    return days;
}

// ================================================================
// 计算指定日期是星期几
// 锚点：1900年1月1日 = 星期一
// 返回值：0=星期日, 1=星期一, ..., 6=星期六
//
// 计算方法：
//   1. 计算目标日期与1900-01-01的总天数差
//   2. 天数差 % 7 得到偏移量
//   3. 偏移量 + 1（因为1900-01-01是星期一）
// ================================================================
int getDayOfWeek(int y, int m, int d) {
    // 1900-01-01 的总天数
    long long base1900 = totalDaysFrom1(1900, 1, 1);
    // 目标日期的总天数
    long long targetDays = totalDaysFrom1(y, m, d);
    // 天数差
    long long diff = targetDays - base1900;
    // 星期：0=周一偏移为0，所以 diff%7=0 → 周一
    return diff % 7;
}

// ================================================================
// 打印某个月的日历（用于演示）
// ================================================================
void printCalendar(int year, int month) {
    int days = getMonthDays(year, month);
    int firstDay = getDayOfWeek(year, month, 1);  // 该月1日是星期几

    cout << "\n╔══════════════════════════════════╗" << endl;
    cout << "║       " << year << " 年 " << setw(2) << month << " 月"
         << (isLeap(year) ? " (闰年)" : "") << "        ║" << endl;
    cout << "╠══════════════════════════════════╣" << endl;
    cout << "║ 一  二  三  四  五  六  日      ║" << endl;
    cout << "║";

    // 打印前面的空格
    for (int i = 0; i < firstDay; i++) {
        cout << "    ";
    }

    // 打印日期
    for (int d = 1; d <= days; d++) {
        cout << setw(3) << d << " ";
        if ((firstDay + d) % 7 == 0) {
            cout << " ║" << endl;
            if (d < days) cout << "║";
        }
    }

    // 补齐最后一行
    int lastPadding = 7 - (firstDay + days) % 7;
    if (lastPadding < 7) {
        for (int i = 0; i < lastPadding; i++) {
            cout << "    ";
        }
        cout << " ║" << endl;
    }
    cout << "╚══════════════════════════════════╝" << endl;
}

// ================================================================
// 例题1：黑色星期五
// 题目：统计1900年~N年之间，所有13号且是星期五的日期数量
//       （已知1900年1月1日是星期一）
//
// 枚举思路：
//   - 遍历每一年、每一月
//   - 计算该月13日是星期几
//   - 如果是星期五（即 getDayOfWeek == 4），计数+1
//
// 注：在我们的星期编码中，0=周一，4=周五
// ================================================================
void solveBlackFriday() {
    cout << "══════════════════════════════════════" << endl;
    cout << "  例题1：黑色星期五" << endl;
    cout << "══════════════════════════════════════" << endl;
    cout << "统计13号又恰好是星期五的日期" << endl;
    cout << "--------------------------------------" << endl;

    int N;
    cout << "请输入结束年份 N（1900 ≤ N ≤ 9999）: ";
    cin >> N;

    int count = 0;
    int shown = 0;  // 只显示前几个结果

    cout << "\n黑色星期五列表（显示前10个）：" << endl;

    // 遍历年份
    for (int y = 1900; y <= N; y++) {
        // 遍历月份
        for (int m = 1; m <= 12; m++) {
            // 计算y年m月13日的星期（0=周一, 4=周五）
            int wd = getDayOfWeek(y, m, 13);

            if (wd == 4) {  // 星期五
                count++;
                if (shown < 10) {
                    cout << "  " << y << "年" << setw(2) << m << "月13日 "
                         << "星期" << weekNames[wd] << endl;
                    shown++;
                }
            }
        }
    }

    cout << "  ..." << endl;
    cout << "--------------------------------------" << endl;
    cout << "1900年~" << N << "年间共有 " << count << " 个黑色星期五" << endl;

    // 理论验证：平均每年约有 12/7 ≈ 1.71 个
    double expected = (N - 1900 + 1) * 12.0 / 7.0;
    cout << "（理论期望值约 " << (int)expected << " 个，每年平均 12/7≈1.71 个）" << endl;
    cout << endl;
}

// ================================================================
// 例题2：日期差
// 题目：输入两个日期（年月日），计算它们之间相差的天数
//       保证第一个日期早于第二个日期
//
// 解法：利用总天数法
//   diff = totalDaysFrom1(y2,m2,d2) - totalDaysFrom1(y1,m1,d1)
// ================================================================
void solveDateDiff() {
    cout << "══════════════════════════════════════" << endl;
    cout << "  例题2：日期差" << endl;
    cout << "══════════════════════════════════════" << endl;
    cout << "计算两个日期之间相差的天数" << endl;
    cout << "--------------------------------------" << endl;

    int y1, m1, d1, y2, m2, d2;

    cout << "请输入第一个日期（年 月 日）: ";
    cin >> y1 >> m1 >> d1;

    cout << "请输入第二个日期（年 月 日，晚于第一个日期）: ";
    cin >> y2 >> m2 >> d2;

    // 计算两个日期的总天数
    long long days1 = totalDaysFrom1(y1, m1, d1);
    long long days2 = totalDaysFrom1(y2, m2, d2);

    // 天数差
    long long diff = days2 - days1;

    if (diff < 0) {
        cout << "警告：第二个日期早于第一个日期，已自动交换。" << endl;
        diff = -diff;
    }

    cout << endl;
    cout << "日期1: " << y1 << "年" << m1 << "月" << d1 << "日";
    cout << "（累计天数: " << days1 << "）" << endl;
    cout << "日期2: " << y2 << "年" << m2 << "月" << d2 << "日";
    cout << "（累计天数: " << days2 << "）" << endl;
    cout << "--------------------------------------" << endl;
    cout << "相差: " << diff << " 天";
    if (diff >= 365) {
        cout << "（约 " << diff / 365 << " 年 " << diff % 365 << " 天）";
    }
    cout << endl;

    // 验证：输出两个日期的星期
    int wd1 = getDayOfWeek(y1, m1, d1);
    int wd2 = getDayOfWeek(y2, m2, d2);
    cout << "星期验证：日期1是星期" << weekNames[wd1]
         << "，日期2是星期" << weekNames[wd2]
         << "（相差" << diff << "天，" << diff % 7 << "周" << diff/7 << "天 → 星期偏移"
         << ((wd2 - wd1 + 7) % 7) << "，一致✓）" << endl;
    cout << endl;
}

// ================================================================
// 演示：判断某年是否为闰年，并显示2月天数
