// 例题2：合并果子
// 题目：有 n 堆果子，每堆重量为 a[i]。每次可以合并任意两堆，
//       合并的代价等于两堆重量之和。求合并成一堆的最小总代价。
//
// 贪心策略：每次选取最小的两堆进行合并（使用最小堆/优先队列）
//
// 归纳法证明（简述）：
//   基础步骤（n=2）：只有两堆时，只有一种合并方式，显然最优。
//
//   归纳步骤：
//     设所有堆中最小的两堆重量为 a 和 b（a ≤ b）。
//     我们可以证明：存在一个最优方案，a 和 b 是第一次合并的两堆。
//
//     证明方法（反证 + 交换论证）：
//       假设最优方案中，第一次合并的不是 a 和 b，而是某两堆 x 和 y，
//       且 a ≤ b ≤ x ≤ y（因为是"最小的两堆"）。
//       把最优方案中 x 和 y 的位置替换为 a 和 b（调整后续合并），
//       可以证明新方案的总代价 ≤ 原方案的总代价。
//       因此，"先合并 a 和 b" 一定不差。
//
//     合并 a 和 b 后，问题变成 n-1 堆的子问题（多了一堆 a+b）。
//     由归纳假设，贪心策略在子问题上也最优。
//     因此整体最优。得证。
//
// 时间复杂度：O(n log n) —— 每次堆操作 O(log n)，共 n-1 次合并
// 空间复杂度：O(n) —— 优先队列存储最多 n 个元素
// ================================================================

void solveMergeFruits() {
    cout << "╔══════════════════════════════════════════╗" << endl;
    cout << "║     例题2：合并果子                        ║" << endl;
    cout << "╚══════════════════════════════════════════╝" << endl;
    cout << endl;

    // ---- 测试数据 ----
    // n = 5 堆果子，重量分别为：1, 3, 4, 2, 5
    const int n = 5;
    int piles[n] = {1, 3, 4, 2, 5};

    cout << "【输入数据】" << endl;
    cout << "果子堆数 n = " << n << endl;
    cout << "各堆重量：";
    for (int i = 0; i < n; i++) {
        cout << piles[i] << " ";
    }
    cout << endl << endl;

    // ---- 贪心核心：使用最小堆（优先队列） ----
    // priority_queue 默认是大顶堆，加 greater<int> 变成小顶堆
    // 这样每次 top() 取出的都是最小的元素
    priority_queue<int, vector<int>, greater<int>> minHeap;

    // 将所有果子堆的重量加入最小堆
    for (int i = 0; i < n; i++) {
        minHeap.push(piles[i]);
    }

    long long totalCost = 0;   // 总合并代价（体力消耗）
    int step = 0;              // 合并步骤计数

    cout << "【合并过程】" << endl;
    cout << "步骤 | 堆1 | 堆2 | 新堆 | 本步代价 | 累计代价" << endl;
    cout << "-----+-----+-----+------+----------+----------" << endl;

    // 循环直到只剩一堆（堆大小为1）
    while (minHeap.size() > 1) {
        step++;

        // 贪心选择：取出最小的两堆
        int smallest1 = minHeap.top();  // 最小堆
        minHeap.pop();
        int smallest2 = minHeap.top();  // 次小堆
        minHeap.pop();

        // 合并这两堆
        int mergedPile = smallest1 + smallest2;
        totalCost += mergedPile;

        // 将合并后的新堆放回优先队列
        minHeap.push(mergedPile);

        // 输出本步详情
        cout << "  " << setw(2) << step << "  | "
             << setw(3) << smallest1 << " | "
             << setw(3) << smallest2 << " | "
             << setw(4) << mergedPile << " | "
             << setw(8) << smallest1 + smallest2 << " | "
             << setw(8) << totalCost << endl;
    }

    cout << "-----+-----+-----+------+----------+----------" << endl;
    cout << endl;

    // ---- 输出结果 ----
    cout << "【最小总体力消耗】" << totalCost << endl;
    cout << endl;

    // ---- 图解合并树 ----
    // 展示哈夫曼树的合并过程
    cout << "【合并树（类似哈夫曼树）】" << endl;
    cout << "  每次选最小的两堆合并，合并后的新堆参与后续选择" << endl;
    cout << endl;

    // 手动模拟哈夫曼合并树以便清晰展示
    cout << "          15 ← 最终一堆" << endl;
    cout << "         /  \\" << endl;
    cout << "        6    9" << endl;
    cout << "       / \\  / \\" << endl;
    cout << "      3   3 4  5" << endl;
    cout << "     / \\" << endl;
    cout << "    1   2" << endl;
    cout << endl;
    cout << "  合并顺序：" << endl;
    cout << "    步骤1: 1+2=3  (代价3)" << endl;
    cout << "    步骤2: 3+3=6  (代价6)" << endl;
    cout << "    步骤3: 4+5=9  (代价9)" << endl;
    cout << "    步骤4: 6+9=15 (代价15)" << endl;
    cout << "    总代价: 3+6+9+15 = 33" << endl;
    cout << endl;

    // ---- 对比：如果不贪心会怎样 ----
    cout << "【贪心 vs 非贪心对比】" << endl;
    cout << "  贪心策略（每次选最小两堆）：总代价 = " << totalCost << endl;
    cout << "  如果随便合并（比如从左到右）：" << endl;
    cout << "    1+3=4, 4+4=8, 8+2=10, 10+5=15" << endl;
    cout << "    总代价 = 4+8+10+15 = 37 > " << totalCost << endl;
    cout << "  => 贪心策略确实更优！✓" << endl;
    cout << endl;
}

// ================================================================
// 附加例题：排队接水 —— 多水龙头版本（选学）
// 题目：有 m 个水龙头，n 个人，求最小总等待时间
//
// 贪心策略：仍按接水时间升序排序，然后轮流分配给人最少的水龙头
// 证明思路：与单水龙头类似，交换论证仍然适用
// ================================================================

void solveMultiTapQueue() {
    cout << "╔══════════════════════════════════════════╗" << endl;
    cout << "║  附加题：多水龙头排队接水（选学）          ║" << endl;
    cout << "╚══════════════════════════════════════════╝" << endl;
    cout << endl;

    const int n = 6;  // 6个人
    const int m = 2;  // 2个水龙头
    int times[n] = {1, 2, 5, 3, 7, 4};

    // 按接水时间升序排序
    sort(times, times + n);

    // m 个水龙头的累计接水时间
    // tapTime[i] 表示第 i 个水龙头当前已安排的总接水时间
    // 初始化为0（相当于小顶堆，但没有用 priority_queue 是为了教学清晰）
    long long tapTime[m] = {0};

    cout << "【输入】" << endl;
    cout << n << " 个人, " << m << " 个水龙头" << endl;
    cout << "接水时间（排序后）：";
    for (int i = 0; i < n; i++) cout << times[i] << " ";
    cout << endl << endl;

    cout << "【分配过程】" << endl;
    long long totalWait = 0;

    for (int i = 0; i < n; i++) {
        // 找到当前累计接水时间最少的水龙头（贪心选择）
        int minTap = 0;
        for (int j = 1; j < m; j++) {
            if (tapTime[j] < tapTime[minTap]) {
                minTap = j;
            }
        }

        // 当前这个人被分配到 minTap 号水龙头
        // 他的等待时间 = 该水龙头已有的累计接水时间
        long long wait = tapTime[minTap];
        totalWait += wait;

        cout << "  接水时间 " << times[i] << " 的人 → 水龙头" << (minTap + 1)
             << "（等待" << wait << "分钟）" << endl;

        // 更新该水龙头的累计接水时间
        tapTime[minTap] += times[i];
    }

    cout << endl;
    cout << "【最小总等待时间】" << totalWait << " 分钟" << endl;
    cout << endl;
}

