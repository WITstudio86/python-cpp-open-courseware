using namespace std;

// ================================================================
// 例题1：排队接水
// 题目：有 n 个人排队接水，每人需要 t[i] 时间。
//       求一种排队顺序，使所有人的等待时间之和最小。
//
// 贪心策略：按接水时间从小到大排序
//
// 交换论证证明（简述）：
//   假设最优排列中，存在某人A在某人B前面，但 t_A > t_B。
//   交换A和B的位置。
//   - A前面的人：等待时间不变
//   - B后面的人：等待时间不变（因为A和B的总接水时间没变）
//   - A和B之间的人（如果有）：等待时间都减少了 (t_A - t_B) > 0
//   因此总等待时间严格减少，矛盾！
//   结论：任何最优排列中，接水时间短的人必须在前面。
//   所以按时间升序排列就是最优解。
//
// 时间复杂度：O(n log n) —— 排序是瓶颈
// 空间复杂度：O(n) —— 存储n个人的信息
// ================================================================

// 定义人员结构体
struct Person {
    int id;      // 原始编号（输入顺序，从1开始）
    int time;    // 接水所需时间（分钟）
};

// 排序比较函数：按接水时间升序排列
bool cmpByTime(Person a, Person b) {
    return a.time < b.time;
}

void solveQueueForWater() {
    cout << "╔══════════════════════════════════════════╗" << endl;
    cout << "║     例题1：排队接水                        ║" << endl;
    cout << "╚══════════════════════════════════════════╝" << endl;
    cout << endl;

    // ---- 测试数据 ----
    // n = 5 个人，接水时间分别为：3, 6, 1, 4, 2
    const int n = 5;
    Person persons[n] = {
        {1, 3},
        {2, 6},
        {3, 1},
        {4, 4},
        {5, 2}
    };

    cout << "【输入数据】" << endl;
    cout << "人数 n = " << n << endl;
    cout << "接水时间：";
    for (int i = 0; i < n; i++) {
        cout << persons[i].time << " ";
    }
    cout << endl << endl;

    // ---- 贪心核心：按接水时间升序排列 ----
    // 这就是贪心选择——让接水快的人排在前面
    sort(persons, persons + n, cmpByTime);

    // ---- 计算最小总等待时间 ----
    // 方法：遍历排序后的数组，维护一个"已接水时间总和"的前缀和
    // 第 i 个人的等待时间 = 前面 i-1 个人的接水时间之和
    long long totalWait = 0;   // 所有人等待时间之和
    long long prefixSum = 0;   // 前面所有人的接水时间之和（前缀和）

    cout << "【排序后的排队顺序】" << endl;
    cout << "顺序 | 编号 | 接水时间 | 等待时间" << endl;
    cout << "-----+------+----------+----------" << endl;

    for (int i = 0; i < n; i++) {
        // 当前这个人的等待时间 = 前面所有人的接水时间之和
        long long waitTime = prefixSum;
        totalWait += waitTime;

        cout << "  " << (i + 1) << "   |  "
             << setw(2) << persons[i].id << "  |    "
             << setw(2) << persons[i].time << "    |    "
             << setw(3) << waitTime << endl;

        // 更新前缀和：加上当前这个人的接水时间
        // 这样后面的人等待时间就会包含这个人的接水时间
        prefixSum += persons[i].time;
    }

    cout << "-----+------+----------+----------" << endl;
    cout << endl;

    // ---- 输出结果 ----
    cout << "【最优排队顺序（按编号输出）】" << endl;
    for (int i = 0; i < n; i++) {
        cout << persons[i].id;
        if (i < n - 1) cout << " ";
    }
    cout << endl;

    cout << "【最小总等待时间】" << totalWait << " 分钟" << endl;
    cout << endl;

    // ---- 验证交换论证 ----
    // 演示：如果故意把时间长的放在前面会怎样？
    cout << "【交换论证验证】" << endl;
    cout << "假设把接水时间 6 的人放在接水时间 1 的人前面：" << endl;
    cout << "  原始最优顺序（部分）：... , 1分钟, 6分钟, ..." << endl;
    cout << "  若交换成：... , 6分钟, 1分钟, ..." << endl;
    cout << "  中间所有人的等待时间增加 (6-1)=5 分钟" << endl;
    cout << "  => 总等待时间必定增加，不可能是最优解" << endl;
    cout << "  结论：时间短的必须在前面！✓" << endl;
    cout << endl;
}

