    cout << "  │ 第1步：假设存在最优解 OPT                            │" << endl;
    cout << "  │ 第2步：找到 OPT 中第一个与贪心解不同的位置            │" << endl;
    cout << "  │ 第3步：用贪心选择替换 OPT 中该位置的选择              │" << endl;
    cout << "  │ 第4步：证明替换后结果不会变差                        │" << endl;
    cout << "  │ 第5步：重复2-4步，直到 OPT = 贪心解，结论成立        │" << endl;
    cout << "  └─────────────────────────────────────────────────────┘" << endl;
    cout << endl;

    // 用排队接水做具体演示
