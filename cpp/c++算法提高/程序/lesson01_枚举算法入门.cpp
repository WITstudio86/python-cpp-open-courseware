void demoSimpleEnum() {
    cout << "══════════════════════════════════════" << endl;
    cout << "  演示：单层枚举——1~100中能被7整除的数" << endl;
    cout << "══════════════════════════════════════" << endl;

    int count = 0;
    for (int i = 1; i <= 100; i++) {
        if (i % 7 == 0) {
            cout << i << " ";
            count++;
            // 每行输出10个数
            if (count % 10 == 0) cout << endl;
        }
    }
    cout << endl;
    cout << "共 " << count << " 个" << endl;
    cout << endl;
}

