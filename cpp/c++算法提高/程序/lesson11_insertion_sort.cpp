#include <iostream>
#include <algorithm>  // 用于 swap
using namespace std;

// --------------------------------------------------
// 打印数组（辅助函数）
// --------------------------------------------------
void printArray(int arr[], int n, const char* msg = "") {
    if (msg[0] != '\0') cout << msg << ": ";
    cout << "[";
    for (int i = 0; i < n; i++) {
        cout << arr[i];
        if (i < n - 1) cout << ", ";
    }
    cout << "]" << endl;
}

// =====================================================
// 函数1：插入排序（基础版本）
//
// 核心思想：像整理扑克牌一样，每次将一张"新牌"插入到
//          手中已经排好序的牌的正确位置。
//
// 参数：
//   arr[] - 待排序的整数数组
//   n     - 数组的元素个数
//
// 算法步骤（以第 i 轮为例）：
//   ① 暂存当前元素 key = arr[i]（就像摸到的新牌）
//   ② 从有序区的末尾（i-1）开始，从右往左扫描
//   ③ 如果有序区元素 arr[j] > key，说明 key 应该放在 arr[j] 的左边
//      此时把 arr[j] 向右移动一格（给 key 腾位置）
//   ④ 重复步骤③，直到 j < 0 或 arr[j] <= key
//   ⑤ 将 key 放入位置 j+1（插入完成！）
// =====================================================
void insertionSort(int arr[], int n) {
    // 外层循环：从第2个元素（下标1）开始
    // 第0个元素单独构成"有序区"，天然有序
    for (int i = 1; i < n; i++) {
        int key = arr[i];   // 暂存当前要插入的"新牌"
        int j = i - 1;      // 从有序区的最后一个位置开始

        // 内层循环：在有序区中从右往左找 key 应该待的位置
        // 如果有序区的元素比 key 大，就往右移一格
        while (j >= 0 && arr[j] > key) {
            arr[j + 1] = arr[j];  // 把当前位置的元素右移
            j--;                   // 指针左移，继续比较前一个
        }

        // 到这里有两种情况：
        // 情况A：j < 0        → key 比有序区所有元素都小，插在最前面（位置0）
        // 情况B：arr[j] <= key → key 应该插在 arr[j] 的右边（位置 j+1）
        arr[j + 1] = key;  // 把"新牌"放到正确位置
    }
}

// =====================================================
// 函数2：线性查找插入位置
//
// 功能：在一个已排序（升序）的数组中，找到 x 应该插入的位置
//       使插入后数组仍保持有序。
//
// 思路：从左到右扫描，找到第一个 >= x 的位置。
//       如果没有找到（所有元素都 < x），则返回 n（插在末尾）。
//
// 时间复杂度：O(n)
// =====================================================
int findInsertPosLinear(int arr[], int n, int x) {
    // 从左往右找第一个 >= x 的位置
    for (int i = 0; i < n; i++) {
        if (arr[i] >= x) {
            return i;  // 找到了，这就是 x 应该插入的位置
        }
    }
    // 所有元素都 < x，x 应该放在数组末尾
    return n;
}

// =====================================================
// 函数3：二分查找插入位置
//
// 功能：在一个已排序（升序）的数组中，用二分查找找到 x
//       应该插入的位置（第一个 >= x 的位置，即 lower_bound）。
//
// 思路：
//   - 每次取中间元素 mid，和 x 比较
//   - 如果 arr[mid] >= x，说明位置可能在左边（包括 mid），继续往左找
//   - 如果 arr[mid] < x，说明位置一定在右边，往右找
//   - 最终 left 就是第一个 >= x 的位置
//
// 时间复杂度：O(log n)
// =====================================================
int findInsertPosBinary(int arr[], int n, int x) {
    int left = 0, right = n - 1;
    int pos = n;  // 默认插入末尾（如果所有元素都 < x）

    while (left <= right) {
        // 计算中间位置，使用 left + (right-left)/2 避免整数溢出
        int mid = left + (right - left) / 2;

        if (arr[mid] >= x) {
            pos = mid;       // 记录当前的候选位置
            right = mid - 1; // 继续往左找，看有没有更靠前的位置
        } else {
            left = mid + 1;  // 往右找
        }
    }

    return pos;
}

// =====================================================
// 例题1：插入位置查找
//
// 题目描述：
//   给定一个已排好序的数组（升序，不含重复元素）
//   和一个待插入的数 x，请找出 x 应该插入的位置。
//
// 输入格式：
//   第一行：n（数组长度）
//   第二行：n 个已排序的整数
//   第三行：x（待插入的数）
//
// 输出格式：
//   一个整数，表示 x 应该插入的位置下标（从 0 开始）
//
// 样例：
//   输入：5
//        1 3 5 7 9
//        6
//   输出：3（6 在 5(下标2) 和 7(下标3) 之间）
// =====================================================
void solve_problem1() {
    cout << "\n========== 例题1：插入位置查找 ==========" << endl;

    // 测试数据
    int arr[] = {1, 3, 5, 7, 9};
    int n = 5;
    int x = 6;

    cout << "数组: ";
    printArray(arr, n);
    cout << "待插入的数 x = " << x << endl;

    // 方法1：线性查找
    int pos1 = findInsertPosLinear(arr, n, x);
    cout << "【线性查找】插入位置: " << pos1
         << "（" << x << " 应插在下标 " << pos1 << " 处）" << endl;

    // 方法2：二分查找
    int pos2 = findInsertPosBinary(arr, n, x);
    cout << "【二分查找】插入位置: " << pos2
         << "（" << x << " 应插在下标 " << pos2 << " 处）" << endl;

    // 验证：模拟插入后的数组
    cout << "插入后数组应为: [1, 3, 5, 6, 7, 9]" << endl;

    // 更多测试用例
    cout << "\n--- 更多测试用例 ---" << endl;

    // 测试1：插在最前面
    int arr2[] = {2, 4, 6, 8};
    cout << "数组 [2, 4, 6, 8]，插入 1 → 位置: "
         << findInsertPosBinary(arr2, 4, 1) << endl;

    // 测试2：插在末尾
    cout << "数组 [2, 4, 6, 8]，插入 10 → 位置: "
         << findInsertPosBinary(arr2, 4, 10) << endl;

    // 测试3：插在中间
    cout << "数组 [2, 4, 6, 8]，插入 5 → 位置: "
         << findInsertPosBinary(arr2, 4, 5) << endl;
}

// =====================================================
// 例题2：部分有序排序
//
// 题目描述：
//   给定一个"几乎有序"的整数序列（每个元素离它最终位置
//   不超过 k），使用插入排序将其完全排序。
//
// 输入格式：
//   第一行：n 和 k
//   第二行：n 个整数
//
// 输出格式：
//   排序后的序列
//
// 样例：
//   输入：6 2
//        2 1 4 3 6 5
//   输出：1 2 3 4 5 6
// =====================================================
void solve_problem2() {
    cout << "\n========== 例题2：部分有序排序 ==========" << endl;

    // 测试数据
    int arr[] = {2, 1, 4, 3, 6, 5};
    int n = 6;
    int k = 2;  // 每个元素离最终位置不超过2

    cout << "原始数组: ";
    printArray(arr, n);
    cout << "k = " << k << "（每个元素离最终位置不超过 " << k << "）" << endl;

    // 执行插入排序
    insertionSort(arr, n);

    cout << "排序结果: ";
    printArray(arr, n);

    // 验证结果
    bool sorted = true;
    for (int i = 1; i < n; i++) {
        if (arr[i] < arr[i - 1]) {
            sorted = false;
            break;
        }
    }
    cout << "排序正确性验证: " << (sorted ? "通过 ✓" : "失败 ✗") << endl;

    // 更多测试用例
    cout << "\n--- 更多测试用例 ---" << endl;

    // 测试1：已经完全有序
    int arr2[] = {1, 2, 3, 4, 5, 6, 7, 8};
    int n2 = 8;
    cout << "测试1 - 已完全有序: ";
    printArray(arr2, n2, "排序前");
    insertionSort(arr2, n2);
    printArray(arr2, n2, "排序后");

    // 测试2：完全逆序（最坏情况）
    int arr3[] = {9, 8, 7, 6, 5, 4, 3, 2, 1};
    int n3 = 9;
    cout << "测试2 - 完全逆序: ";
    printArray(arr3, n3, "排序前");
    insertionSort(arr3, n3);
    printArray(arr3, n3, "排序后");

    // 测试3：单个元素
    int arr4[] = {42};
    int n4 = 1;
    cout << "测试3 - 单个元素: ";
    printArray(arr4, n4, "排序前");
    insertionSort(arr4, n4);
    printArray(arr4, n4, "排序后");
}

// =====================================================
// 附加演示：带步骤输出的插入排序
//
// 功能：逐步展示插入排序的完整过程，方便理解算法原理。
//       每一轮都打印当前数组状态和正在操作的元素。
// =====================================================
void insertionSortWithSteps(int arr[], int n) {
    cout << "\n========== 插入排序逐步演示 ==========" << endl;
    cout << "初始数组: ";
    printArray(arr, n);
    cout << "------------------------------------" << endl;

    for (int i = 1; i < n; i++) {
        int key = arr[i];
        int j = i - 1;

        cout << "第 " << i << " 轮：取出 key = arr[" << i << "] = " << key << endl;
        cout << "  有序区: [";
        for (int t = 0; t < i; t++) {
            cout << arr[t];
            if (t < i - 1) cout << ", ";
        }
        cout << "]  无序区: [";
        for (int t = i; t < n; t++) {
            cout << arr[t];
            if (t < n - 1) cout << ", ";
        }
        cout << "]" << endl;

        int shifts = 0;
        while (j >= 0 && arr[j] > key) {
            cout << "  arr[" << j << "]=" << arr[j] << " > key=" << key
                 << "，右移 arr[" << j << "] → arr[" << j+1 << "]" << endl;
            arr[j + 1] = arr[j];
            j--;
            shifts++;
        }

        if (shifts == 0) {
            cout << "  不需要移动，key 保持在原位" << endl;
        }

        arr[j + 1] = key;
        cout << "  插入 key=" << key << " 到位置 arr[" << j+1 << "]" << endl;
        cout << "  本轮结果: ";
        printArray(arr, n);
        cout << endl;
    }

    cout << "====================================" << endl;
    cout << "排序完成！最终结果: ";
    printArray(arr, n);
}

