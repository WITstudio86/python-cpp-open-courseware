#include <iostream>
#include <cmath>
#include <iomanip>
using namespace std;

// ================================================================
// 辅助函数：判断一个整数是否为回文数
// 回文数：正读和反读相同的数，如 121、12321
// 算法：将数字反转后与原数比较
// ================================================================
bool isPalindrome(int n) {
    int original = n;       // 保存原数
    int reversed = 0;       // 存储反转后的数

    // 逐位反转
    while (n > 0) {
        int digit = n % 10;              // 取最后一位
        reversed = reversed * 10 + digit; // 拼接到反转数末尾
        n /= 10;                          // 去掉最后一位
    }

    return original == reversed;  // 比较原数和反转数
}

// ================================================================
// 例题1：完美立方
// 题目：给定 N（N ≤ 100），找出所有 a ≤ N 的等式 a^3 = b^3 + c^3 + d^3
//       其中 b, c, d > 1 且 b ≤ c ≤ d
//
// 优化策略分析：
//   1. 范围缩小：b, c, d 都小于 a（因为立方和等于 a^3，各项小于总和）
//   2. 排序约定：约定 b ≤ c ≤ d，避免同一组解的排列重复
//   3. 剪枝1：b^3 ≥ a^3 时 break（b 已经太大）
//   4. 剪枝2：b^3 + c^3 ≥ a^3 时 break（c 已经太大）
//   5. 剪枝3：当和超过 a^3 时 break（d 已经太大，且 d 递增）
// ================================================================
void solvePerfectCube(int N) {
    cout << "══════════════════════════════════════" << endl;
    cout << "  例题1：完美立方 (N = " << N << ")" << endl;
    cout << "══════════════════════════════════════" << endl;
    cout << "寻找 a^3 = b^3 + c^3 + d^3 的所有解" << endl;
    cout << "其中 1 < b ≤ c ≤ d < a ≤ N" << endl;
    cout << "--------------------------------------" << endl;

    int count = 0;  // 解计数器

    // 枚举 a：从2开始（a=1 时 b,c,d 不可能都大于1）
    for (int a = 2; a <= N; a++) {
        int a3 = a * a * a;  // 预计算 a^3，避免重复计算

        // 枚举 b：b < a（因为 b^3 < a^3）
        for (int b = 2; b < a; b++) {
            int b3 = b * b * b;

            // 剪枝1：如果 b^3 已经 ≥ a^3，更大的 b 更不可能
            if (b3 >= a3) break;

            // 枚举 c：b ≤ c < a（从小到大，避免重复）
            for (int c = b; c < a; c++) {
                int c3 = c * c * c;
                int bc3 = b3 + c3;  // 预计算部分和

                // 剪枝2：如果 b^3 + c^3 已经 ≥ a^3，更大的 c 不可能
                if (bc3 >= a3) break;

                // 枚举 d：c ≤ d < a
                for (int d = c; d < a; d++) {
                    int d3 = d * d * d;
                    int sum = bc3 + d3;

                    if (sum == a3) {
                        count++;
                        cout << "解" << count << ": ";
                        cout << "Cube = " << setw(3) << a;
                        cout << ", Triple = (" << setw(2) << b;
                        cout << "," << setw(2) << c;
                        cout << "," << setw(2) << d << ")";
                        // 验证
                        cout << "  [验证: " << a << "^3 = " << a3
                             << " = " << b3 << "+" << c3 << "+" << d3 << "]";
                        cout << endl;
                    }

                    // 剪枝3：如果和已经超过 a^3，更大的 d 不可能
                    if (sum > a3) break;
                }
            }
        }
    }

    if (count == 0)
        cout << "（无解）" << endl;
    else
        cout << "--------------------------------------" << endl
             << "共找到 " << count << " 组解" << endl;
    cout << endl;
}

// ================================================================
// 例题2：回文平方数
// 题目：给定 N，找出 1~N 中所有平方也是回文数的数
//
// 枚举思路：
//   - 枚举对象：i ∈ [1, N]
//   - 判断条件：i*i 是回文数
//   - 优化空间不大（每个数都要检查），但回文判断是 O(log i) 的
// ================================================================
void solvePalindromicSquare(int N) {
    cout << "══════════════════════════════════════" << endl;
    cout << "  例题2：回文平方数 (N = " << N << ")" << endl;
    cout << "══════════════════════════════════════" << endl;
    cout << "寻找 1~" << N << " 中平方也是回文数的数" << endl;
    cout << "--------------------------------------" << endl;

    int count = 0;

    for (int i = 1; i <= N; i++) {
        int square = i * i;

        if (isPalindrome(square)) {
            count++;
            cout << i << " × " << i << " = " << square;
            // 对于较大的平方数，补充说明
            if (square >= 1000) {
                cout << " ← 回文！";
            }
            cout << endl;
        }
    }

    cout << "--------------------------------------" << endl;
    cout << "1~" << N << " 中共有 " << count << " 个回文平方数" << endl;
    cout << endl;
}

// ================================================================
// 演示：枚举优化效果对比
// 用单层枚举 + continue/break 演示剪枝效果
// ================================================================
void demoOptimization() {
    cout << "══════════════════════════════════════" << endl;
    cout << "  演示：continue 和 break 的使用" << endl;
    cout << "══════════════════════════════════════" << endl;

    // continue 示例：只输出奇数
    cout << "【continue 示例】1~20 中的奇数：" << endl;
    for (int i = 1; i <= 20; i++) {
        if (i % 2 == 0) continue;  // 偶数跳过
        cout << i << " ";
    }
    cout << endl;

    // break 示例：找到第一个满足条件的就停止
    cout << "\n【break 示例】第一个能被17整除的三位数：" << endl;
    for (int i = 100; i <= 999; i++) {
        if (i % 17 == 0) {
            cout << i << "（" << i << " = 17 × " << i/17 << "）" << endl;
            break;  // 找到就停
        }
    }
    cout << endl;
}

