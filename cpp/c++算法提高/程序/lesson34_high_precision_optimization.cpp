/*
 * ================================================================
 * C++算法提高 第34课：高精度应用与优化——压位存储（万进制）
 * ================================================================
 *
 * 算法知识点：
 *   - 压位存储（万进制）：每个数组元素存储4位十进制数字
 *   - 高精度乘低精度（压位版）：进位由 /10 变为 /BASE
 *   - 高精度减法（压位版）：借位由 +10 变为 +BASE
 *   - 输出前导零处理：非最高段需要用 setw + setfill('0') 补齐
 *   - 快速计算 2^n：循环 n 次，每次乘以 2
 *
 * 经典例题：
 *   例题1 - 2的N次方：输入 n（1 ≤ n ≤ 500），输出 2^n 的精确值
 *   例题2 - Hanoi双塔问题：输入 n（1 ≤ n ≤ 200），输出 2^(n+1) - 2
 */

#include <iostream>
#include <vector>
#include <iomanip>
#include <string>
using namespace std;

// ================================================================
// 压位高精度常量定义
// BASE = 10000 表示使用万进制（每个元素存储4位十进制数）
// WIDTH = 4     表示输出时每个非最高段应占的宽度
//
// 选择万进制的原因：
//   - 每个元素存4位，压缩比为4:1（空间和运算次数都减少到1/4）
//   - 乘法时：digits[i] * 2 + carry 最大约 20000+，远小于 int 上限
//   - 输出友好：4位一组，与千分位对齐，肉眼容易检查结果
// ================================================================
const int BASE = 10000;
const int WIDTH = 4;

// ================================================================
// BigInt 结构体：压位高精度整数（万进制）
// digits 数组从低位到高位存储，digits[0] 是最低位
// 例如：数值 12345678 存储为 digits = [5678, 1234]
// ================================================================
struct BigInt {
    vector<int> digits;

    // 构造函数：将普通整数转换为万进制存储
    // 例如：n=12345678 → digits = [5678, 1234]
    BigInt(int n = 0) {
        if (n == 0) {
            digits.push_back(0);
        } else {
            while (n > 0) {
                digits.push_back(n % BASE);
                n /= BASE;
            }
        }
    }

    // ----------------------------------------------------------
    // multiply：高精度乘低精度（压位版）
    // 例如：12345678 × 2 = 24691356
    //   输入：digits = [5678, 1234], x = 2
    //   过程：
    //     i=0: 5678 × 2 = 11356 → digits[0]=1356, carry=1
    //     i=1: 1234 × 2 + 1 = 2469 → digits[1]=2469, carry=0
    //   输出：digits = [1356, 2469]  表示 24691356 ✓
    // ----------------------------------------------------------
    void multiply(int x) {
        int carry = 0;
        for (int i = 0; i < (int)digits.size(); i++) {
            // 使用 long long 防止中间结果溢出
            long long cur = (long long)digits[i] * x + carry;
            digits[i] = cur % BASE;   // 当前段取余数
            carry = cur / BASE;        // 进位到下一位
        }
        // 处理最后的进位（可能需要多个万进制段）
        while (carry > 0) {
            digits.push_back(carry % BASE);
            carry /= BASE;
        }
    }

    // ----------------------------------------------------------
    // subtract2：高精度减2（用于 Hanoi双塔公式 2^(n+1) - 2）
    // 由于只减2，借位最多影响前两个段，但代码支持通用减法
    // 例如：10000 - 2 = 9998
    //   输入：digits = [0, 1]  （表示 10000）
    //   过程：
    //     i=0: 0 < 2 → digits[0] = 0 + 10000 - 2 = 9998, borrow=1
    //     i=1: 1 >= 1 → digits[1] = 1 - 1 = 0, borrow=0
    //   输出：digits = [9998]  （去掉前导零后）
    // ----------------------------------------------------------
    void subtract2() {
        int borrow = 2;
        for (int i = 0; i < (int)digits.size() && borrow > 0; i++) {
            if (digits[i] >= borrow) {
                digits[i] -= borrow;
                borrow = 0;
            } else {
                // 当前段不够减，向高位借1（借 BASE）
                digits[i] = digits[i] + BASE - borrow;
                borrow = 1;
            }
        }
        // 去除高位的前导零（对应 BASE 级别的零段）
        while (digits.size() > 1 && digits.back() == 0) {
            digits.pop_back();
        }
    }

    // ----------------------------------------------------------
    // print：输出高精度数
    // 关键点：非最高段的所有段必须用前导零补齐到 WIDTH 位
    //
    // 例如：digits = [2, 1]  表示 10002
    //   输出：digits[1]=1 → 直接输出 "1"
    //         digits[0]=2 → 补齐输出 "0002"
    //   最终："10002" ✓
    //
    // 常见错误：忘记补零，输出 "12" ✗
    // ----------------------------------------------------------
    void print() const {
        // 最高段直接输出（不需要补前导零）
        cout << digits.back();
        // 其余各段补足 WIDTH 位
        for (int i = (int)digits.size() - 2; i >= 0; i--) {
            cout << setw(WIDTH) << setfill('0') << digits[i];
        }
        cout << endl;
    }

    // ----------------------------------------------------------
    // getDecimalLength：估算十进制位数
    // 用于展示计算结果的长度
    // ----------------------------------------------------------
    int getDecimalLength() const {
        if (digits.size() == 1 && digits[0] == 0) return 1;
        int len = (digits.size() - 1) * WIDTH;
        int high = digits.back();
        while (high > 0) {
            len++;
            high /= 10;
        }
        return len;
    }
};

// ================================================================
// pow2：快速计算 2 的 n 次方（使用压位高精度）
// 参数：n - 指数（0 ≤ n ≤ 500）
// 返回：2^n 的精确值
//
// 算法：从 1 开始，循环 n 次，每次乘以 2
// 虽然每次只乘 2，但使用压位后运算量仅为普通方法的 1/4
//
// 复杂度：
//   时间：O(n²/B) ≈ O(n²/4)  （B=4为压缩比）
//   空间：O(n/B) ≈ O(n/4)
//
// 示例：
//   n=0  → 1
//   n=1  → 2
//   n=5  → 32
//   n=10 → 1024
//   n=64 → 18446744073709551616
// ================================================================
BigInt pow2(int n) {
    BigInt result(1);  // 初始为 2^0 = 1
    for (int i = 1; i <= n; i++) {
        result.multiply(2);
    }
    return result;
}

// ================================================================
// 例题1：2的N次方
// 题目：输入一个正整数 n（1 ≤ n ≤ 500），计算 2^n 的精确值
//
// 输入格式：一个整数 n
// 输出格式：2^n 的精确值
//
// 样例输入1：64
// 样例输出1：18446744073709551616
//
// 样例输入2：100
// 样例输出2：1267650600228229401496703205376
//
// 算法说明：
//   从 1 开始，循环 n 次，每次将当前值乘以 2。
//   使用压位高精度（万进制）存储中间结果，效率约为普通方法的4倍。
//   当 n=500 时，结果约有 151 位十进制数字，在万进制下仅需约 38 个段。
// ================================================================
void solvePow2() {
    cout << "══════════════════════════════════════" << endl;
    cout << "  例题1：2的N次方" << endl;
    cout << "══════════════════════════════════════" << endl;
    cout << "请输入指数 n（1 ≤ n ≤ 500）：" << endl;

    int n;
    cin >> n;

    if (n < 1 || n > 500) {
        cout << "输入超出范围！请确保 n ∈ [1, 500]" << endl;
        return;
    }

    cout << endl;
    cout << "计算 2^" << n << " ..." << endl;
    cout << "--------------------------------------" << endl;

    BigInt result = pow2(n);

    cout << "2^" << n << " = ";
    result.print();
    cout << "--------------------------------------" << endl;
    cout << "十进制位数：" << result.getDecimalLength() << " 位" << endl;
    cout << "万进制段数：" << result.digits.size() << " 段" << endl;
    cout << "（万进制下每个段存储4位十进制数，空间节省约 "
         << fixed << setprecision(0)
         << 100.0 * (1.0 - (double)result.digits.size() / result.getDecimalLength())
         << "%）" << endl;
    cout << endl;
}

// ================================================================
// 例题2：Hanoi双塔问题
// 题目：汉诺双塔问题。A柱上有2n个圆盘，n种不同大小，每种大小有2个
//       相同的圆盘。按照汉诺塔规则将所有圆盘移到C柱，求最少移动次数。
//
// 输入格式：一个整数 n（1 ≤ n ≤ 200）
// 输出格式：最少移动次数
//
// 公式：H(n) = 2^(n+1) - 2
//
// 样例输入：2
// 样例输出：6
//
// 公式推导（递推）：
//   设 H(n) 为双塔问题的最少移动次数（2n个圆盘）
//
//   移动策略：
//     1. 将上面 2(n-1) 个圆盘从A移到B  → H(n-1) 步
//     2. 将最大的2个圆盘从A移到C        → 2 步
//     3. 将B柱上 2(n-1) 个圆盘移到C    → H(n-1) 步
//
//   递推式：H(n) = 2 × H(n-1) + 2
//   边界：H(1) = 2（两个相同圆盘，直接移两次即可）
//
//   展开求解：
//     H(n) = 2 × H(n-1) + 2
//          = 2[2H(n-2) + 2] + 2
//          = 2² × H(n-2) + (2² + 2)
//          = ...
//          = 2^(n-1) × H(1) + (2^(n-1) + ... + 2² + 2)
//          = 2^(n-1) × 2 + (2^n - 2)
//          = 2^n + 2^n - 2
//          = 2^(n+1) - 2
//
//   验证：
//     n=1: 2^(1+1) - 2 = 4 - 2 = 2   → 正确！两个相同圆盘只需移2步
//     n=2: 2^(2+1) - 2 = 8 - 2 = 6   → 与样例一致！
//     n=3: 2^(3+1) - 2 = 16 - 2 = 14
//
// 复杂度：
//   与例题1相同：O((n+1)²/4) 时间，O((n+1)/4) 空间
//   当 n=200 时，结果约有 61 位十进制数，万进制下约需 16 个段
// ================================================================
void solveHanoiTwin() {
    cout << "══════════════════════════════════════" << endl;
    cout << "  例题2：Hanoi双塔问题" << endl;
    cout << "══════════════════════════════════════" << endl;
    cout << "A柱上有2n个圆盘（n种大小，每种2个）" << endl;
    cout << "按照汉诺塔规则全部移到C柱" << endl;
    cout << "公式：最少移动次数 = 2^(n+1) - 2" << endl;
    cout << "--------------------------------------" << endl;
    cout << "请输入 n（1 ≤ n ≤ 200）：" << endl;

    int n;
    cin >> n;

    if (n < 1 || n > 200) {
        cout << "输入超出范围！请确保 n ∈ [1, 200]" << endl;
        return;
    }

    cout << endl;
    cout << "计算 Hanoi双塔 H(" << n << ") = 2^(" << n << "+1) - 2 ..." << endl;
    cout << "--------------------------------------" << endl;

    // 计算 2^(n+1)
    BigInt result = pow2(n + 1);

    // 减去 2
    result.subtract2();

    cout << "H(" << n << ") = 2^(" << n << "+1) - 2 = 2^" << (n + 1)
         << " - 2 = ";
    result.print();
    cout << "--------------------------------------" << endl;
    cout << "十进制位数：" << result.getDecimalLength() << " 位" << endl;
    cout << "即最少需要移动 " << result.getDecimalLength() << " 位数字的次数！" << endl;
    cout << endl;
}

