// ================================================================
// 例题1：最大子段和 —— 分治解法
// ================================================================

/*
 * 问题描述：
 *   给定一个整数数组 arr[left ... right]，找出和最大的连续子数组，
 *   返回该子数组的元素总和。
 *
 * 分治思路：
 *   把数组从中间 mid 分成两半：左半 [left, mid] 和右半 [mid+1, right]。
 *   最大子段和必定出现在以下三种情况之一：
 *     情况1：完全在左半部分 → 递归求解左半部分
 *     情况2：完全在右半部分 → 递归求解右半部分
 *     情况3：跨越中点，一部分在左半、一部分在右半
 *            → 从中点向左扫描找最大后缀和，
 *              再从中点向右扫描找最大前缀和，
 *              两者相加即为跨越中点的最大子段和
 *   三种情况取最大值，就是整个区间的答案。
 *
 * 时间复杂度分析：
 *   T(n) = 2T(n/2) + O(n) → O(n log n)
 *   （存在更优的 Kadane 算法 O(n)，但分治解法更好地体现了"化整为零"思想）
 */

// ----------------------------------------------------------------
// 递归分治求解：返回 arr[left...right] 中的最大子段和
// 参数：
//   arr[] - 整数数组
//   left  - 当前区间的左端点下标（包含）
//   right - 当前区间的右端点下标（包含）
// ----------------------------------------------------------------
int maxSubArrayDivideConquer(int arr[], int left, int right) {
    // =============================================
    // 【递归基】区间只有一个元素，直接返回该元素
    // 子问题已经足够小，不需要再分解
    // =============================================
    if (left == right) {
        return arr[left];
    }

    // =============================================
    // 【分解步骤】将当前区间分成左右两半
    // 用中点 mid 作为分界线
    // 注意：此处使用 (left + right) / 2 防止整数溢出
    //       对于中小学生的数据范围完全安全
    // =============================================
    int mid = (left + right) / 2;

    // =============================================
    // 【解决步骤 - 情况1 & 情况2】
    // 递归求解左右两半的最大子段和
    // 这里递归调用自己，处理规模减半的子问题
    // =============================================
    int leftMaxSum  = maxSubArrayDivideConquer(arr, left, mid);     // 左半部分的最大子段和
    int rightMaxSum = maxSubArrayDivideConquer(arr, mid + 1, right); // 右半部分的最大子段和

    // =============================================
    // 【合并步骤 - 情况3】
    // 计算跨越中点的最大子段和
    // 需要分别找到：
    //   (a) 以 mid 为右端点的最大后缀和（在左半部分内）
    //   (b) 以 mid+1 为左端点的最大前缀和（在右半部分内）
    // 将两者相加即可
    // =============================================

    // ---- (a) 求左半部分的最大后缀和 ----
    // 从中点 mid 开始，向左扫描累加，记录最大值
    int leftSuffixSum = 0;        // 当前累加的后缀和
    int maxLeftSuffix = INT_MIN;  // 左半最大后缀和，初始化为最小整数
    for (int i = mid; i >= left; i--) {
        leftSuffixSum += arr[i];              // 累加当前元素
        if (leftSuffixSum > maxLeftSuffix) {  // 更新最大值
            maxLeftSuffix = leftSuffixSum;
        }
    }

    // ---- (b) 求右半部分的最大前缀和 ----
    // 从中点+1开始，向右扫描累加，记录最大值
    int rightPrefixSum = 0;        // 当前累加的前缀和
    int maxRightPrefix = INT_MIN;  // 右半最大前缀和，初始化为最小整数
    for (int i = mid + 1; i <= right; i++) {
        rightPrefixSum += arr[i];                // 累加当前元素
        if (rightPrefixSum > maxRightPrefix) {   // 更新最大值
            maxRightPrefix = rightPrefixSum;
        }
    }

    // ---- 跨越中点的最大子段和 = 左最大后缀 + 右最大前缀 ----
    int crossMaxSum = maxLeftSuffix + maxRightPrefix;

    // =============================================
    // 【合并结果】三种情况取最大值
    // 即：完全在左半、完全在右半、跨越中点
    // 取三者中的最大值作为当前区间的答案
    // =============================================
    // 手写 max 函数（不依赖 algorithm 库也可以）
    int result = leftMaxSum;
    if (rightMaxSum > result) result = rightMaxSum;
    if (crossMaxSum > result) result = crossMaxSum;

    return result;
}

// ----------------------------------------------------------------
// 包装函数：方便调用，只需传入数组和大小
// ----------------------------------------------------------------
int maxSubArraySum(int arr[], int n) {
    if (n <= 0) return 0;  // 空数组处理
    return maxSubArrayDivideConquer(arr, 0, n - 1);
}


// ================================================================
// 例题2：棋盘覆盖问题 —— 分治解法
// ================================================================

/*
 * 问题描述：
 *   有一个 2^k × 2^k 的棋盘（k >= 0），其中恰好有一个方格是"特殊方格"
 *   （不能覆盖）。现在要用 L 形骨牌覆盖棋盘上除特殊方格以外的所有方格。
 *   L 形骨牌由 3 个小方格组成，形状像一个直角（2×2 中去掉一个角）。
 *
 * 例如：k=2 时棋盘大小是 4×4，使用 5 个 L 形骨牌即可完全覆盖
 *       （(16 - 1) / 3 = 5 个骨牌正好用完）
 *
 * 分治思路：
 *   核心思想：将大棋盘不断等分为 4 个更小的子棋盘，
 *   直到子棋盘规模缩小到可以直接处理。
 *
 *   具体做法（以左上角为坐标原点，0 开始编号）：
 *     1. 将 2^k × 2^k 棋盘划分成 4 个 2^{k-1} × 2^{k-1} 的子棋盘
 *     2. 特殊方格必定在其中一个子棋盘中
 *     3. 在棋盘正中心的 2×2 区域，用 1 个 L 形骨牌覆盖其余 3 个子棋盘
 *        各一个方格（这 3 个方格分别成为对应子棋盘的新"特殊方格"）
 *     4. 递归处理 4 个子棋盘（每个子棋盘现在都有一个特殊方格）
 *     5. 当子棋盘大小为 1×1（即只有特殊方格本身）时，无需覆盖，直接返回
 *
 * 参数说明：
 *   tr, tc - 当前子棋盘左上角方格的行号(row)和列号(col)
 *   dr, dc - 当前子棋盘内特殊方格的行号和列号
 *   size   - 当前子棋盘的边长（2的幂次）
 *
 * 坐标示意（tr=0, tc=0, size=4 的情况）：
 *      列 0   1   2   3
 *   行 ┌───┬───┰───┬───┐
 *   0  │   │   ┃   │   │
 *     ├───┼───╂───┼───┤
 *   1  │   │   ┃   │   │
 *     ┝━━━┿━━━╋━━━┿━━━┥
 *   2  │   │   ┃   │dr │  ← 假设特殊方格在 (2, 3)
 *     ├───┼───╂───┼───┤
 *   3  │   │   ┃   │   │
 *     └───┴───┸───┴───┘
 *
 * 用中线（水平tr+size/2，竖直线tc+size/2）将棋盘分为四个象限
 */

// ----------------------------------------------------------------
// 全局常量与变量
// ----------------------------------------------------------------
const int MAX_SIZE = 16;  // 最大棋盘大小 2^4 = 16（可按需调整）
int board[MAX_SIZE][MAX_SIZE];  // 棋盘二维数组
int tileNumber = 1;             // 全局骨牌编号，每放入一个骨牌就加1

// ----------------------------------------------------------------
// 棋盘覆盖的分治函数
// 参数：
//   tr   - 当前子棋盘左上角行号（top row）
//   tc   - 当前子棋盘左上角列号（top column）
//   dr   - 特殊方格的行号（defect row）
//   dc   - 特殊方格的列号（defect column）
//   size - 当前子棋盘的边长（必须是2的幂次）
// ----------------------------------------------------------------
void chessBoard(int tr, int tc, int dr, int dc, int size) {
    // =============================================
    // 【递归基】棋盘大小为 1×1 时，只有特殊方格本身
    // 不需要覆盖任何东西，直接返回
    // =============================================
    if (size == 1) {
        return;
    }

    // =============================================
    // 【分解步骤】
    // 当前骨牌编号（本层即将放置的 L 形骨牌的编号）
    // 四个子棋盘共享这一个编号
    // =============================================
    int t = tileNumber;
    tileNumber++;  // 编号递增，为下一个骨牌做准备

    // 子棋盘边长 = 当前棋盘边长的一半
    int halfSize = size / 2;

    // =============================================
    // 计算棋盘中心十字线的位置
    // 用于判断特殊方格位于哪个子棋盘，
    // 以及确定新特殊方格的位置
    // =============================================
    // 水平分界线的行号 = 左上角行号 + 半边长（即右半部分的第一行）
    // 垂直分界线的列号 = 左上角列号 + 半边长（即下半部分的第一列）
    int midRow = tr + halfSize;
    int midCol = tc + halfSize;

    // =============================================
    // 根据特殊方格的位置，分别处理四个子棋盘
    // 四个子棋盘分别是：
    //   左上：行 [tr, midRow-1]，列 [tc, midCol-1]
    //   右上：行 [tr, midRow-1]，列 [midCol, tc+size-1]
    //   左下：行 [midRow, tr+size-1]，列 [tc, midCol-1]
    //   右下：行 [midRow, tr+size-1]，列 [midCol, tc+size-1]
    // =============================================

    // ────────── 处理左上子棋盘 ──────────
    if (dr < midRow && dc < midCol) {
        // 特殊方格在左上子棋盘内
        // 递归处理：特殊方格坐标不变，子棋盘边长减半
        chessBoard(tr, tc, dr, dc, halfSize);
    } else {
        // 特殊方格不在左上子棋盘内
        // 在左上子棋盘的右下角放置一个骨牌方格（使其成为该子棋盘的"新特殊方格"）
        // 该方格的坐标是 (midRow - 1, midCol - 1)，即左上子棋盘的最右下角
        board[midRow - 1][midCol - 1] = t;
        // 递归处理左上子棋盘，以新放置的方格作为特殊方格
        chessBoard(tr, tc, midRow - 1, midCol - 1, halfSize);
    }

    // ────────── 处理右上子棋盘 ──────────
    if (dr < midRow && dc >= midCol) {
        // 特殊方格在右上子棋盘内
        chessBoard(tr, midCol, dr, dc, halfSize);
    } else {
        // 特殊方格不在右上子棋盘内
        // 在右上子棋盘的左下角放置一个骨牌方格
        // 坐标为 (midRow - 1, midCol)
        board[midRow - 1][midCol] = t;
        chessBoard(tr, midCol, midRow - 1, midCol, halfSize);
    }

    // ────────── 处理左下子棋盘 ──────────
    if (dr >= midRow && dc < midCol) {
        // 特殊方格在左下子棋盘内
        chessBoard(midRow, tc, dr, dc, halfSize);
    } else {
        // 特殊方格不在左下子棋盘内
        // 在左下子棋盘的右上角放置一个骨牌方格
        // 坐标为 (midRow, midCol - 1)
        board[midRow][midCol - 1] = t;
        chessBoard(midRow, tc, midRow, midCol - 1, halfSize);
    }

    // ────────── 处理右下子棋盘 ──────────
    if (dr >= midRow && dc >= midCol) {
        // 特殊方格在右下子棋盘内
        chessBoard(midRow, midCol, dr, dc, halfSize);
    } else {
        // 特殊方格不在右下子棋盘内
        // 在右下子棋盘的左上角放置一个骨牌方格
        // 坐标为 (midRow, midCol)
        board[midRow][midCol] = t;
        chessBoard(midRow, midCol, midRow, midCol, halfSize);
    }
}

// ----------------------------------------------------------------
// 打印棋盘（带颜色标记的数字）
// 特殊方格用 0 表示，骨牌编号从 1 开始
// ----------------------------------------------------------------
void printBoard(int size) {
    cout << "\n  棋盘覆盖结果（数字相同表示同一个 L 形骨牌，0 表示特殊方格）：\n" << endl;

    // 打印列号
    cout << "     ";
    for (int j = 0; j < size; j++) {
        cout << setw(4) << j;
    }
    cout << endl;

    // 打印分隔线
    cout << "    ";
    for (int j = 0; j < size; j++) {
        cout << "────";
    }
    cout << endl;

    // 打印每一行
    for (int i = 0; i < size; i++) {
        cout << setw(3) << i << " │";  // 行号
        for (int j = 0; j < size; j++) {
            if (board[i][j] == 0) {
                // 特殊方格用星号标记，更醒目
                cout << "  * ";
            } else {
                cout << setw(3) << board[i][j] << " ";
            }
        }
        cout << endl;
    }
    cout << endl;
}

// ----------------------------------------------------------------
// 初始化并运行棋盘覆盖
// ----------------------------------------------------------------
void runChessBoardDemo(int k, int dr, int dc) {
    // k 是指数，棋盘大小为 2^k × 2^k
    int size = (int)pow(2, k);

    cout << "\n╔══════════════════════════════════════╗" << endl;
    cout << "║  例题2：棋盘覆盖问题                 ║" << endl;
    cout << "╚══════════════════════════════════════╝" << endl;
    cout << "棋盘大小: 2^" << k << " × 2^" << k << " = " << size << " × " << size << endl;
    cout << "特殊方格位置: 第 " << dr << " 行, 第 " << dc << " 列" << endl;
    cout << "需要的 L 形骨牌数量: (" << size << "×" << size << " - 1) / 3 = "
         << (size * size - 1) / 3 << " 个" << endl;

    // 初始化棋盘（全部置 0）
    for (int i = 0; i < size; i++) {
        for (int j = 0; j < size; j++) {
            board[i][j] = 0;
        }
    }

    // 重置骨牌编号
    tileNumber = 1;

    // 调用分治算法填充棋盘
    // 棋盘左上角从 (0, 0) 开始，特殊方格在 (dr, dc)
    chessBoard(0, 0, dr, dc, size);

    // 输出结果
    printBoard(size);
}


// ================================================================
// 辅助函数：打印数组
// ================================================================
void printArray(int arr[], int n) {
    cout << "[";
    for (int i = 0; i < n; i++) {
        cout << arr[i];
        if (i < n - 1) cout << ", ";
    }
    cout << "]" << endl;
}


