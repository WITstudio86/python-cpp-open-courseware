/**
 * ============================================================
 * 知识点总结
 * ============================================================
 *
 * 1. 树的直径（两种方法）：
 *    - 两次DFS：O(n)，仅适用于非负权边，实现简单
 *      核心：从任意点出发的最远点必为直径端点
 *    - 树形DP：O(n)，可处理负权边，一次DFS
 *      核心：维护每个节点的最长和次长向下路径
 *
 * 2. 树上背包（选课问题）：
 *    - 状态：dp[u][j] = 在u子树中选j个节点的最大价值
 *    - 转移：分组背包，枚举每个儿子子树贡献的节点数
 *    - 优化：利用子树大小剪枝，j的上界取 min(m, size_now)
 *    - 复杂度：O(nm)（优化后）
 *    - 关键技巧：添加虚拟根节点统一处理森林
 *
 * 3. 换根DP（二次扫描法）：
 *    - 第一步（dfs1）：固定一个根，计算子树信息（后序）
 *    - 第二步（dfs2）：利用父节点答案O(1)推导子节点答案（先序）
 *    - 核心公式（深度和换根）：
 *      ans[v] = ans[u] + n - 2 * size[v]
 *    - 适用场景：求"以每个节点为根时的某种全局信息"
 *    - 关键：找到简洁的换根递推公式
 *
 * 4. 考试技巧：
 *    - 识别题目隐含的树结构（表面是图，实际是树）
 *    - 树的直径优先考虑两次DFS（多数情况边权非负）
 *    - 树上背包注意 m <= n 的规模（通常 n ≤ 300）
 *    - 换根DP需要清晰地区分"子树信息"和"全局信息"
 *    - 注意 long long 溢出（深度和可能达到 O(n^2) 级别）
 *
 * 5. 常见错误：
 *    - 两次DFS求直径时未清空dist数组
 *    - 树上背包未逆序枚举容量（导致同组物品被多次使用）
 *    - 换根DP中子树大小计算错误（混淆有向和无向）
 *    - 负权边场景下，树形DP求直径时 d1,d2 初始化为0而非 -INF
 *
 * ============================================================
 */
