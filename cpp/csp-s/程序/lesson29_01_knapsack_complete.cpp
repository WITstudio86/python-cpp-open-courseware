// ============================================================
// 1. 01背包 —— 二维DP标准实现
// ============================================================
// 时间复杂度：O(N * V)
// 空间复杂度：O(N * V)
// 优点：可以方便地回溯具体选择方案
int knapsack01_2D(const vector<int>& w, const vector<int>& v, int V) {
    int N = w.size() - 1;  // 物品编号从1开始，w[0]是占位
    // dp[i][j]: 考虑前i件物品，总重量不超过j时的最大价值
    vector<vector<int>> dp(N + 1, vector<int>(V + 1, 0));

    for (int i = 1; i <= N; i++) {
        for (int j = 0; j <= V; j++) {
            // 不选第i件物品
            dp[i][j] = dp[i - 1][j];
            // 如果容量够，考虑选第i件物品
            if (j >= w[i]) {
                dp[i][j] = max(dp[i][j], dp[i - 1][j - w[i]] + v[i]);
            }
        }
    }

    cout << "  [01背包 二维DP] 最大价值 = " << dp[N][V] << endl;
    return dp[N][V];
}

// ============================================================
// 2. 01背包 —— 一维滚动数组优化（逆序遍历）
// ============================================================
// 时间复杂度：O(N * V)
// 空间复杂度：O(V)
//
// 【关键】为什么必须逆序遍历？
//   dp[j] = max(dp[j], dp[j - w[i]] + v[i])
//   等式右边的 dp[j - w[i]] 必须是【上一轮】(i-1)的旧值。
//   如果正序遍历，当计算 dp[j] 时，dp[j - w[i]] 可能已经被本轮更新过，
//   导致第i件物品被多次使用，退化为完全背包。
//   逆序遍历确保 j-w[i] < j，较小的索引在本轮中尚未被覆盖，
//   仍然保存着上一轮的旧值，从而保证每件物品最多用一次。
int knapsack01_1D(const vector<int>& w, const vector<int>& v, int V) {
    int N = w.size() - 1;
    vector<int> dp(V + 1, 0);

    // 逐物品迭代
    for (int i = 1; i <= N; i++) {
        // 逆序遍历容量：从V到w[i]
        // 只有当 j >= w[i] 时才有可能装入，所以以 w[i] 为下界
        for (int j = V; j >= w[i]; j--) {
            // dp[j]:     不选物品i（保持上一轮的旧值）
            // dp[j-w[i]] + v[i]: 选物品i
            //   注意：这里的 dp[j-w[i]] 由于逆序，仍是上一轮的旧值
            dp[j] = max(dp[j], dp[j - w[i]] + v[i]);
        }
    }

    cout << "  [01背包 一维逆序] 最大价值 = " << dp[V] << endl;
    return dp[V];
}

// ============================================================
// 3. 完全背包 —— 一维数组实现（正序遍历）
// ============================================================
// 时间复杂度：O(N * V)
// 空间复杂度：O(V)
//
// 【关键】为什么必须正序遍历？
//   完全背包中每件物品可以使用任意多次。
//   正序遍历时，计算 dp[j] 时 dp[j - w[i]] 可能已经被本轮更新过，
//   即已经包含了物品i。此时再在此基础上加一件物品i，
//   相当于物品i被多次使用，这正是完全背包所需要的效果。
//   逆序反而会让物品i最多只用一次（变成01背包）。
int knapsackComplete(const vector<int>& w, const vector<int>& v, int V) {
    int N = w.size() - 1;
    vector<int> dp(V + 1, 0);

    for (int i = 1; i <= N; i++) {
        // 正序遍历容量：从 w[i] 到 V
        // 正序使得 dp[j - w[i]] 可能已是本轮更新后的值
        for (int j = w[i]; j <= V; j++) {
            dp[j] = max(dp[j], dp[j - w[i]] + v[i]);
        }
    }

    cout << "  [完全背包 一维正序] 最大价值 = " << dp[V] << endl;
    return dp[V];
}

// ============================================================
// 4. 01背包 —— 恰好装满版本
// ============================================================
// 初始化技巧：
//   dp[0] = 0         精确匹配容量0，价值为0（合法状态）
//   dp[1..V] = -INF   其他容量暂无法恰好装满（非法状态）
//
// 原理：状态转移 dp[j] = max(dp[j], dp[j-w[i]] + v[i])
//   如果 dp[j-w[i]] 是 -INF（无法恰好装满 j-w[i]），
//   那么 dp[j-w[i]] + v[i] 仍然是极小的负数，
//   不会用于更新 dp[j]。只有从 dp[0] = 0 出发，
//   通过转移能够到达的状态才会被更新为有效值。
int knapsack01_exact(const vector<int>& w, const vector<int>& v, int V) {
    int N = w.size() - 1;
    vector<int> dp(V + 1, -INF);
    dp[0] = 0;  // 关键：容量0可以恰好装满（一件都不装）

    for (int i = 1; i <= N; i++) {
        // 01背包用逆序
        for (int j = V; j >= w[i]; j--) {
            // 只有当 dp[j-w[i]] 不是 -INF 时，更新才有效
            // 但实际上: max(-INF, -INF+v[i]) = 很小的数，不影响
            dp[j] = max(dp[j], dp[j - w[i]] + v[i]);
        }
    }

    if (dp[V] < 0) {
        cout << "  [01背包 恰好装满] 无法恰好装满容量 " << V << endl;
        return -1;
    }
    cout << "  [01背包 恰好装满] 最大价值 = " << dp[V] << endl;
    return dp[V];
}

// ============================================================
// 5. 完全背包 —— 恰好装满版本
// ============================================================
int knapsackComplete_exact(const vector<int>& w, const vector<int>& v, int V) {
    int N = w.size() - 1;
    vector<int> dp(V + 1, -INF);
    dp[0] = 0;

    for (int i = 1; i <= N; i++) {
        // 完全背包用正序
        for (int j = w[i]; j <= V; j++) {
            dp[j] = max(dp[j], dp[j - w[i]] + v[i]);
        }
    }

    if (dp[V] < 0) {
        cout << "  [完全背包 恰好装满] 无法恰好装满容量 " << V << endl;
        return -1;
    }
    cout << "  [完全背包 恰好装满] 最大价值 = " << dp[V] << endl;
    return dp[V];
}

// ============================================================
// 6. 01背包 —— 求方案数
// ============================================================
// dp[j]: 恰好装满容量j的方案数
// 初始化：dp[0] = 1（空背包是一种方案）
int knapsack01_count(const vector<int>& w, int V) {
    int N = w.size() - 1;
    vector<int> dp(V + 1, 0);
    dp[0] = 1;  // 一件都不选是一种方案

    for (int i = 1; i <= N; i++) {
        // 01背包逆序
        for (int j = V; j >= w[i]; j--) {
            dp[j] = (dp[j] + dp[j - w[i]]) % MOD;
        }
    }

    cout << "  [01背包 方案数] 恰好装满容量 " << V << " 的方案数 = " << dp[V] << endl;
    return dp[V];
}

// ============================================================
// 7. 完全背包 —— 求方案数
// ============================================================
int knapsackComplete_count(const vector<int>& w, int V) {
    int N = w.size() - 1;
    vector<int> dp(V + 1, 0);
    dp[0] = 1;

    for (int i = 1; i <= N; i++) {
        // 完全背包正序
        for (int j = w[i]; j <= V; j++) {
            dp[j] = (dp[j] + dp[j - w[i]]) % MOD;
        }
    }

    cout << "  [完全背包 方案数] 恰好装满容量 " << V << " 的方案数 = " << dp[V] << endl;
    return dp[V];
}

// ============================================================
// 8. 01背包 —— 求字典序最小方案（回溯法）
// ============================================================
// 使用二维DP + 记录表 g[i][j]，从 (N, V) 回溯
// 回溯策略：从后往前判断，只要可以选就选，最终 reverse 即为字典序最小
void knapsack01_minLexOrder(const vector<int>& w, const vector<int>& v, int V) {
    int N = w.size() - 1;
    vector<vector<int>> dp(N + 1, vector<int>(V + 1, 0));
    // g[i][j] = true 表示在状态(i, j)处选择了物品i
    vector<vector<bool>> g(N + 1, vector<bool>(V + 1, false));

    // 二维DP + 记录选择
    for (int i = 1; i <= N; i++) {
        for (int j = 0; j <= V; j++) {
            dp[i][j] = dp[i - 1][j];  // 默认不选
            if (j >= w[i]) {
                int val = dp[i - 1][j - w[i]] + v[i];
                // 注意：使用 > 而不是 >= 来保证字典序最小
                // > 保证仅在严格更优时才选，避免不必要的选择
                if (val > dp[i][j]) {
                    dp[i][j] = val;
                    g[i][j] = true;
                }
            }
        }
    }

    // 回溯：从 (N, V) 开始
    int j = V;
    vector<int> selected;

    // 从后往前遍历物品，能选则选
    for (int i = N; i >= 1; i--) {
        if (j >= w[i] && dp[i][j] == dp[i - 1][j - w[i]] + v[i]) {
            selected.push_back(i);
            j -= w[i];
        }
    }

    // 因为是倒着收集的，reverse 后即为编号从小到大
    reverse(selected.begin(), selected.end());

    cout << "  [01背包 字典序最小方案] 最大价值 = " << dp[N][V] << endl;
    cout << "    选择的物品编号: ";
    if (selected.empty()) {
        cout << "(无)";
    } else {
        for (size_t k = 0; k < selected.size(); k++) {
            if (k > 0) cout << " -> ";
            cout << selected[k];
        }
    }
    cout << endl;
}

