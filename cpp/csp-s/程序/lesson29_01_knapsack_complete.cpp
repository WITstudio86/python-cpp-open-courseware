// 9. 真题1：采药 (NOIP2005 普及组)
// ============================================================
// 题目：有T的时间，M株草药，每株需要 time[i] 时间，有 value[i] 价值
//       每株只能采一次，求最大总价值
void solve_herbPicking() {
    printSeparator("真题1：采药 (NOIP2005 普及组)");

    // 样例输入：T=70, M=3
    // 草药1: 71 100
    // 草药2: 69 1
    // 草药3: 1 2
    // 预期输出：3

    int T = 70, M = 3;
    vector<int> w = {0, 71, 69, 1};   // 重量 = 采药时间
    vector<int> v = {0, 100, 1, 2};    // 价值 = 草药价值

    vector<int> dp(T + 1, 0);

    // 01背包一维逆序
    for (int i = 1; i <= M; i++) {
        for (int j = T; j >= w[i]; j--) {
            dp[j] = max(dp[j], dp[j - w[i]] + v[i]);
        }
    }

    cout << "  样例输入：T=70, M=3" << endl;
    cout << "  草药: (71,100), (69,1), (1,2)" << endl;
    cout << "  最大总价值 = " << dp[T] << " (预期: 3)" << endl;
    cout << "  解释: 选草药3(1,2)，剩余时间=69，草1和草2都装不下" << endl;
}

// ============================================================
// 10. 真题2：装箱问题（最小剩余容量）
// ============================================================
// 题目：箱子容量V，n个物品各有体积，求装入后箱子的最小剩余空间
// 思路：体积既是重量也是价值，做01背包，答案 = V - dp[V]
void solve_binPacking() {
    printSeparator("真题2：装箱问题 (最小剩余容量)");

    // 样例输入：V=24, n=6
    // 物品体积：8, 3, 12, 7, 9, 7
    // 最优：8 + 7 + 9 = 24，剩余0

    int V = 24, n = 6;
    vector<int> w = {0, 8, 3, 12, 7, 9, 7};  // 体积 = 重量 = 价值

    vector<int> dp(V + 1, 0);

    // 01背包：体积既是重量也是价值
    for (int i = 1; i <= n; i++) {
        for (int j = V; j >= w[i]; j--) {
            // v[i] = w[i]，即体积就是价值
            dp[j] = max(dp[j], dp[j - w[i]] + w[i]);
        }
    }

    int minRemain = V - dp[V];

    cout << "  样例输入：V=24, n=6" << endl;
    cout << "  物品体积：8, 3, 12, 7, 9, 7" << endl;
    cout << "  最大装载体积 = " << dp[V] << endl;
    cout << "  最小剩余空间 = " << minRemain << " (预期: 0)" << endl;
    cout << "  解释: 选 8+7+9=24，恰好装满" << endl;
}

