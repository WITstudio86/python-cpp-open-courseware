# 三、有函数：优雅！
print("\n=== 三、有函数：简洁清晰 ===")

def print_line():
    """打印一条分隔线"""
    print("=" * 30)

# 看！只需要调用函数就行了
print_line()
print("语文成绩单")
print_line()
print("小明: 95 分")
print("小红: 88 分")
print_line()

print_line()
print("数学成绩单")
print_line()
print("小明: 92 分")
print("小红: 90 分")
print_line()

print("\n上面的代码只写了一次分隔线代码！")
print("如果想把 = 改成 -，只需要改一个地方！")

