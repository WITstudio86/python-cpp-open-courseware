# 重构后
print("\n【重构后】使用函数，简洁多了：")

def print_separator():
    """打印分隔线"""
    print("=" * 30)

def print_chapter(title):
    """打印章节标题"""
    print_separator()
    print(title)
    print_separator()

print_chapter("第1章")
print("内容...")
print_separator()
print()
print_chapter("第2章  ")
print("内容...")
print_separator()

