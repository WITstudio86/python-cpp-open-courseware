# ===== 1. 最基本的 input() =====
print("===== 1. 最基本的 input() =====")

# input() 会让程序停下来，等你输入
# 括号里的文字是"提示语"
input("按回车键继续...")  # 程序停在这里，等你按回车

print("你刚才按了回车，程序继续运行了！")

# ===== 2. 把输入存到变量里 =====
print("\n===== 2. 把输入存起来 =====")

# 输入的内容一定要用变量"接住"，不然就丢了！
name = input("请问你叫什么名字？ ")
# name 现在是一个"盒子"，里面放着用户输入的名字

print("你好，", name, "！")  # 用逗号把文字和变量连起来
print(name, "真是一个好听的名字！")

# 如果不存起来，就找不到了：
# input("你叫什么？")  # 用户输入了，但没有变量保存
# print("你好！")       # 不知道用户叫什么...

# ===== 3. 收集多个信息 =====
print("\n===== 3. 收集更多信息 =====")

age = input("你今年几岁了？ ")
grade = input("你上几年级了？ ")
school = input("你在哪个学校上学？ ")

print("\n让我确认一下你的信息：")
print("姓名：", name)
print("年龄：", age, "岁")
print("年级：", grade, "年级")
print("学校：", school)
print("信息确认完毕！")

