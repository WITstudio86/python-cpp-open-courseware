# ===== 4. 切片 —— 切出一段文字 =====
print("\n===== 4. 切片 [开始:结束] =====")

# 规则：[开始:结束] → 从"开始"拿，拿到"结束"之前停
# 记忆：含左不含右！

text = "我爱Python编程"
print("原文:", text)
print("[0:2]  →", text[0:2])     # 我爱（索引0和1，不含2）
print("[2:8]  →", text[2:8])     # Python（索引2到7）
print("[8:]   →", text[8:])      # 编程（从8到末尾）
print("[:2]   →", text[:2])      # 我爱（从开头到2）
print("[:]    →", text[:])       # 全部

# 更多切片示例
word = "Hello World"
print("\n原文:", word)
print("[:5]:", word[:5])         # Hello
print("[6:]:", word[6:])         # World
print("[0:5]:", word[0:5])       # Hello
print("[3:8]:", word[3:8])       # lo Wo

# ===== 5. 切片步长 =====
print("\n===== 5. 步长切片 [开始:结束:步长] =====")

word = "Python"
print("原文:", word)
print("每隔1个:", word[::1])      # Python（默认步长1）
print("每隔2个:", word[::2])      # Pto
print("每隔3个:", word[::3])      # Ph

# ===== 6. 倒序魔法 [::-1] =====
print("\n===== 6. 倒序 [::-1] =====")

print("Python 倒过来:", "Python"[::-1])   # nohtyP
print("上海自来水 倒过来:", "上海自来水"[::-1])
print("12345 倒过来:", "12345"[::-1])

# 回文检查（正读反读一样）
word1 = "level"
word2 = "python"
print(f'\n"{word1}" 是回文吗？', word1 == word1[::-1])   # True
print(f'"{word2}" 是回文吗？', word2 == word2[::-1])     # False

# ===== 7. 实用例子 =====
print("\n===== 7. 实用例子 =====")

# 提取姓和名
full_name = "欧阳小明"
surname = full_name[:2]          # 姓（前2个字）
given_name = full_name[2:]       # 名（第3个字开始）
print(f"全名:{full_name} → 姓:{surname} 名:{given_name}")

# 提取一句话的第一个字和最后一个字
saying = "好好学习天天向上"
print(f"第一个字:{saying[0]}, 最后一个字:{saying[-1]}")

# 隐藏部分信息
phone = "13812345678"
hidden = phone[:3] + "****" + phone[7:]
print(f"手机号:{hidden}")        # 138****5678

# 截取古诗
poem = "床前明月光疑是地上霜举头望明月低头思故乡"
print(f"第一句:{poem[:5]}")       # 床前明月光
print(f"第二句:{poem[5:10]}")     # 疑是地上霜
print(f"第三句:{poem[10:15]}")    # 举头望明月
print(f"第四句:{poem[15:]}")     # 低头思故乡

# 字符串长度限制保护
long_text = "这是一段很长很长的文字"
if len(long_text) > 10:
    short_text = long_text[:10] + "..."
    print(f"截断显示:{short_text}")


