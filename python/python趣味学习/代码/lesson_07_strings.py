# ===== 1. 创建字符串 =====
print("===== 1. 创建字符串 =====")

# 三种引号都可以
s1 = "Hello"                     # 双引号
s2 = 'Python'                    # 单引号
s3 = """多行
字符串"""                        # 三引号（可以跨多行）

print("双引号:", s1)
print("单引号:", s2)
print("三引号:", s3)

# 注意："123"（有引号）和 123（无引号）是不同的！
text_123 = "123"    # 这是字符串
num_123 = 123       # 这是数字
print('\n"123" 的类型:', type(text_123))
print("123 的类型:", type(num_123))

# 什么时候用哪种引号？
print("\n--- 引号的选择 ---")
# 文字里有单引号 → 外面用双引号
print("I'm a student")
# 文字里有双引号 → 外面用单引号
print('他说："你好！"')
# 多行 → 用三引号
print("""静夜思
床前明月光
疑是地上霜""")

# ===== 2. len() —— 数一数有几个字符 =====
print("\n===== 2. len() 数字符个数 =====")

print('"Hello" 的长度:', len("Hello"))        # 5
print('"你好世界" 的长度:', len("你好世界"))    # 4
print('"Python 真好" 的长度:', len("Python 真好"))  # 9（空格也算！）
print('空字符串的长度:', len(""))             # 0

# 互动：数一下你的名字有几个字
name = "欧阳小明"
print(f'"{name}" 有 {len(name)} 个字')

# ===== 3. 索引 —— 每个字都有编号（从0开始！）=====
print("\n===== 3. 索引（从 0 开始！）=====")

#      P  y  t  h  o  n
# 正着:0  1  2  3  4  5
# 倒着:-6 -5 -4 -3 -2 -1

word = "Python"
print("字符串:", word)
print("索引 0:", word[0])      # P（第一个）
print("索引 1:", word[1])      # y（第二个）
print("索引 2:", word[2])      # t（第三个）
print("索引 5:", word[5])      # n（最后一个）
print("索引 -1:", word[-1])    # n（倒数第一，最常用！）
print("索引 -2:", word[-2])    # o（倒数第二）

# 试试中文
sentence = "我爱学编程"
print("\n句子:", sentence)
print("[0]:", sentence[0])     # 我
print("[1]:", sentence[1])     # 爱
print("[3]:", sentence[3])     # 编
print("[-1]:", sentence[-1])   # 程

