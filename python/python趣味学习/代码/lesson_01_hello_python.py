# ===== 2. 让电脑做计算（比人算得快多了！）=====
print("\n--- 我是超级计算器 ---")
print("123 + 456 =", 123 + 456)
print("999 × 888 =", 999 * 888)
print("1000 - 357 =", 1000 - 357)
print("2 的 100 次方 =", 2 ** 100)  # 超大的数字，电脑瞬间算出来！

