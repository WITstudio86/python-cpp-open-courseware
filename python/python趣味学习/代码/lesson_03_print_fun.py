# 主题：print() 的各种用法和技巧
# ============================================================

# ===== 1. 输出文字（字符串）=====
print("===== 本领一：输出文字 =====")

print("你好，Python！")         # 双引号
print('你好，Python！')         # 单引号也可以
print("中文 English 123 !@#")  # 什么语言和符号都可以！

# 注意：引号必须是英文引号，不是中文的""
# 以下会报错：
# print（"你好"）   # 括号是中文的
# print("你好"）   # 一边中文一边英文

# ===== 2. 输出数字和算式 =====
print("\n===== 本领二：输出数字和算式 =====")

print(100)               # 输出数字 100
print(100 + 200)         # 输出计算结果 300
print(50 - 30)           # 30
print(8 * 7)             # 乘法（用*而不是×）
print(100 / 5)           # 除法
print(2 ** 10)           # 2的10次方 = 1024
print(17 % 5)            # 取余数 = 2

# 电脑先算括号里的东西，再输出结果
print("3 + 5 =", 3 + 5)  # 先算3+5=8，再输出 "3 + 5 = 8"

# ===== 3. 一次输出多个内容 =====
print("\n===== 本领三：一次输出多个 =====")

# 用逗号分隔多个内容，电脑会自动加空格
name = "小明"
age = 11
print("我叫", name, "今年", age, "岁")

# sep 参数：自定义分隔符
print("苹果", "香蕉", "橘子", sep="、")    # 用顿号分隔
print("2024", "10", "01", sep="-")        # 用横线分隔
print("A", "B", "C", sep=" → ")           # 用箭头分隔

# end 参数：自定义结尾（默认是换行）
print("第一句", end="...")
print("第二句", end="...")
print("第三句")                            # 最后这个正常换行

print("加载中", end="")
print(".", end="")
print(".", end="")
print(".")                                 # 输出：加载中...

# ===== 4. 换行 \n =====
print("\n===== 本领四：换行 =====")

# \n 就是"在这里换行"的意思
print("第一行\n第二行\n第三行")

# 和多个 print 效果一样
print("--- 效果对比 ---")
print("第一行")
print("第二行")
print("第三行")

# 背一首诗
print("\n静夜思")
print("床前明月光\n疑是地上霜\n举头望明月\n低头思故乡")

# ===== 5. 字符画大创作 =====
print("\n===== 字符画创 =====作")

# 直角三角形
print("--- 直角三角形 ---")
print("*")
print("**")
print("***")
print("****")
print("*****")

# 等腰三角形（金字塔）
print("\n--- 金字塔 ---")
print("    *")
print("   ***")
print("  *****")
print(" *******")
print("*********")

# 笑脸
print("\n--- 笑脸 ---")
print("  *****  ")
print(" *     * ")
print("*  O O  *")
print("*   ^   *")
print("* \\___/ *")
print(" *     * ")
print("  *****  ")

# 圣诞树
print("\n--- 圣诞树 ---")
print("    ★")
print("   ***")
print("  *****")
print(" *******")
print("*********")
print("   |||")
print("   |||")
print("---------")

# 一行代码画三角形（用\n）
print("\n--- 一行代码画三角形 ---")
print("    *\n   ***\n  *****\n *******\n*********")

# ===== 6. 趣味应用：进度条 =====
print("\n===== 趣味应用：进度条 =====")

print("正在下载...")
print("[", end="")
print("█" * 5, end="")
print(" " * 5, end="")
print("] 50%")

# 模拟完成
print("[", end="")
print("█" * 10, end="")
print("] 100% 下载完成！")


