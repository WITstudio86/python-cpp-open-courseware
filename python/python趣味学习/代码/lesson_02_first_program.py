# ===== 1. 第一个程序：Hello, World! =====
# 这是编程界的"传统"——每个程序员的第一个程序都是 Hello, World!
print("Hello, World!")
print("你好，世界！")

# ===== 2. 试试更多输出 =====
print("\n--- 更多问候 ---")
print("Hello, Python!")          # 英文
print("你好，Python！")          # 中文
print("こんにちは、パイソン！")   # 日文也可以！
print("Bonjour, Python!")        # 法文也行！

# ===== 3. 认识代码结构 =====
# 每一行 print 是一条"指令"
# 电脑会从上到下，一行一行执行
print("\n--- 电脑按顺序执行 ---")
print("第一条指令：我醒了")
print("第二条指令：我准备好了")
print("第三条指令：开始工作！")

# ===== 4. 输出你喜欢的任何东西 =====
print("\n--- 你想让电脑说什么？ ---")
# 试试看！把你想说的话放在引号里
print("今天天气真好！")
print("我要学好 Python！")
print("123456789")              # 数字也可以放在引号里
print("!@#$%^&*()")            # 符号也可以

# ===== 5. 小练习：认识错误 =====
# 如果你忘了写引号，会发生什么？
# 把下面这行的 # 去掉试试看（会报错哦）：
# print(你好)
# 错误原因：Python 以为"你好"是一个变量名，但我们还没定义它

# 正确写法：
print("你好")  # 加上引号，Python 就知道这是"文字"

# ===== 6. 多个 print 的效果 =====
print("\n--- 小诗一首 ---")
print("春晓")
print("春眠不觉晓")
print("处处闻啼鸟")
print("夜来风雨声")
print("花落知多少")
# 每个 print 都会自动换行

