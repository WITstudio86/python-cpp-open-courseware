"""
第1节：Hello, Pygame! —— 第一个游戏窗口
==========================================
本程序演示 Pygame 的基本用法：
1. 初始化 Pygame
2. 创建游戏窗口
3. 设置窗口标题
4. 填充背景颜色
5. 保持窗口打开，直到用户点击关闭按钮

你可以尝试修改下面"可尝试的颜色"中的 RGB 值，
看看不同的颜色效果！
"""

import pygame  # 导入 Pygame 游戏开发库
import sys     # 导入系统库，用于退出程序

# ============================================
# 1. 初始化 Pygame（必须最先调用！）
# ============================================
pygame.init()  # 启动 Pygame 的所有模块，就像按下游戏机的"开机键"

# ============================================
# 2. 设置游戏窗口
# ============================================
WIDTH = 800   # 窗口宽度（单位：像素）
HEIGHT = 600  # 窗口高度（单位：像素）

# set_mode() 创建一个窗口，参数是一个元组 (宽度, 高度)
screen = pygame.display.set_mode((WIDTH, HEIGHT))

# set_caption() 设置窗口标题栏显示的文字
pygame.display.set_caption("Hello, Pygame! —— 我的第一个游戏窗口")

# ============================================
# 3. 定义颜色（RGB 格式）
# ============================================
# RGB 颜色：每个颜色由 红(Red)、绿(Green)、蓝(Blue) 三种光混合而成
# 每种颜色的取值范围是 0 ~ 255
# 0 表示"完全不亮"，255 表示"最亮"

# --- 当前使用的背景颜色 ---
BACKGROUND_COLOR = (135, 206, 235)  # 天蓝色 (R=135, G=206, B=235)

# --- 你可以尝试替换成下面的颜色 ---
# COLOR_SKY_BLUE   = (135, 206, 235)  # 天蓝色
# COLOR_ORANGE      = (255, 165, 0)    # 橙色
# COLOR_GREEN       = (0, 255, 0)      # 亮绿色
# COLOR_PURPLE      = (160, 32, 240)   # 紫色
# COLOR_YELLOW      = (255, 255, 0)    # 黄色
# COLOR_WHITE       = (255, 255, 255)  # 白色
# COLOR_BLACK       = (0, 0, 0)        # 黑色
# COLOR_RED         = (255, 0, 0)      # 红色
# COLOR_BLUE        = (0, 0, 255)      # 蓝色
# COLOR_PINK        = (255, 192, 203)  # 粉色

# 试试把上面 BACKGROUND_COLOR 的值换成其他颜色！

# ============================================
# 4. 游戏主循环（让窗口一直显示）
# ============================================
print("游戏窗口已打开！点击窗口右上角的 × 按钮可以关闭。")
print("窗口大小：{} x {}".format(WIDTH, HEIGHT))
print("背景颜色：RGB{}".format(BACKGROUND_COLOR))

running = True  # 用一个变量来控制游戏是否继续运行

while running:
    # --- 4.1 处理事件（比如点击关闭按钮、按键盘等）---
    for event in pygame.event.get():  # 获取所有等待处理的事件
        if event.type == pygame.QUIT:  # 如果用户点击了关闭按钮（×）
            running = False            # 将 running 设为 False，退出循环
            print("正在关闭游戏... 再见！")

    # --- 4.2 绘制画面 ---
    screen.fill(BACKGROUND_COLOR)  # 用背景颜色填充整个窗口（相当于"刷墙"）

    # --- 4.3 刷新显示 ---
    pygame.display.flip()  # 把画好的内容显示到屏幕上（相当于"翻页"）

# ============================================
# 5. 退出 Pygame
# ============================================
pygame.quit()  # 关闭 Pygame，释放资源
sys.exit()     # 彻底退出程序
print("游戏已关闭。")
