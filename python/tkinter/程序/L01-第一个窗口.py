import tkinter as tk

# ========================================
# 第 1 节：认识 tkinter —— 创建你的第一个窗口
# ========================================

# 1. 创建窗口对象（root = 根窗口）
root = tk.Tk()

# 2. 设置窗口标题
root.title("我的第一个窗口")

# 3. 设置窗口大小（宽 x 高，单位：像素）
root.geometry("500x400")

# 4. 设置背景颜色
root.configure(bg="#e8f5e9")  # 浅绿色

# 5. 启动主循环 —— 让窗口一直显示，等待用户操作
#    这行必须放在代码最后！
root.mainloop()
