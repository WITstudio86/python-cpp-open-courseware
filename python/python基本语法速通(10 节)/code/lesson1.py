# 井号后面的文字叫「注释」，电脑不执行，写给人看

print("######## 热身：print 的六种玩法 ########")
print()

# 1) 输出一句话
print("你好，Python！")

# 2) 一次输出好几样，默认用空格隔开
print("我", "爱", "编程")

# 3) sep 换分隔符
print("我", "爱", "编程", sep="-")

# 4) 直接算数：没有引号的数字会先算再显示
print("100 + 23 =", 100 + 23)
print("2 的 10 次方 =", 2 ** 10)

# 5) 字符串乘法：重复
print("哈" * 8)
print("=" * 28)

# 6) \n 换行  \t 制表符（相当于按一次 Tab）
print("第一行\n第二行")
print("姓名\t年龄\t城市")
print("小明\t13\t上海")

# end="" 表示这次 print 结束时不换行
print("同一行：", end="")
print("A", end="")
print("B", end="")
print("C")

print()
